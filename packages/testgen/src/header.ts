import { createHash } from "node:crypto";
import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

/**
 * Every generated test file says it is generated, from what, and carries the sha-256 of what
 * Atticus wrote (as assistant files do). On the next run a file whose content no longer
 * matches its hash was edited by a person and is left alone unless `--force`; a file without
 * the header was never Atticus's and is kept unless `--force`. The hash covers the file
 * without the header, so writing the header doesn't change it.
 *
 * Comment styles: `#` (Gherkin, YAML), `//` (Java, TypeScript) and, for JSON, which has no
 * comments, a first `"$generated"` property holding the same text.
 */

export const sha256 = (s: string) => createHash("sha256").update(s, "utf8").digest("hex");

export type HeaderStyle = "hash" | "slash" | "json";

const TAG = "atticus-sha256";
const TEXT = (source: string, hash: string) =>
  `Generated by Atticus from ${source}. Edit the source instead: Atticus regenerates this file and keeps hand edits only until --force. ${TAG}: ${hash}`;
const LINE_RE = new RegExp(
  `^(?:#|//) Generated by Atticus from (.+?)\\. .*${TAG}: ([0-9a-f]{64})$`,
);
const JSON_RE = new RegExp(
  `^\\{\\n  "\\$generated": "Generated by Atticus from (.+?)\\. .*${TAG}: ([0-9a-f]{64})",\\n`,
);

export interface GeneratedFile {
  /** Path relative to the folder it is written into, "/"-separated. */
  path: string;
  content: string;
  style: HeaderStyle;
  /** What it was generated from, e.g. openspec/changes/<id>/stories/<story>.md. */
  source: string;
  /** The test case ids the file holds (for the manifest and traceability; not written). */
  cases?: string[];
}

/** The full text of a generated file. Content must end with a newline. */
export function withHeader(f: GeneratedFile): string {
  const hash = sha256(f.content);
  if (f.style === "json") {
    if (!f.content.startsWith("{\n")) throw new Error(`${f.path}: JSON content must be an object`);
    return `{\n  "$generated": "${TEXT(f.source, hash)}",\n${f.content.slice(2)}`;
  }
  return `${f.style === "hash" ? "#" : "//"} ${TEXT(f.source, hash)}\n${f.content}`;
}

/** The header of a whole generated file: its source, hash and the body the hash covers. */
export function readHeader(
  text: string,
): { source: string; hash: string; body: string } | undefined {
  const t = text.replace(/\r\n/g, "\n");
  const j = JSON_RE.exec(t);
  if (j) return { source: j[1]!, hash: j[2]!, body: `{\n${t.slice(j[0].length)}` };
  const nl = t.indexOf("\n");
  const first = nl < 0 ? t : t.slice(0, nl);
  const m = LINE_RE.exec(first);
  if (m) return { source: m[1]!, hash: m[2]!, body: t.slice(nl + 1) };
  return undefined;
}

export type WriteAction =
  "created" | "updated" | "unchanged" | "kept-edited" | "kept-not-generated";

export interface WriteResult {
  path: string;
  action: WriteAction;
  written: boolean;
}

/**
 * Write generated files under `dir`. Idempotent: unchanged files are not touched. A file a
 * person edited, or one Atticus never wrote, is kept unless `force`. Paths may not leave `dir`.
 */
export async function writeGenerated(
  dir: string,
  files: readonly GeneratedFile[],
  o: { force?: boolean; check?: boolean } = {},
): Promise<WriteResult[]> {
  const out: WriteResult[] = [];
  for (const f of files) {
    if (f.path.startsWith("/") || f.path.split("/").includes("..") || /^[A-Za-z]:/.test(f.path))
      throw new Error(`refusing to write outside the target folder: ${f.path}`);
    const full = join(dir, ...f.path.split("/"));
    const text = withHeader(f);
    const current = await readFile(full, "utf8")
      .then((t) => t.replace(/\r\n/g, "\n"))
      .catch(() => undefined);
    let action: WriteAction;
    if (current === undefined) action = "created";
    else if (current === text) action = "unchanged";
    else {
      const h = readHeader(current);
      if (!h) action = o.force ? "updated" : "kept-not-generated";
      else if (sha256(h.body) !== h.hash) action = o.force ? "updated" : "kept-edited";
      else action = "updated";
    }
    const write = !o.check && (action === "created" || action === "updated");
    if (write) {
      await mkdir(dirname(full), { recursive: true });
      const tmp = `${full}.atticus-tmp`;
      await writeFile(tmp, text, "utf8");
      await rename(tmp, full);
    }
    out.push({ path: f.path, action, written: write });
  }
  return out;
}
