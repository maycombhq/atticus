import { cp, mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  acceptProposal,
  checkedProposals,
  proposalRelOf,
  QuestionDraft,
  QuestionError,
  raiseQuestions,
  readQuestion,
} from "../src/index.js";

/**
 * The assistant proposes, a person confirms (ADR 0144, Q5): a proposed answer beside the
 * question, in proposals/questions/<id>.yaml; every citation checked (the file is in the repo, the
 * line is there, the quote is on it) before anyone sees it; a person's acceptance makes it their
 * answer, recorded as theirs. Fixtures: fixtures/question-proposals.
 */

const FIX = join(dirname(fileURLToPath(import.meta.url)), "../../../fixtures/question-proposals");
const AT = "2026-10-31T12:00:00.000Z";

async function estate(proposal?: string) {
  const root = await mkdtemp(join(tmpdir(), "atticus-proposals-"));
  await mkdir(join(root, "org-pack"), { recursive: true });
  await cp(join(FIX, "workspace"), join(root, "workspace"), { recursive: true });
  const q = (
    await raiseQuestions(
      root,
      [
        QuestionDraft.parse({
          question: "Is docs/playground.js generated or part of the product?",
          options: [
            { label: "Generated", means: "nobody edits it", changes: "the scan leaves it out" },
            { label: "Product", means: "it ships", changes: "the scan reads it" },
          ],
          evidence: ["docs/playground.js:1"],
        }),
      ],
      {
        step: "scan-survey",
        repo: "forge-notes",
        command: "atticus scan survey forge-notes",
        rerun: "atticus scan survey forge-notes --force",
        at: AT,
      },
    )
  ).raised[0]!;
  if (proposal) {
    const f = join(root, ...proposalRelOf(root, q.id).split("/"));
    await mkdir(dirname(f), { recursive: true });
    await writeFile(f, await readFile(join(FIX, "proposals", `${proposal}.yaml`), "utf8"));
  }
  return { root, q };
}

describe("a proposed answer, checked before it is shown (ADR 0144, Q5)", () => {
  it("lives beside the question, in proposals/questions/<id>.yaml", async () => {
    const { root, q } = await estate();
    expect(proposalRelOf(root, q.id)).toBe(`proposals/questions/${q.id}.yaml`);
  });

  it("keeps a proposal whose every citation is on its line", async () => {
    const { root, q } = await estate("good");
    const got = await checkedProposals(root);
    expect(got.map((p) => [p.id, p.ok, p.problems])).toEqual([[q.id, true, []]]);
    expect(got[0]!.proposal?.answer).toEqual({ option: 1 });
  });

  it("refuses a quote that isn't on its line", async () => {
    const { root } = await estate("bad-quote");
    const [p] = await checkedProposals(root);
    expect(p!.ok).toBe(false);
    expect(p!.problems).toEqual([
      'docs/playground.js:2 doesn\'t say "Generated by the docs build".',
    ]);
  });

  it("refuses a line past the end, a file that isn't there and a path out of the repo", async () => {
    const { root } = await estate("bad-line");
    const [p] = await checkedProposals(root);
    expect(p!.problems).toEqual([
      "docs/playground.js has 2 lines, so there is no line 40.",
      "docs/missing.js isn't in forge-notes.",
      "../../outside.txt leaves the repo: cite a file in it.",
    ]);
  });

  it("refuses an option the question doesn't have", async () => {
    const { root } = await estate("bad-option");
    const [p] = await checkedProposals(root);
    expect(p!.problems).toEqual(["There is no option 3: pick 1 to 2."]);
  });

  it("drops a proposal for a question already answered: nothing to propose", async () => {
    const { root, q } = await estate("good");
    await acceptProposal(root, q.id, { by: "pat", at: AT });
    const [p] = await checkedProposals(root);
    expect(p).toMatchObject({ id: q.id, ok: false, stale: true });
  });

  it("a person accepting it makes it their answer, recorded as by them", async () => {
    const { root, q } = await estate("good");
    const r = await acceptProposal(root, q.id, { by: "pat", at: AT });
    expect(r.question.answer).toMatchObject({ option: 1, by: "pat", at: AT });
    expect((await readQuestion(root, q.id))?.state).toBe("answered");
  });

  it("refuses to accept a proposal that fails its check, or none", async () => {
    const bad = await estate("bad-quote");
    await expect(acceptProposal(bad.root, bad.q.id, { by: "pat", at: AT })).rejects.toThrow(
      QuestionError,
    );
    expect((await readQuestion(bad.root, bad.q.id))?.state).toBe("open");
    const none = await estate();
    await expect(acceptProposal(none.root, none.q.id, { by: "pat", at: AT })).rejects.toThrow(
      /no proposed answer/,
    );
  });
});
