import { copyFile, mkdir, readdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";

/**
 * Beta.27 review: one definition of "planning files a person wrote", read by the stories stage
 * (which refuses to replace them unless forced), the plan gate, `atticus next`, At a glance and
 * the Stories page, so none of them offers a step another refuses.
 */

/** The first words of every planning file Atticus writes; a file without them a person wrote. */
export const GENERATED_MARK = "<!-- Generated by atticus plan";

/** The planning files the stories stage writes, which a person may write instead. */
export const PLANNING_FILES = ["stories.md", "tasks.md", "requests.md"] as const;

/**
 * Whether a planning file's text is one Atticus wrote: its first words are the generated mark.
 * Beta.27 review: a UTF-8 byte-order mark and whitespace or blank lines before it (an editor on
 * Windows saving the file) don't make it a person's.
 */
export const isGenerated = (text: string): boolean =>
  text.replace(/^\uFEFF/, "").trimStart().startsWith(GENERATED_MARK);

/** Of `rels` (relative to the change folder `dir`), those that exist without the generated mark. */
export async function personWritten(dir: string, rels: readonly string[]): Promise<string[]> {
  const own: string[] = [];
  for (const rel of rels) {
    const text = await readFile(join(dir, ...rel.split("/")), "utf8").catch(() => undefined);
    if (text !== undefined && !isGenerated(text)) own.push(rel);
  }
  return own;
}

/**
 * Beta.27 review: before a forced draft replaces files a person wrote, a copy of each, in the
 * change folder's `stage/<stage>-by-person/<n>/` (a new n each time, as the stage loop keeps a
 * person's edits). Returns that folder, metarepo-relative (`rel` is the change folder's), or
 * nothing when there was nothing to keep.
 */
export async function keepPersonWritten(
  dir: string,
  rel: string,
  stage: string,
  files: readonly string[],
): Promise<string | undefined> {
  if (!files.length) return undefined;
  const base = join(dir, "stage", `${stage}-by-person`);
  const taken = (await readdir(base).catch(() => [] as string[]))
    .map((n) => Number(n))
    .filter((n) => Number.isInteger(n) && n > 0);
  const n = Math.max(0, ...taken) + 1;
  for (const f of files) {
    const dest = join(base, String(n), ...f.split("/"));
    await mkdir(dirname(dest), { recursive: true });
    await copyFile(join(dir, ...f.split("/")), dest);
  }
  return `${rel}/stage/${stage}-by-person/${n}/`;
}

/** The change's planning files a person wrote (stories.md, tasks.md, requests.md). */
export const personWrittenPlanning = (dir: string): Promise<string[]> =>
  personWritten(dir, PLANNING_FILES);

/** Whether a stage is the one that writes the planning files: its artifacts are stories or tasks. */
export const writesPlanning = (step: { artifacts: readonly string[] }): boolean =>
  step.artifacts.includes("stories") || step.artifacts.includes("tasks");

/**
 * A stage's work is done: its loop says so, or (`person`) a person wrote what it writes and the
 * stage never ran.
 */
export const stageWorkDone = (state: string): boolean => state === "done" || state === "person";

/** A stage that hasn't run and isn't running: not started yet, or (`skipped`) the change passed it. */
export const stageIdle = (state: string): boolean => state === "not-started" || state === "skipped";
