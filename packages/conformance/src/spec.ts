function context(sourceDir: string): DocContext {
  const docs = new Map<string, SchemaDocs>();
  for (const f of readdirSync(sourceDir)
    .filter((n) => n.endsWith(".ts"))
    .sort())
    for (const [k, v] of docComments(readFileSync(join(sourceDir, f), "utf8")))
      if (!docs.has(k)) docs.set(k, v);
  const named = new Map<unknown, string>();
  for (const [k, v] of Object.entries(core))
    if (v && typeof v === "object" && "_zod" in v && !named.has(v)) named.set(v, k);
  return { named, docs };
}

const schemaOf = (name: string) => (core as unknown as Record<string, unknown>)[name];

function contractPage(c: Contract, ctx: DocContext): string {
  const out: string[] = [
    GENERATED_NOTE,
    "",
    `# ${c.title}`,
    "",
    ...c.intro.flatMap((p) => [p, ""]),
  ];
  out.push(`Specification version ${SPEC_VERSION}.`, "", "| Version | Value |", "| --- | --- |");
  for (const [k, v] of c.versions) out.push(`| ${k} | ${String(v)} |`);
  out.push("");
  if (c.extra) out.push(...c.extra(ctx), "");
  for (const s of c.sections) {
    const schema = schemaOf(s.name);
    if (!schema) continue;
    out.push(`## ${s.name}`, "");
    const doc = ctx.docs.get(s.name)?.doc;
    if (s.where) {
      const [path, note] = s.where.split(/ (?=\()/);
      out.push(`Where: \`${path}\`${note ? ` ${note}` : ""}.`, "");
    }
    if (doc) out.push(doc, "");
    const rows = fieldRows(schema, ctx, s.name, c.id === "C1" ? { skip: new Set(COMMON) } : {});
    out.push(rows.length > 0 ? fieldTable(rows) : "No fields.", "");
  }
  return (
    out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd() + "\n"
  );
}

