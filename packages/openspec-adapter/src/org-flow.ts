/**
 * The org-flow workflow schema, version 2 (ADR 0006 addendum, 2026-10-25): OpenSpec's own schema
 * format, written into the metarepo at openspec/schemas/org-flow/. Its artifacts are the files
 * Atticus 2's stages write, in OpenSpec's model, in the order the stages run:
 *
 *   proposal (feature stage) → design (architecture stage) → stories → specs, tasks (stories stage)
 *
 * so `openspec status` and Atticus never disagree about what is done. The specs are OpenSpec
 * deltas generated from the stories' acceptance criteria; `openspec validate --strict` gates the
 * stories stage and the hand-off, and `openspec archive` merges them into openspec/specs/.
 *
 * Files Atticus keeps beside them (brief.md, feature.yaml, feature.md, target-flows/, stories/,
 * knowledge.yaml, needs.*, stage/, review/) are not artifacts; OpenSpec ignores them. Version 1
 * listed Atticus 1's interfaces, mappings, data and snow, which Atticus 2 never writes.
 *
 * Each artifact's instruction is what the stage that writes it reads first (through `openspec
 * instructions`), with openspec/config.yaml's context and rules; an organisation changes them
 * through the org pack (process/), which regenerates this folder. Nobody edits it by hand.
 */
export const ORG_FLOW = "org-flow";
/** The schema's version: 2 since Atticus 2's artifacts (ADR 0006 addendum, 2026-10-25). */
export const ORG_FLOW_VERSION = 2;

/** Atticus 2's stages, each writing one or more org-flow artifacts. */
export type OrgFlowStage = "feature" | "architecture" | "stories";

interface ArtifactDef {
  id: string;
  generates: string;
  description: string;
  requires: string[];
  /** The Atticus stage that writes the artifact. */
  stage: OrgFlowStage;
  instruction: string;
  template: string;
}

