/** The schema.yaml content, as data. */
export function orgFlowSchema() {
  return {
    name: ORG_FLOW,
    version: ORG_FLOW_VERSION,
    description:
      "Atticus 2 change flow - proposal (feature) → design (architecture) → stories → specs, tasks",
    artifacts: ARTIFACTS.map((a) => ({
      id: a.id,
      generates: a.generates,
      description: a.description,
      template: `${a.id}.md`,
      instruction: a.instruction + "\n",
      requires: a.requires,
    })),
    apply: {
      requires: ["tasks"],
      tracks: "tasks.md",
      instruction:
        "Run one task at a time with atticus task <change> <task>, in the change's worktrees, in task order. Tick each task in tasks.md when its tests pass. Stop and ask when a task conflicts with the specs or design.\n",
    },
  };
}

export const ORG_FLOW_ARTIFACTS = ARTIFACTS.map((a) => a.id);

/** The stage that writes each org-flow artifact: `openspec status` → Atticus's next stage. */
export const ARTIFACT_STAGE: Readonly<Record<string, OrgFlowStage>> = Object.fromEntries(
  ARTIFACTS.map((a) => [a.id, a.stage]),
);

/** The artifacts a stage writes, in schema order. */
export const artifactsOfStage = (stage: OrgFlowStage): string[] =>
  ARTIFACTS.filter((a) => a.stage === stage).map((a) => a.id);

/** Version 1's artifacts that version 2 drops (Atticus 1's): their templates are removed. */
export const ORG_FLOW_V1_ONLY = ["interfaces", "mappings", "data", "snow"] as const;

/** The org-flow schema version a metarepo has installed, or undefined when it has none. */
export async function orgFlowVersionOf(root: string): Promise<number | undefined> {
  const text = await readFile(
    join(root, "openspec", "schemas", ORG_FLOW, "schema.yaml"),
    "utf8",
  ).catch(() => undefined);
  if (text === undefined) return undefined;
  try {
    const v = (parse(text) as { version?: unknown } | null)?.version;
    return typeof v === "number" ? v : 1;
  } catch {
    return 1;
  }
}

/** Write openspec/schemas/org-flow/ (schema.yaml and templates/). Overwrites: the folder is generated. */
export async function writeOrgFlowSchema(root: string): Promise<string> {
  const dir = join(root, "openspec", "schemas", ORG_FLOW);
  await mkdir(join(dir, "templates"), { recursive: true });
  const header =
    "# Generated by Atticus from the org pack. Do not edit; change org-pack/process and regenerate.\n";
  await writeFile(
    join(dir, "schema.yaml"),
    header + stringify(orgFlowSchema(), { lineWidth: 0 }),
    "utf8",
  );
  for (const a of ARTIFACTS) {
    await writeFile(join(dir, "templates", `${a.id}.md`), a.template, "utf8");
  }
  // Version 1's templates for the artifacts version 2 no longer has.
  for (const id of ORG_FLOW_V1_ONLY) await rm(join(dir, "templates", `${id}.md`), { force: true });
  return dir;
}

/** Set the default schema in openspec/config.yaml, keeping the rest of the file and its comments. */
export async function setDefaultSchema(root: string, schema: string): Promise<void> {
  const path = join(root, "openspec", "config.yaml");
  let text = "";
  try {
    text = await readFile(path, "utf8");
  } catch {
    // no config yet
  }
  const doc = parseDocument(text);
  doc.set("schema", schema);
  await writeFile(path, doc.toString({ lineWidth: 0 }), "utf8");
}
