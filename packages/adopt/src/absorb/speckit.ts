/**
 * Spec Kit pieces in Atticus terms: a constitution's principles (each becomes a
 * constitution-layer rule draft), the feature-spec template (an org-pack change template),
 * and a feature spec (an OpenSpec living spec, for a one-off import or a read-only reference).
 */

export interface Principle {
  title: string;
  body: string;
  line: number;
  nonNegotiable: boolean;
}

export interface ConstitutionParts {
  principles: Principle[];
  /** Other second-level sections (Additional Constraints, Governance...). */
  sections: { title: string; body: string; line: number }[];
  /** Generated by Atticus's own hand-down: nothing to absorb. */
  generatedByAtticus: boolean;
}

export function parseConstitution(text: string): ConstitutionParts {
  const lines = text.split("\n");
  const out: ConstitutionParts = {
    principles: [],
    sections: [],
    generatedByAtticus: /Generated from the Atticus constitution/.test(text),
  };
  let h2: string | undefined;
  let current: { title: string; body: string[]; line: number; principle: boolean } | undefined;
  const flush = () => {
    if (!current) return;
    const body = current.body.join("\n").trim();
    if (current.principle)
      out.principles.push({
        title: current.title
          .replace(/^[IVXLCDM]+\.\s*/, "")
          .replace(/\s*\(NON-NEGOTIABLE\)\s*$/i, ""),
        body,
        line: current.line,
        nonNegotiable: /NON-NEGOTIABLE/i.test(current.title),
      });
    else if (body) out.sections.push({ title: current.title, body, line: current.line });
    current = undefined;
  };
  lines.forEach((l, i) => {
    const m2 = /^##\s+(.+)$/.exec(l);
    const m3 = /^###\s+(.+)$/.exec(l);
    if (m2) {
      flush();
      h2 = m2[1]!.trim();
      if (!/principles/i.test(h2)) current = { title: h2, body: [], line: i + 1, principle: false };
      return;
    }
    if (m3 && h2 && /principles/i.test(h2)) {
      flush();
      current = { title: m3[1]!.trim(), body: [], line: i + 1, principle: true };
      return;
    }
    if (/^\*\*Version\*\*/.test(l)) return;
    current?.body.push(l);
  });
  flush();
  return out;
}

/** Spec Kit's spec template as an org-pack change template: headings kept, placeholders as comments. */
export function changeTemplateFrom(id: string, name: string, text: string): string {
  const body: string[] = [];
  for (const raw of text.split("\n")) {
    const l = raw
      .replace(/\[FEATURE NAME\]|\[FEATURE\]/g, "{{title}}")
      .replace(/\[DATE\]/g, "{{date}}")
      .replace(/\[###-feature-name\]/g, "{{id}}");
    if (/^#\s/.test(l)) body.push("# {{title}}", "");
    else if (/^#{2,6}\s/.test(l)) body.push(l.replace(/\s*\*\([^)]*\)\*\s*$/, ""), "");
    else if (l.trim() && !/^\*\*(Feature Branch|Created|Status)\*\*/.test(l))
      body.push(`<!-- ${l.trim().replace(/-->/g, "")} -->`, "");
  }
  const skeleton = body
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  return `---\nid: ${id}\nname: ${name}\nchangeType: feature\ndescription: Drafted by atticus absorb from a Spec Kit spec template.\n---\n${skeleton}\n`;
}

/**
 * A Spec Kit feature spec as an OpenSpec spec: each functional requirement (FR-nnn) becomes a
 * requirement, each acceptance scenario (Given/When/Then) a scenario of the first one.
 */
export function openSpecFrom(
  feature: string,
  text: string,
): { spec: string; requirements: number } {
  const title = /^#\s+Feature Specification:\s*(.+)$/m.exec(text)?.[1]?.trim() ?? feature;
  const reqs = [...text.matchAll(/^\s*-\s+\*\*(FR-\d+)\*\*:\s*(.+)$/gm)].map((m) => ({
    id: m[1]!,
    text: m[2]!.trim().replace(/\bMUST\b/, "SHALL"),
  }));
  const scenarios = [
    ...text.matchAll(/\*\*Given\*\*\s*(.+?),\s*\*\*When\*\*\s*(.+?),\s*\*\*Then\*\*\s*(.+)$/gm),
  ].map((m, i) => ({ n: i + 1, given: m[1]!, when: m[2]!, then: m[3]!.trim() }));
  const out = [
    `# ${feature} Specification`,
    "",
    "## Purpose",
    "",
    title,
    "",
    "## Requirements",
    "",
  ];
  reqs.forEach((r, i) => {
    out.push(`### Requirement: ${r.id}`, "", r.text, "");
    const mine = i === 0 ? scenarios : [];
    for (const s of mine)
      out.push(
        `#### Scenario: Acceptance scenario ${s.n}`,
        "",
        `- **GIVEN** ${s.given}`,
        `- **WHEN** ${s.when}`,
        `- **THEN** ${s.then}`,
        "",
      );
    if (!mine.length)
      out.push(
        `#### Scenario: ${r.id} holds`,
        "",
        `- **WHEN** the feature is used`,
        `- **THEN** ${r.text.replace(/^System SHALL\s*/i, "the system does this: ")}`,
        "",
      );
  });
  return { spec: `${out.join("\n").trimEnd()}\n`, requirements: reqs.length };
}
