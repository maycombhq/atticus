type Options = typeof OPTIONS;

/**
 * The commands that read a flag the other way round from the rest, by their first words (after a
 * leading `legacy`): critic's --resume is a switch (elsewhere it names a run), and ci snippet's
 * --write and bench stories' --draft name a folder and a file (elsewhere each is a switch).
 */
const BY_COMMAND: { words: string[]; options: ParseArgsOptionsConfig }[] = [
  { words: ["critic"], options: { resume: { type: "boolean" } } },
  { words: ["ci", "snippet"], options: { write: { type: "string" } } },
  { words: ["bench", "stories"], options: { draft: { type: "string" } } },
];

const read = (argv: readonly string[], options: ParseArgsOptionsConfig) =>
  parseArgs({ args: [...argv], allowPositionals: true, options, strict: false });

/** The options as the command a line names reads them: OPTIONS, with its own types where it has them. */
export function optionsFor(argv: readonly string[]): Options {
  const words = read(argv, OPTIONS).positionals;
  const named = words[0] === "legacy" ? words.slice(1) : words;
  const own = BY_COMMAND.find((c) => c.words.every((w, i) => named[i] === w));
  return (own ? { ...OPTIONS, ...own.options } : OPTIONS) as Options;
}

/** A command line's positional words, as the command line reads them (an option's value isn't one). */
export function commandWords(argv: readonly string[]): string[] {
  return read(argv, optionsFor(argv)).positionals;
}
