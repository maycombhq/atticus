/**
 * Atticus 2 as an OpenSpec citizen (ADR 0006 addendum, 2026-10-25): the files of the org-flow v2
 * schema that Atticus generates rather than a drafter writing them twice. `proposal.md` from the
 * brief and feature.yaml; `specs/<capability>/spec.md` as OpenSpec deltas from the stories'
 * acceptance criteria, with no model call: one capability per flow, a requirement per story
 * (SHALL), a scenario per criterion (GIVEN/WHEN/THEN). A capability already in openspec/specs is
 * MODIFIED, carrying its archived scenarios (OpenSpec refuses a MODIFIED that drops one); a
 * removed flow's requirements are REMOVED. `openspec validate --strict` is the stories stage's
 * gate; `openspec archive` then merges the deltas into openspec/specs/.
 */

export const SPEC_MARK =
  "<!-- Generated by atticus plan stories from the stories' acceptance criteria. Edit the stories and run the stage again. -->";
export const PROPOSAL_MARK =
  "<!-- Generated by atticus change feature from brief.md and feature.yaml. Edit feature.yaml and run the stage again. -->";

/** OpenSpec warns (a failure under --strict) on a requirement text over 500 characters. */
const MAX_REQUIREMENT = 480;

const sentence = (s: string) => (/[.!?]$/.test(s.trim()) ? s.trim() : `${s.trim()}.`);
const bare = (s: string) => s.trim().replace(/[.\s]+$/, "");
const cap = (s: string) => (s ? `${s[0]!.toUpperCase()}${s.slice(1)}` : s);
const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
const clip = (s: string, n: number) => {
  if (s.length <= n) return s;
  const cut = s.slice(0, n - 1);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(" "), n / 2)).trimEnd()}…`;
};

// ------------------------------------------------------------------ the specs openspec has

export interface ExistingScenario {
  name: string;
  rawText: string;
}

export interface ExistingRequirement {
  name: string;
  text: string;
  scenarios: ExistingScenario[];
}

/** A capability in openspec/specs, as `openspec show <spec> --type spec --json` gives it. */
export interface ExistingSpec {
  id: string;
  /** The flow its Purpose names (`Behaviour of flow \`<id>\``), when Atticus wrote it. */
  flow?: string;
  requirements: ExistingRequirement[];
}

const FLOW_IN = /flow `([^`]+)`/i;

/**
 * The OpenSpec root of a metarepo or adopted repo: the folder whose `openspec/` holds the changes
 * (`.atticus` in a repo adopted in place), or undefined when it has no openspec/config.yaml (not
 * set up with OpenSpec, as in most unit-test roots).
 */
export function openspecRootOf(root: string): string | undefined {
  const dir = openspecDirOf(root);
  if (basename(dir) !== "openspec") return undefined;
  return existsSync(join(dir, "config.yaml")) ? dirname(dir) : undefined;
}

/** The metarepo's OpenSpec (the pinned CLI over its openspec/), or undefined when it has none. */
export function metarepoOpenSpec(root: string): OpenSpec | undefined {
  const r = openspecRootOf(root);
  return r ? createOpenSpec({ root: r }) : undefined;
}

/** The capabilities in openspec/specs, through `openspec list --specs` and `show` (no file reading). */
export async function readExistingSpecs(os: OpenSpec): Promise<ExistingSpec[]> {
  const out: ExistingSpec[] = [];
  for (const s of await os.listSpecs()) {
    const d = await os.showSpec(s.id);
    const flow = FLOW_IN.exec(d.overview ?? "")?.[1];
    out.push({
      id: s.id,
      ...(flow ? { flow } : {}),
      requirements: d.requirements.map((r) => ({
        name: r.name,
        text: r.text,
        scenarios: r.scenarios.map((x) => ({ name: x.name, rawText: x.rawText })),
      })),
    });
  }
  return out;
}

// ------------------------------------------------------------------ capabilities

/**
 * A flow's capability, named stably: the capability openspec/specs already has for the flow (its
 * Purpose names it), else the flow's name part (`place-order` of `forge-orders.place-order`),
 * prefixed with its repo when the estate has more than one repo and the name doesn't start with
 * it already.
 */
export function capabilityOf(
  flow: string,
  repo: string,
  o: { existing?: ExistingSpec[]; multiRepo: boolean },
): string {
  const had = o.existing?.find((s) => s.flow === flow);
  if (had) return had.id;
  const part = slug(flow.split(".").slice(1).join("-") || flow);
  const r = slug(repo);
  const name = o.multiRepo && !part.startsWith(r) ? `${r}-${part}` : part;
  return name.slice(0, 80).replace(/-+$/, "") || r;
}

// ------------------------------------------------------------------ deltas

export interface DeltaRequirement {
  name: string;
  text: string;
  /** Rendered scenario blocks, "#### Scenario: …" and its bullets. */
  scenarios: { name: string; body: string }[];
}

export interface SpecDelta {
  capability: string;
  flow: string;
  /** For a capability openspec/specs doesn't have yet: its Purpose. */
  purpose?: string;
  added: DeltaRequirement[];
  modified: DeltaRequirement[];
  removed: { name: string; reason: string }[];
}

/** A criterion as OpenSpec's GIVEN/WHEN/THEN bullets, and a scenario name from its outcome. */
export function scenarioOf(text: string): { name: string; body: string } {
  const t = bare(text);
  const m =
    /^\s*given\s+(.+?),?\s+when\s+(.+?),?\s+then\s+(.+)$/is.exec(t) ??
    /^\s*()when\s+(.+?),?\s+then\s+(.+)$/is.exec(t);
  const given = m?.[1]?.trim();
  const when = m?.[2]?.trim();
  const then = (m?.[3] ?? t).trim();
  const body = [
    ...(given ? [`- **GIVEN** ${given}`] : []),
    `- **WHEN** ${when ?? "the flow runs"}`,
    `- **THEN** ${then}`,
  ].join("\n");
  return { name: cap(clip(then.replace(/\s+/g, " "), 100)), body };
}

const aOrAn = (w: string) => (/^[aeiou]/i.test(w.trim()) ? "an" : "a");

/** The requirement's words: the story's title and its statement with SHALL, then its flow. */
function requirementText(change: string, s: DeltaStory, w: StoryWords | undefined): string {
  const statement = w
    ? `${sentence(w.title)} The system SHALL give ${aOrAn(w.asA)} ${bare(w.asA)} ${bare(w.iWant)}, so that ${sentence(w.soThat)}`
    : `The system SHALL do what flow ${s.flow} (${s.name}) does once the change is in.`;
  const trailer = `Flow: \`${s.flow}\`; story ${s.id} of ${change}.`;
  return `${clip(statement, MAX_REQUIREMENT - trailer.length - 2)}\n\n${trailer}`;
}

/** The story's criteria in task order, each once (B-once: a criterion is written on one task). */
function criteriaOf(s: DeltaStory, w: StoryWords | undefined): StoryCriterion[] {
  if (!w) return [];
  return s.tasks.flatMap((t) => w.tasks.find((x) => x.id === t.id)?.criteria ?? []);
}

/** Unique scenario names within a requirement: a repeated outcome gets "(2)", "(3)". */
function uniqueNames(xs: { name: string; body: string }[]): { name: string; body: string }[] {
  const seen = new Map<string, number>();
  return xs.map((x) => {
    const n = (seen.get(x.name.toLowerCase()) ?? 0) + 1;
    seen.set(x.name.toLowerCase(), n);
    return n === 1 ? x : { ...x, name: `${x.name} (${n})` };
  });
}

/**
 * The spec deltas of a change's stories, deterministically: one per flow. A story whose flow's
 * capability openspec/specs has, with a requirement for the flow, MODIFIES it (its scenarios kept,
 * a scenario of the same name replaced); otherwise it is ADDED. A removed flow REMOVES the
 * capability's requirements. A story with no criteria yet has no requirement (OpenSpec needs a
 * scenario), and neither has a removed flow openspec/specs never had.
 */
export function specDeltas(
  change: string,
  stories: DeltaStory[],
  answer: StoriesAnswer,
  o: { existing?: ExistingSpec[]; multiRepo: boolean },
): SpecDelta[] {
  const out: SpecDelta[] = [];
  for (const s of stories) {
    const capability = capabilityOf(s.flow, s.repo, o);
    const had = o.existing?.find((x) => x.id === capability);
    const w = answer.stories.find((x) => x.id === s.id);
    const prior =
      had?.requirements.find((r) => r.text.includes(`Flow: \`${s.flow}\``)) ??
      had?.requirements.find((r) => r.name.toLowerCase() === s.name.toLowerCase());
    const d: SpecDelta = {
      capability,
      flow: s.flow,
      ...(had
        ? {}
        : {
            purpose: `Behaviour of flow \`${s.flow}\` (${bare(s.name)})${s.entry ? `, started by ${s.entry}` : ""}. Atticus writes it from the stories of each change that touches the flow.`,
          }),
      added: [],
      modified: [],
      removed: [],
    };
    if (s.change === "remove") {
      for (const r of had?.requirements ?? [])
        d.removed.push({ name: r.name, reason: `Flow ${s.flow} is removed by ${change}.` });
    } else {
      const fresh = uniqueNames(criteriaOf(s, w).map((c) => scenarioOf(c.text)));
      if (fresh.length) {
        const text = requirementText(change, s, w);
        if (prior) {
          // The archived scenarios in their order, one of the same name replaced in place (a
          // criterion whose outcome reads the same), then the new ones. OpenSpec refuses a
          // MODIFIED that drops a scenario, so none is dropped: a criterion whose outcome changed
          // is a new scenario beside the old, for a person to retire in the specs.
          const byName = new Map(fresh.map((x) => [x.name.toLowerCase(), x]));
          const kept = prior.scenarios.map(
            (x) => byName.get(x.name.toLowerCase()) ?? { name: x.name, body: x.rawText.trim() },
          );
          const had = new Set(prior.scenarios.map((x) => x.name.toLowerCase()));
          const added = fresh.filter((x) => !had.has(x.name.toLowerCase()));
          d.modified.push({ name: prior.name, text, scenarios: [...kept, ...added] });
        } else d.added.push({ name: bare(s.name), text, scenarios: fresh });
      }
    }
    if (d.added.length + d.modified.length + d.removed.length) out.push(d);
  }
  // Two stories on one capability (a flow named twice): their requirements in one file.
  const merged: SpecDelta[] = [];
  for (const d of out) {
    const m = merged.find((x) => x.capability === d.capability);
    if (!m) merged.push(d);
    else {
      m.added.push(...d.added);
      m.modified.push(...d.modified);
      m.removed.push(...d.removed);
    }
  }
  return merged;
}

const requirementBlock = (r: DeltaRequirement) =>
  [
    `### Requirement: ${r.name}`,
    r.text,
    "",
    ...r.scenarios.flatMap((x) => [`#### Scenario: ${x.name}`, x.body, ""]),
  ].join("\n");

/** One capability's delta file, in OpenSpec's format. */
export function renderSpecDelta(d: SpecDelta): string {
  const lines = [SPEC_MARK];
  if (d.purpose) lines.push("## Purpose", "", d.purpose, "");
  if (d.added.length) lines.push("## ADDED Requirements", "", ...d.added.map(requirementBlock));
  if (d.modified.length)
    lines.push("## MODIFIED Requirements", "", ...d.modified.map(requirementBlock));
  if (d.removed.length)
    lines.push(
      "## REMOVED Requirements",
      "",
      ...d.removed.flatMap((r) => [`### Requirement: ${r.name}`, `**Reason**: ${r.reason}`, ""]),
    );
  return `${lines.join("\n").trimEnd()}\n`;
}

/** The files the deltas are, relative to the change folder. */
export const specFiles = (deltas: SpecDelta[]): Record<string, string> =>
  Object.fromEntries(deltas.map((d) => [`specs/${d.capability}/spec.md`, renderSpecDelta(d)]));

/**
 * Write the deltas into the change's specs/, removing the spec files Atticus generated earlier
 * that this run no longer writes. A spec file a person wrote (no mark) is kept as it is.
 */
export async function writeSpecFiles(
  dir: string,
  files: Record<string, string>,
): Promise<string[]> {
  const specs = join(dir, "specs");
  for (const c of await readdir(specs).catch(() => [] as string[])) {
    const f = join(specs, c, "spec.md");
    if (files[`specs/${c}/spec.md`] !== undefined) continue;
    const t = await readFile(f, "utf8").catch(() => undefined);
    if (t?.startsWith(SPEC_MARK)) await rm(join(specs, c), { recursive: true, force: true });
  }
  const written: string[] = [];
  for (const [rel, text] of Object.entries(files)) {
    const f = join(dir, ...rel.split("/"));
    const had = await readFile(f, "utf8").catch(() => undefined);
    if (had !== undefined && !had.startsWith(SPEC_MARK)) continue;
    await mkdir(dirname(f), { recursive: true });
    await writeFileAtomic(f, text);
    written.push(rel);
  }
  // OpenSpec refuses skip_specs beside spec files, and a change with none needs it.
  await setSkipSpecs(dir, Object.keys(files).length === 0);
  return written;
}

/** Set or clear `skip_specs` in the change's .openspec.yaml, keeping the rest of the file. */
async function setSkipSpecs(dir: string, skip: boolean): Promise<void> {
  const f = join(dir, ".openspec.yaml");
  const text = await readFile(f, "utf8").catch(() => undefined);
  if (text === undefined) return;
  const doc = parseDocument(text);
  if (Boolean(doc.get("skip_specs")) === skip) return;
  if (skip) doc.set("skip_specs", true);
  else doc.delete("skip_specs");
  await writeFile(f, doc.toString({ lineWidth: 0 }), "utf8");
}

// ------------------------------------------------------------------ proposal

/** The brief's problem: the paragraph under a Problem or Why heading, else its first paragraph. */
function briefWhy(brief: string): string {
  const text = brief.replace(/\r\n/g, "\n").replace(/<!--[\s\S]*?-->/g, "");
  const under =
    /^#{1,3}\s*(?:problem|why|the problem|background)\b[^\n]*\n+([\s\S]*?)(?=\n#{1,3}\s|$)/im.exec(
      text,
    )?.[1];
  const paras = (under ?? text.replace(/^#[^\n]*\n/gm, ""))
    .split(/\n\s*\n/)
    .map((p) => p.replace(/\s+/g, " ").trim())
    .filter((p) => p && !p.startsWith("|"));
  return paras[0] ?? "";
}

export interface ProposalCapability {
  capability: string;
  flow: string;
  name: string;
  op: "ADDED" | "MODIFIED" | "REMOVED";
}

/**
 * proposal.md from the brief and the feature placed against the estate: Why (the brief's
 * problem; OpenSpec asks for 50 to 1000 characters), What Changes (the summary, each flow changed,
 * each new flow), Capabilities (once the stories stage has the spec deltas; until then the flows
 * that will be), Impact (the repos and the gaps) and Open questions.
 */
export function renderProposal(
  title: string,
  p: FeaturePlacement,
  brief: string,
  o: { repoOf?: (flow: string) => string | undefined; capabilities?: ProposalCapability[] } = {},
): string {
  let why = briefWhy(brief) || p.summary;
  if (why.length < 60) why = `${sentence(why)} ${p.summary}`.trim();
  why = clip(why, 950);
  const changed = p.flows.filter((f) => f.how === "changed");
  const repos = [
    ...new Set([
      ...changed.flatMap((f) => (o.repoOf?.(f.id) ? [o.repoOf(f.id)!] : [])),
      ...p.newFlows.map((f) => f.repo),
    ]),
  ].sort();
  const caps = o.capabilities ?? [];
  const lines = [
    PROPOSAL_MARK,
    `# Proposal: ${title}`,
    "",
    "## Why",
    "",
    why,
    "",
    "## What Changes",
    "",
    `- ${sentence(p.summary.replace(/\s+/g, " "))}`,
    ...changed.map((f) => `- Changes flow \`${f.id}\`: ${sentence(f.why.replace(/\s+/g, " "))}`),
    ...p.newFlows.map((f) => `- New flow in ${f.repo}: ${bare(f.name)}.`),
    "",
    "## Capabilities",
    "",
  ];
  if (caps.length) {
    const added = caps.filter((c) => c.op === "ADDED");
    const other = caps.filter((c) => c.op !== "ADDED");
    if (added.length)
      lines.push(
        "### New Capabilities",
        ...added.map((c) => `- \`${c.capability}\`: flow \`${c.flow}\` (${bare(c.name)})`),
        "",
      );
    if (other.length)
      lines.push(
        "### Modified Capabilities",
        ...other.map(
          (c) =>
            `- \`${c.capability}\`: flow \`${c.flow}\` (${bare(c.name)})${c.op === "REMOVED" ? ", removed" : ""}`,
        ),
        "",
      );
  } else
    lines.push(
      "The stories stage names them: one capability per flow the change adds or changes, in specs/<capability>/spec.md.",
      "",
    );
  lines.push(
    "## Impact",
    "",
    repos.length ? `- Repos: ${repos.join(", ")}.` : "- Repos: not placed yet.",
    ...p.flows.filter((f) => f.how === "read").map((f) => `- Reads flow \`${f.id}\`, unchanged.`),
    "",
    "## Open questions",
    "",
    ...(p.gaps.length
      ? p.gaps.map((g) => `- ${sentence(g.what.replace(/\s+/g, " "))}`)
      : ["- None found by the feature stage; see needs.md for what the change waits on."]),
    "",
  );
  return lines.join("\n");
}

/** Write proposal.md unless a person wrote one (no mark): Atticus 1's proposals are kept. */
export async function writeProposal(dir: string, text: string): Promise<boolean> {
  const f = join(dir, "proposal.md");
  const had = await readFile(f, "utf8").catch(() => undefined);
  if (had !== undefined && !had.startsWith(PROPOSAL_MARK)) return false;
  await writeFileAtomic(f, text);
  return true;
}

// ------------------------------------------------------------------ a change's files

export interface OpenSpecFiles {
  deltas: SpecDelta[];
  /** The spec files, relative to the change folder. */
  files: Record<string, string>;
  /** Each story's flow → its capability, for the flows that have a delta. */
  capabilityOf: Map<string, string>;
  /** proposal.md with the capabilities, when the change has a feature.yaml. */
  proposal?: string;
}

/**
 * The OpenSpec files a change's stories make (no model call): the spec deltas against what
 * openspec/specs has (read through `openspec list --specs` and `show`), and proposal.md naming
 * them. Shared by the stories stage, its gate, the fast path and `atticus upgrade`.
 */
export async function openspecFiles(
  root: string,
  change: string,
  stories: DeltaStory[],
  answer: StoriesAnswer,
  estate?: Estate,
): Promise<OpenSpecFiles> {
  const osRoot = openspecRootOf(root);
  const existing = osRoot
    ? await readExistingSpecs(createOpenSpec({ root: osRoot })).catch(() => [])
    : [];
  const repos = new Set([
    ...(estate?.flows.map((f) => f.repo) ?? []),
    ...stories.map((s) => s.repo),
  ]);
  const o = { existing, multiRepo: repos.size > 1 };
  const deltas = specDeltas(change, stories, answer, o);
  const capabilityOfFlow = new Map(
    stories
      .map((s) => [s.flow, capabilityOf(s.flow, s.repo, o)] as const)
      .filter(([, c]) => deltas.some((d) => d.capability === c)),
  );
  const dir = changeFolder(root, change);
  const placed = await readFile(join(dir, "feature.yaml"), "utf8")
    .then((t) => FeaturePlacement.safeParse(parse(t)))
    .catch(() => undefined);
  let proposal: string | undefined;
  if (placed?.success) {
    const title = await changeStore(root)
      .read(change)
      .then((c) => c.title)
      .catch(() => change);
    const brief = await readFile(join(dir, "brief.md"), "utf8").catch(() => "");
    proposal = renderProposal(title, placed.data, brief, {
      repoOf: (f) => estate?.flowById.get(f)?.repo,
      capabilities: deltas.map((d) => {
        const s = stories.find((x) => x.flow === d.flow)!;
        return {
          capability: d.capability,
          flow: d.flow,
          name: s.name,
          op: d.purpose ? "ADDED" : d.removed.length && !d.modified.length ? "REMOVED" : "MODIFIED",
        };
      }),
    });
  }
  return {
    deltas,
    files: specFiles(deltas),
    capabilityOf: capabilityOfFlow,
    ...(proposal ? { proposal } : {}),
  };
}

// ------------------------------------------------------------------ OpenSpec's status

/** A change's artifacts as `openspec status --change <id>` reports them, with their stage. */
export interface OpenSpecProgress {
  artifacts: { id: string; status: string; stage?: OrgFlowStage }[];
  /** The stage that writes the first artifact not done; undefined when every one is. */
  next?: OrgFlowStage;
  complete: boolean;
}

/**
 * A change's artifact progress from OpenSpec (ADR 0006 addendum): the source of which stage's
 * files are written. Atticus's own gates (the critic, the hand-off PR a person merges) stay on
 * top and are recorded in change.yaml and stage/, where OpenSpec has no place for them.
 */
export async function openspecProgress(os: OpenSpec, change: string): Promise<OpenSpecProgress> {
  const s = await os.status(change);
  const artifacts = s.artifacts.map((a) => ({
    id: a.id,
    status: a.status,
    ...(ARTIFACT_STAGE[a.id] ? { stage: ARTIFACT_STAGE[a.id]! } : {}),
  }));
  const next = artifacts.find((a) => a.status !== "done")?.stage;
  return { artifacts, ...(next ? { next } : {}), complete: s.isComplete };
}

// ------------------------------------------------------------------ OpenSpec's instructions

/**
 * What a stage reads first (ADR 0006 addendum): `openspec instructions <artifact> --change <id>`
 * for each artifact the stage writes, as a source of its prompt: the schema's instruction and
 * template, and openspec/config.yaml's context and rules for the artifact. An organisation that
 * edits the schema (through the org pack) or the config changes what the drafter is told; Atticus
 * adds the catalog, the knowledge and the facts beside it. Nothing when the metarepo isn't set up
 * with OpenSpec (the prompt is then as before), or OpenSpec can't answer.
 */
export async function openspecInstructionSource(
  root: string,
  change: string,
  stage: OrgFlowStage,
): Promise<SourceInput | undefined> {
  const os = metarepoOpenSpec(root);
  if (!os) return undefined;
  const parts: string[] = [];
  for (const artifact of artifactsOfStage(stage)) {
    const i = await os.instructions(artifact, change).catch(() => undefined);
    if (!i) continue;
    parts.push(
      `## ${i.artifactId} (${i.outputPath}), schema ${i.schemaName}`,
      "",
      i.description,
      "",
      ...(i.instruction ? [i.instruction.trim(), ""] : []),
      ...(i.rules?.length
        ? ["Rules (openspec/config.yaml):", ...i.rules.map((r) => `- ${r}`), ""]
        : []),
      "The file's shape (the schema's template):",
      "",
      i.template.trim(),
      "",
    );
  }
  if (!parts.length) return undefined;
  const ctx = await os
    .instructions(artifactsOfStage(stage)[0]!, change)
    .then((i) => i.context?.trim())
    .catch(() => undefined);
  return {
    id: "openspec-instructions",
    kind: "document",
    origin: `openspec instructions (${artifactsOfStage(stage).join(", ")}) --change ${change}`,
    text: [...(ctx ? ["Project context (openspec/config.yaml):", "", ctx, ""] : []), ...parts]
      .join("\n")
      .trim(),
    classification: "internal",
    priority: 95,
  };
}

// ------------------------------------------------------------------ the gate

/** OpenSpec's advice on more than ten deltas: a note, never a block (the flows decide the size). */
const ADVICE = /Consider splitting changes/i;

const issueOf = (change: string, i: ValidationIssue): StageIssue => ({
  rule: "openspec.validate",
  target: `${change}/${i.path}`,
  message: `openspec validate --strict: ${i.message}`,
  blocking: i.level !== "INFO" && !ADVICE.test(i.message),
  kind: "drafting",
});

/**
 * `openspec validate <change> --strict` on the files a draft would write, before they are written:
 * the metarepo's openspec/ (config, schemas, specs) and the change's .openspec.yaml copied to a
 * temporary root with the draft's files, so a draft that fails never touches the change folder.
 * Nothing when the root isn't set up with OpenSpec. Each ERROR or WARNING is a blocking finding.
 */
export async function validateDraft(
  root: string,
  change: string,
  dir: string,
  files: Record<string, string>,
  o: { bin?: string } = {},
): Promise<StageIssue[]> {
  const osRoot = openspecRootOf(root);
  if (!osRoot) return [];
  const tmp = await mkdtemp(join(tmpdir(), "atticus-validate-"));
  try {
    const os = join(osRoot, "openspec");
    await mkdir(join(tmp, "openspec", "changes", change), { recursive: true });
    for (const f of ["config.yaml", "schemas", "specs"])
      if (existsSync(join(os, f)))
        await cp(join(os, f), join(tmp, "openspec", f), { recursive: true });
    const target = join(tmp, "openspec", "changes", change);
    for (const f of [".openspec.yaml", "proposal.md", "design.md", "stories.md", "tasks.md"])
      if (existsSync(join(dir, f))) await cp(join(dir, f), join(target, f));
    // The draft's spec files replace the change's generated ones.
    for (const [rel, text] of Object.entries(files)) {
      const f = join(target, ...rel.split("/"));
      await mkdir(dirname(f), { recursive: true });
      await writeFile(f, text, "utf8");
    }
    await setSkipSpecs(target, !Object.keys(files).some((f) => f.startsWith("specs/")));
    const r = await createOpenSpec({ root: tmp, ...(o.bin ? { bin: o.bin } : {}) }).validate({
      item: change,
      type: "change",
      strict: true,
    });
    return (r.items[0]?.issues ?? [])
      .filter((i) => i.level !== "INFO")
      .map((i) => issueOf(change, i));
  } catch (e) {
    return [
      {
        rule: "openspec.validate",
        target: change,
        message: `openspec validate couldn't run: ${(e as Error).message}`,
        blocking: false,
      },
    ];
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}
