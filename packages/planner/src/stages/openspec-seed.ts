import type { FlowRecord } from "@maycombhq/core";
import {
  capabilityOf,
  renderSpecDelta,
  type DeltaRequirement,
  type ExistingSpec,
  type SpecDelta,
} from "./openspec-files.js";

/**
 * A repo's starting spec, seeded from its verified flows (ADR 0146, plan item V2). A repo that
 * has never had a change has nothing in openspec/specs, so its first change would write every
 * flow it touches as ADDED. The seed gives each verified flow its capability (named as the
 * stories stage names it, `capabilityOf`), one requirement for the flow, and a scenario for its
 * main path, each branch step and each error case. Every WHEN, THEN and AND is a step's or an
 * error's own words with the lines they cite; where the flow says nothing, the scenario says
 * nothing. No model call.
 *
 * The seed is an OpenSpec change of its own in the metarepo (`seed-<repo>`), never a file in a
 * code repo: a person reads it, edits it, and accepts it with `atticus spec accept <repo>`,
 * which is `openspec archive`. From then on OpenSpec's archive keeps openspec/specs current, and
 * the stories stage writes MODIFIED for the requirement the seed left (its text carries
 * `Flow: \`<id>\``, which is how `specDeltas` finds it).
 */

export const SEED_MARK =
  "<!-- Generated by atticus spec seed from the repo's verified flows. Run it again to refresh it; delete this line to keep your edits. A person accepts the seed with atticus spec accept <repo>. -->";

/** OpenSpec warns (a failure under --strict) on a requirement text over 500 characters. */
const MAX_REQUIREMENT = 480;

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
const bare = (s: string) =>
  s
    .trim()
    .replace(/\s+/g, " ")
    .replace(/[.\s]+$/, "");
/** "A client posts" reads as "a client posts" mid-sentence; "API" and "Count.run" stay as written. */
const lowerFirst = (s: string) =>
  /^[A-Z][a-z]*(\s|$)/.test(s) ? `${s[0]!.toLowerCase()}${s.slice(1)}` : s;
const clip = (s: string, n: number) => {
  if (s.length <= n) return s;
  const cut = s.slice(0, n - 1);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(" "), n / 2)).trimEnd()}…`;
};

/** The seed change's id: `seed-<repo>`. */
export const seedChangeId = (repo: string): string =>
  `seed-${slug(repo)}`.slice(0, 80).replace(/-+$/, "");

interface Cited {
  repo?: string;
  path?: string;
  line?: number;
}

/** The lines a step, error or trigger cites: `path:line`, with the repo when it is another one. */
function citeOf(evidence: readonly Cited[], repo: string): string {
  const seen = new Set<string>();
  for (const e of evidence) {
    if (!e.path) continue;
    const where = `${e.repo && e.repo !== repo ? `${e.repo}:` : ""}${e.path}${e.line ? `:${e.line}` : ""}`;
    seen.add(`\`${where}\``);
  }
  return [...seen].join(", ");
}

const said = (what: string, evidence: readonly Cited[], repo: string) => {
  const c = citeOf(evidence, repo);
  return `${lowerFirst(bare(what))}${c ? ` (${c})` : ""}`;
};

/** Unique scenario names within a requirement: a repeated one gets "(2)", "(3)". */
function uniqueNames(xs: { name: string; body: string }[]): { name: string; body: string }[] {
  const seen = new Map<string, number>();
  return xs.map((x) => {
    const n = (seen.get(x.name.toLowerCase()) ?? 0) + 1;
    seen.set(x.name.toLowerCase(), n);
    return n === 1 ? x : { ...x, name: `${x.name} (${n})` };
  });
}

/** A flow's one requirement: the main path, each branch step, each error case. */
export function seedRequirement(flow: FlowRecord, repo: string): DeltaRequirement {
  const when = `- **WHEN** ${said(flow.trigger.what, flow.trigger.evidence, repo)}`;
  const steps = flow.steps.filter((s) => s.kind !== "entry" && s.kind !== "branch");
  // A flow of entry steps only: what it does is what they say.
  const main = steps.length ? steps : flow.steps.filter((s) => s.kind !== "branch");
  const scenarios: { name: string; body: string }[] = [];
  if (main.length)
    scenarios.push({
      name: `Main path: ${clip(bare(main[main.length - 1]!.what), 90)}`,
      body: [
        when,
        ...main.map(
          (s, i) => `- **${i === 0 ? "THEN" : "AND"}** ${said(s.what, s.evidence, repo)}`,
        ),
      ].join("\n"),
    });
  for (const b of flow.steps.filter((s) => s.kind === "branch"))
    scenarios.push({
      name: `Path: ${clip(bare(b.what), 90)}`,
      body: [when, `- **THEN** ${said(b.what, b.evidence, repo)}`].join("\n"),
    });
  for (const e of flow.errors)
    scenarios.push({
      name: `Error: ${clip(bare(e.when), 90)}`,
      body: [
        when,
        `- **AND** ${said(e.when, e.evidence, repo)}`,
        `- **THEN** ${said(e.then, e.evidence, repo)}`,
      ].join("\n"),
    });
  const trailer = `Flow: \`${flow.id}\`; seeded from code by atticus spec seed.`;
  const statement = `The system SHALL behave as flow \`${flow.id}\` does in the code today, started when ${said(flow.trigger.what, flow.trigger.evidence, repo)}.`;
  return {
    name: clip(bare(flow.name), 120),
    text: `${clip(statement, MAX_REQUIREMENT - trailer.length - 2)}\n\n${trailer}`,
    scenarios: uniqueNames(scenarios),
  };
}

export interface SeedSpec {
  /** The OpenSpec change the seed is: `seed-<repo>`. */
  change: string;
  repo: string;
  deltas: SpecDelta[];
  /** The spec files, relative to the change folder. */
  files: Record<string, string>;
  /** proposal.md of the seed change. */
  proposal: string;
  /** The flows not seeded, and why. */
  skipped: { flow: string; why: string }[];
}

/** Flows that aren't what the code does today. */
const NOT_TODAY = new Set(["planned-new", "retired"]);

/**
 * The seed of a repo's starting spec: a capability per flow openspec/specs doesn't have yet. A
 * flow whose capability it has (by the flow its Purpose names, or by name) is left to the
 * changes; a planned or retired flow isn't the code today.
 */
export function seedSpec(
  repo: string,
  flows: readonly FlowRecord[],
  o: { existing?: ExistingSpec[]; multiRepo: boolean },
): SeedSpec {
  const skipped: SeedSpec["skipped"] = [];
  const deltas: SpecDelta[] = [];
  for (const f of [...flows].sort((a, b) => a.id.localeCompare(b.id))) {
    if (NOT_TODAY.has(f.status)) {
      skipped.push({ flow: f.id, why: f.status });
      continue;
    }
    const capability = capabilityOf(f.id, repo, o);
    if (o.existing?.some((s) => s.id === capability || s.flow === f.id)) {
      skipped.push({ flow: f.id, why: `openspec/specs has it already, as ${capability}` });
      continue;
    }
    if (deltas.some((d) => d.capability === capability)) {
      skipped.push({ flow: f.id, why: `another flow of the repo is named ${capability} too` });
      continue;
    }
    const entry = f.trigger.ref ? `, started by ${f.trigger.ref}` : "";
    deltas.push({
      capability,
      flow: f.id,
      purpose: `Behaviour of flow \`${f.id}\` (${bare(f.name)})${entry}. Seeded by atticus spec seed from the flow verified in the code of ${repo}; each change that touches the flow modifies it.`,
      added: [seedRequirement(f, repo)],
      modified: [],
      removed: [],
    });
  }
  const change = seedChangeId(repo);
  return {
    change,
    repo,
    deltas,
    files: Object.fromEntries(
      deltas.map((d) => [`specs/${d.capability}/spec.md`, renderSpecDelta(d, SEED_MARK)]),
    ),
    proposal: renderSeedProposal(repo, deltas, skipped, flows),
    skipped,
  };
}

/** proposal.md of the seed change: what it seeds, what it doesn't, and how a person accepts it. */
export function renderSeedProposal(
  repo: string,
  deltas: readonly SpecDelta[],
  skipped: readonly { flow: string; why: string }[],
  flows: readonly FlowRecord[],
): string {
  const nameOf = (id: string) => bare(flows.find((f) => f.id === id)?.name ?? id);
  const n = deltas.length;
  return [
    SEED_MARK,
    `# Proposal: Starting spec for ${repo}`,
    "",
    "## Why",
    "",
    `${repo} has no spec in openspec/specs for these flows yet. This seeds one from the ${n} ${n === 1 ? "flow" : "flows"} Atticus verified in its code, so the first change to the repo modifies requirements that are already there instead of adding everything. Every scenario cites the lines it was read from.`,
    "",
    "## What Changes",
    "",
    "- A capability per flow, with one requirement for the flow and a scenario for its main path, each branch and each error case, worded from the flow's steps and errors.",
    "- No code changes.",
    "",
    "## Capabilities",
    "",
    "### New Capabilities",
    ...deltas.map((d) => `- \`${d.capability}\`: flow \`${d.flow}\` (${nameOf(d.flow)})`),
    "",
    "## Impact",
    "",
    `- Repos: ${repo} (its spec only; nothing in the repo changes).`,
    ...(skipped.length
      ? [`- Not seeded: ${skipped.map((s) => `\`${s.flow}\` (${s.why})`).join("; ")}.`]
      : []),
    "",
    "## Accepting it",
    "",
    `Read each spec under specs/ against the code it cites; edit what reads wrong, and delete a file's first line (the mark) so a second run keeps your edits. Then run \`atticus spec accept ${repo}\`: it runs \`openspec validate --strict\` and \`openspec archive\`, which writes openspec/specs/. Commit that in the metarepo's pull request.`,
    "",
  ].join("\n");
}
