/**
 * The data store a table is in: the catalog's, or, for a table the change adds, the data store
 * its id starts with (forge-orders-db.order_pin is in forge-orders-db).
 */
export function storeOfTable(e: Estate, table: string): string | undefined {
  const own = (e.byId.get(table) as { dataStore?: string } | undefined)?.dataStore;
  if (own) return own;
  const i = table.lastIndexOf(".");
  const prefix = i > 0 ? table.slice(0, i) : undefined;
  return prefix && e.byId.get(prefix)?.kind === "DataStore" ? prefix : undefined;
}

/** How a store's migrations are named today, from the catalog's Migration records. */
export interface StoreMigrations {
  store: string;
  /** The repo the migrations are in, by their evidence. */
  repo?: string;
  tool?: string;
  /** The folder they are all in, when they are in one. */
  folder?: string;
  /** Their file names, newest first. */
  files: string[];
  /**
   * The numbering every file name shares, when they all share one: a prefix, a number, a
   * separator, words and an extension (V3__add_sku.sql: V, 3, __, add_sku, .sql).
   */
  pattern?: { prefix: string; sep: string; ext: string; width: number; newest: number };
}

const NUMBERED = /^([A-Za-z]*)(\d+)([^A-Za-z0-9]+)([A-Za-z0-9].*?)(\.[A-Za-z0-9]+)$/;

/** The store's migrations, as facts read off the catalog: no guess at a tool's convention. */
export function migrationsOf(e: Estate, store: string): StoreMigrations {
  const recs = (
    e.records as {
      kind: string;
      dataStore?: string;
      file?: string;
      tool?: string;
      evidence?: { repo?: string }[];
    }[]
  ).filter((r) => r.kind === "Migration" && r.dataStore === store && r.file);
  // A migration that is a folder of its own (<folder>/<name>/migration.sql) is named by its
  // folder, and the migrations' folder is the one those are in (B-places).
  const nested =
    recs.length > 0 &&
    recs.every((r) => r.file!.split(/[\\/]/).length > 2 && fileOf(r.file!) === "migration.sql");
  const unit = (f: string) => (nested ? f.split(/[\\/]/).slice(0, -1).join("/") : f);
  const names = recs.map((r) => fileOf(unit(r.file!)));
  const parts = names.map((n) => NUMBERED.exec(n));
  const all = parts.every((p) => p) && parts.length > 0;
  const same = (k: number) => all && new Set(parts.map((p) => p![k])).size === 1;
  let pattern: StoreMigrations["pattern"];
  if (same(1) && same(3) && same(5)) {
    const nums = parts.map((p) => p![2]!);
    const padded =
      nums.some((x) => x.startsWith("0")) && new Set(nums.map((x) => x.length)).size === 1;
    pattern = {
      prefix: parts[0]![1]!,
      sep: parts[0]![3]!,
      ext: parts[0]![5]!,
      width: padded ? nums[0]!.length : 0,
      newest: Math.max(...nums.map(Number)),
    };
  }
  const num = (n: string) => Number(NUMBERED.exec(n)?.[2] ?? -1);
  const files = [...names].sort((a, b) =>
    pattern ? num(b) - num(a) || b.localeCompare(a) : b.localeCompare(a),
  );
  const folders = [
    ...new Set(recs.map((r) => unit(r.file!).split(/[\\/]/).slice(0, -1).join("/"))),
  ];
  const repos = [...new Set(recs.map((r) => r.evidence?.[0]?.repo).filter((x) => !!x))];
  const tools = [...new Set(recs.map((r) => r.tool).filter((x) => !!x))];
  return {
    store,
    ...(repos.length === 1 ? { repo: repos[0]! } : {}),
    ...(tools.length === 1 ? { tool: tools[0]! } : {}),
    ...(folders.length === 1 && folders[0] ? { folder: folders[0] } : {}),
    files,
    ...(pattern ? { pattern } : {}),
  };
}

/**
 * A table's name as SQL writes it: the catalog record's `name` (chat_pin for the id
 * db.chat-pin), else the id's last part with its hyphens as underscores.
 */
export function sqlNameOf(e: Estate, table: string): string {
  const own = (e.byId.get(table) as { name?: unknown } | undefined)?.name;
  return typeof own === "string" && own.trim()
    ? own.trim()
    : table.split(".").at(-1)!.replace(/-/g, "_");
}

/** The next free migration name in the store's numbering, with these words. */
export function nextMigration(m: StoreMigrations, words: string): string | undefined {
  const p = m.pattern;
  if (!p) return undefined;
  return `${p.prefix}${String(p.newest + 1).padStart(p.width, "0")}${p.sep}${words}${p.ext}`;
}

/** The column types a store's tables are written with in the catalog, sorted. */
export function columnTypesOf(e: Estate, store: string): string[] {
  const tables = new Set(
    (e.records as Rec[])
      .filter((r) => r.kind === "Table" && r.dataStore === store)
      .map((r) => r.id),
  );
  return [
    ...new Set(
      (e.records as Rec[])
        .filter(
          (r) => r.kind === "Column" && tables.has(String(r.table)) && typeof r.type === "string",
        )
        .map((r) => String(r.type)),
    ),
  ].sort();
}

/** "named as forge-orders-db's migrations are: the next is V4__<what_it_does>.sql, in <folder>". */
function migrationAdvice(e: Estate, table: string): string {
  const store = storeOfTable(e, table);
  if (!store) return "the migration file, with its extension";
  const m = migrationsOf(e, store);
  const next = nextMigration(m, "<what_it_does>");
  const where = m.folder ? `, in ${m.folder}` : "";
  if (next) return `named as ${store}'s migrations are: the next is ${next}${where}`;
  if (m.files.length)
    return `the migration file, with its extension, named as ${store}'s are (${m.files.slice(0, 3).join(", ")})${where}`;
  return "the migration file, with its extension";
}

/**
 * What is wrong with a migration's name, from how the table's store names its migrations
 * today (the catalog's files, their numbering and folder): the next free name is given. A
 * name in words is given the words a person would read (create_<table>, add_<column>) as an
 * example only. Undefined when it reads right.
 */
function migrationProblem(
  name: string,
  table: string,
  e: Estate,
  example: string,
  onFile = false,
): string | undefined {
  const file = fileOf(name);
  const store = storeOfTable(e, table);
  const m = store ? migrationsOf(e, store) : undefined;
  // Target flows on file, checked again once the change's code merged: the migration the
  // catalog now has by this very file name is the change's own (H4), not one to number past.
  if (onFile && m?.files.includes(file)) return undefined;
  // B-places: a migration the store already has is never edited; the change is a new one.
  if (m?.files.includes(file)) {
    const where = m.folder ? `, in ${m.folder}` : "";
    const stem = file.replace(/^[A-Za-z]*\d+[^A-Za-z0-9]+/, "").replace(/\.[A-Za-z0-9]+$/, "");
    const next = nextMigration(m, stem);
    return `names the migration ${name}, which ${store} already has: a change to its tables is a new migration beside it${where}: name the file ${next ?? `as its migrations are named (${m.files.slice(0, 3).join(", ")})`}.`;
  }
  const p = m?.pattern;
  if (m && p) {
    const x = NUMBERED.exec(file);
    const fits =
      x && x[1] === p.prefix && x[3] === p.sep && x[5] === p.ext && Number(x[2]) > p.newest;
    if (fits) return undefined;
    const what =
      m.tool === "flyway"
        ? `Flyway, the newest ${p.prefix}${p.newest}`
        : `the newest ${m.files[0]}`;
    const where = m.folder ? `, in ${m.folder}` : "";
    const wordy = /^[A-Za-z0-9][\w.-]*$/.test(name.trim());
    const stem = file.replace(/^[A-Za-z]*\d+[^A-Za-z0-9]+/, "").replace(/\.[A-Za-z0-9]+$/, "");
    return wordy
      ? `names the migration ${name}, which isn't how ${store}'s migrations are named (${what}): name the file ${nextMigration(m, stem)}${where}.`
      : `names the migration ${name}, which isn't how ${store}'s migrations are named (${what}): name the file ${nextMigration(m, "<what_it_does>")}, such as ${nextMigration(m, example)}${where}.`;
  }
  if (!/\.[A-Za-z0-9]+$/.test(file))
    return `names the migration ${name}, which isn't a file name: name the migration file, with its extension${m?.files.length ? `, as ${store}'s are named (${m.files.slice(0, 3).join(", ")})` : ""}.`;
  // B-places: a store with migrations is changed by a new one of theirs, not by another file.
  const exts = new Set(m?.files.map((f) => /\.[A-Za-z0-9]+$/.exec(f)?.[0]) ?? []);
  const ext = /\.[A-Za-z0-9]+$/.exec(file)![0];
  if (m && exts.size === 1 && !exts.has(ext))
    return `names the migration ${name}, which isn't one of ${store}'s migrations (${m.files.slice(0, 3).join(", ")}): a change to its tables is a new migration named as they are${m.folder ? `, in ${m.folder}` : ""}.`;
  return undefined;
}

/** The files a repo's records and flows cite, per estate. */
const citedFiles = new WeakMap<Estate, Set<string>>();
function citesFile(e: Estate, repo: string, path: string): boolean {
  let files = citedFiles.get(e);
  if (!files) {
    files = new Set<string>();
    const put = (ev: unknown, repo?: string) => {
      for (const x of (Array.isArray(ev) ? ev : []) as { repo?: string; path?: string }[])
        if (x.path) files!.add(`${x.repo ?? repo ?? ""}:${x.path}`);
    };
    for (const r of e.records as Rec[]) put(r.evidence);
    for (const f of e.flows) {
      put(f.flow.trigger.evidence, f.repo);
      for (const s of f.flow.steps) put(s.evidence, f.repo);
      for (const x of f.flow.errors ?? []) put(x.evidence, f.repo);
    }
    citedFiles.set(e, files);
  }
  return files.has(`${repo}:${path}`);
}

/**
 * Where an added step goes (B-places): a target flow's `at` names a file of the step's repo
 * that its checkout under workspace/ or the catalog has, a line the file has and a function in
 * it, when the checkout is there to read. Old answers have no `at`, so nothing is asked of them.
 */
export async function placeIssues(
  deltas: FlowDelta[],
  e: Estate,
  root?: string,
): Promise<StageIssue[]> {
  const out: StageIssue[] = [];
  for (const d of deltas)
    for (const [i, s] of d.steps.entries()) {
      if (!s.at) continue;
      const target = `${d.flow}#${i + 1}:at`;
      const change = `Change ${i + 1} to ${d.flow}`;
      if (s.op !== "add") {
        out.push({
          rule: "delta.at-not-added",
          target,
          message: `${change} gives at, which is for a step the change adds: a step it ${s.op}s is where today's flow cites it, so at is left out of its task.`,
          blocking: false,
          repo: d.repo,
        });
        continue;
      }
      const p = parseAt(s.at);
      const text = p && root ? await readCheckoutFile(root, d.repo, p.path) : undefined;
      if (!p || (text === undefined && !citesFile(e, d.repo, p.path))) {
        out.push({
          rule: "delta.at-unknown",
          target,
          message: `${change} puts the new step at ${s.at}, but ${d.repo} has no such file in its checkout or the catalog: give the path as the repo has it (path:line of the line the step goes after, or path:function), or leave at out for code in a new file.`,
          blocking: true,
          repo: d.repo,
        });
        continue;
      }
      if (text === undefined) continue;
      const lines = text.replace(/\r\n?/g, "\n").replace(/\n$/, "").split("\n").length;
      if (p.line !== undefined && (p.line < 1 || p.line > lines))
        out.push({
          rule: "delta.at-line",
          target,
          message: `${change} puts the new step after line ${p.line} of ${p.path}, which has ${lines} lines in ${d.repo}'s checkout: give the line it goes after.`,
          blocking: true,
          repo: d.repo,
        });
      const fn = p.function?.split(/[.#]/).at(-1);
      if (fn && !new RegExp(`(^|[^\\w$])${fn.replace(/\$/g, "\\$")}([^\\w$]|$)`).test(text))
        out.push({
          rule: "delta.at-function",
          target,
          message: `${change} puts the new step in ${p.function}, which ${p.path} doesn't have in ${d.repo}'s checkout: name a function the file has, or give path:line.`,
          blocking: true,
          repo: d.repo,
        });
    }
  return out;
}

/**
 * The facts a step that writes a table needs, for the stores the change is likely to write
 * (ADR 0111 addendum): how each names its migrations (at most three file names, the next free
 * one and the folder) and the column types its tables are written with. Facts from the catalog,
 * given before the first draft so it needn't learn them from a finding.
 */
export function storeFacts(e: Estate, stores: string[], tables: readonly string[] = []): string {
  const lines: string[] = [];
  for (const s of stores) {
    const m = migrationsOf(e, s);
    const types = columnTypesOf(e, s);
    const next = nextMigration(m, "<what_it_does>");
    const mig = m.files.length
      ? `migrations in ${m.folder ?? "several folders"}, the newest ${m.files.slice(0, 3).join(", ")}${next ? `; the next is ${next}` : ""}`
      : noMigrationWords(e, s, tables);
    lines.push(
      `- ${s}${m.repo ? ` (repo ${m.repo})` : ""}: ${mig}.${types.length ? ` Column types as its tables write them: ${types.slice(0, 8).join(", ")}.` : ""}`,
    );
  }
  return lines.length
    ? ["The data stores the change may write, from the catalog:", ...lines].join("\n")
    : "";
}

/**
 * A store with no migrations (B-places): the files its tables' columns are declared in change in
 * place. B-run2-fixes 1: for each table the change's flows use, the files that declare that
 * table's columns (its schema file and the entity mapped to it, `declaringFiles`), not every file
 * one of the store's columns is cited in; with none of its tables used, the store's as a whole.
 */
function noMigrationWords(e: Estate, store: string, tables: readonly string[]): string {
  const own = [...new Set(tables)].filter((t) => storeOfTable(e, t) === store).sort();
  const all = (e.records as Rec[])
    .filter((r) => r.kind === "Table" && r.dataStore === store)
    .map((r) => r.id);
  const said = (
    own.length
      ? own.map((t) => ({ t, files: declaringFiles(e, [t]).map((f) => f.path) }))
      : [{ t: undefined, files: declaringFiles(e, all).map((f) => f.path) }]
  ).filter((g) => g.files.length);
  if (!said.length)
    return "the catalog has no migration of it: name the migration file, with its extension";
  const one = said.length === 1 && said[0]!.files.length === 1;
  const where = said
    .map(
      (g) =>
        `${g.t ? `the columns of ${sqlNameOf(e, g.t)}` : "its columns"} are declared in ${g.files.join(", ")}`,
    )
    .join("; ");
  return `the catalog has no migration of it; ${where}: a change there is made in place, so name ${one ? "that file" : "the schema file that creates the table"} under store.migration`;
}

/** The tables today's flows the change touches use, for the store facts (B-run2-fixes 1). */
export function touchedTables(e: Estate, p: FeaturePlacement): string[] {
  const out = new Set<string>();
  for (const f of p.flows)
    for (const s of e.flowById.get(f.id)?.flow.steps ?? []) if (s.store) out.add(s.store.table);
  return [...out].sort();
}

/**
 * The data stores a change may write: those of the tables today's touched flows use, and those
 * owned by a component in a repo the change touches or adds a flow to. At most five.
 */
export function storesFor(e: Estate, p: FeaturePlacement): string[] {
  const out = new Set<string>();
  const repos = new Set<string>(p.newFlows.map((n) => n.repo));
  for (const f of p.flows) {
    const sf = e.flowById.get(f.id);
    if (!sf) continue;
    repos.add(sf.repo);
    for (const s of sf.flow.steps) {
      const st = s.store ? storeOfTable(e, s.store.table) : undefined;
      if (st) out.add(st);
    }
  }
  for (const r of e.records as Rec[]) {
    if (r.kind !== "DataStore" || typeof r.ownerComponent !== "string") continue;
    const repo = (e.byId.get(r.ownerComponent) as { repo?: string } | undefined)?.repo;
    if (repo && repos.has(repo)) out.add(r.id);
  }
  return [...out].sort().slice(0, 5);
}

/** The tables a change may store into: those today's touched flows use, and the stores' tables. */
export function tablesFor(e: Estate, p: FeaturePlacement): string[] {
  const out = new Set<string>();
  for (const f of p.flows)
    for (const s of e.flowById.get(f.id)?.flow.steps ?? []) if (s.store) out.add(s.store.table);
  const stores = new Set(storesFor(e, p));
  for (const r of e.records as Rec[])
    if (r.kind === "Table" && typeof r.dataStore === "string" && stores.has(r.dataStore))
      out.add(r.id);
  return [...out].sort();
}

/**
 * Who uses what the touched flows serve and store into, from the map (ADR 0124 addendum B-arch):
 * the callers of each flow's entry and the readers and writers of each table its steps use, so
 * a breaking change lists them from the first draft. Nothing when the map knows no one.
 */
export function consumersSource(e: Estate, p: FeaturePlacement): SourceInput[] {
  const lines: string[] = [];
  const tables = new Set<string>();
  // The touched flows' own components are the change's; only the others are listed.
  const own = new Set<string>();
  for (const f of p.flows) {
    const sf = e.flowById.get(f.id);
    if (!sf) continue;
    own.add(sf.flow.component);
    const ref = sf.flow.trigger.ref;
    if (ref && e.byId.get(ref)?.kind === "Endpoint") {
      const who = endpointConsumers(e, ref, sf.flow.component);
      if (who.length)
        lines.push(`- ${endpointName(e, ref)} (flow ${f.id}): called by ${who.join(", ")}`);
    }
    for (const s of sf.flow.steps) if (s.store) tables.add(s.store.table);
  }
  for (const t of [...tables].sort()) {
    const who = tableConsumers(e, t).filter((c) => !own.has(c));
    if (who.length) lines.push(`- ${t}: read or written by ${who.join(", ")}`);
  }
  if (!lines.length) return [];
  return [
    {
      id: "consumers",
      kind: "catalog",
      origin: "the catalog's interfaces and tables, and the repos' specs (deterministic)",
      text: [
        "Who uses the entries and tables of the flows the change touches today, from the map. A change that breaks one lists them under consumers.",
        ...lines.slice(0, 40),
      ].join("\n"),
      classification: "internal",
      priority: 87,
    },
  ];
}

