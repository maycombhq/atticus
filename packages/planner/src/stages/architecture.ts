export function checkDeltas(
  deltas: FlowDelta[],
  e: Estate,
  p: FeaturePlacement,
  reads: ReadFlow[] = [],
  o: {
    /** The org pack's data classification levels (pack.yaml), lowest first. */
    levels?: string[];
    /**
     * The org pack's spec templates (ADR 0079): what each step kind must name. A step kind
     * that must name a table (store) and not a target has no `to`.
     */
    templates?: readonly SpecTemplate[];
    /**
     * The target flows are the stage's result on file, checked again after it was done
     * (H4): what the change itself adds (a table or entry it marks new, its migration) may
     * be in the catalog now because its code merged, so that is not held against it.
     */
    onFile?: boolean;
  } = {},
): StageIssue[] {
  const out: StageIssue[] = [];
  /** Whether a step kind names a table and never a target, by the flow's spec template. */
  const storeOnly = (kind: string, flow: string, repo: string) => {
    const ref =
      e.flowById.get(flow)?.flow.template ??
      [...e.flowById.values()].find((f) => f.repo === repo)?.flow.template;
    const step = specTemplateFor(o.templates ?? [], ref?.split("@")[0]).steps.find(
      (s) => s.kind === kind,
    );
    const needs = step?.requires ?? [];
    return needs.some((x) => x.startsWith("store.")) && !needs.includes("to");
  };
  for (const r of reads) {
    if (!e.flowById.has(r.flow))
      out.push({
        rule: "delta.unknown-read",
        target: r.flow,
        message: unknownReadMessage(r.flow, e),
        blocking: true,
      });
    if (deltas.some((d) => d.flow === r.flow && !isEmptyDelta(d)))
      out.push({
        rule: "delta.read-and-changed",
        target: r.flow,
        message: `Flow ${r.flow} is under both flows and reads; it is one or the other.`,
        blocking: true,
      });
    // The feature said it changes; the architect found no step that does. Shown, not blocking.
    if (p.flows.some((f) => f.id === r.flow && f.how === "changed"))
      out.push({
        rule: "delta.changed-only-read",
        target: r.flow,
        message: `The feature says flow ${r.flow} changes, but the target flows only read it: ${r.why}`,
        blocking: false,
      });
  }
  const issue = (rule: string, target: string, message: string, repo: string) =>
    out.push({ rule, target, message, blocking: true, repo });
  const isTable = (table: string) => e.byId.get(table)?.kind === "Table";

  // ---- the tables this change creates (A5): each is defined once, by the step that marks it
  // new; every other step that uses it names it and takes the rest from there.
  // A table the catalog has, marked new, is delta.table-exists, not a definition.
  const defs = tableDefinitions(deltas, (t) => !isTable(t) || !!o.onFile);
  const ref = (x: { flow: string; change: number }) => `change ${x.change} to ${x.flow}`;
  const defOf = (table: string) => defs.get(table)?.[0];
  const isDef = (table: string, flow: string, change: number) => {
    const x = defOf(table);
    return !!x && x.flow === flow && x.change === change;
  };

  // What each table gains in this change, gathered over every step (one finding a table for
  // what belongs to the table, however many flow changes touch it; A3).
  type Gain = {
    repo: string;
    /** Each column added, with the first step that adds it. */
    cols: Map<string, { flow: string; change: number }>;
    types: Set<string>;
    classified: Set<string>;
    migration: boolean;
    /** Each column the table has that gets another type, with the first step that says so. */
    retyped: Map<string, Retyped & { flow: string; change: number }>;
  };
  const gains = new Map<string, Gain>();
  const gainOf = (table: string, repo: string) => {
    let g = gains.get(table);
    if (!g) {
      g = {
        repo,
        cols: new Map(),
        types: new Set(),
        classified: new Set(),
        migration: false,
        retyped: new Map(),
      };
      gains.set(table, g);
    }
    return g;
  };

  // A6: every classification is checked against the org pack's levels where it is written: on
  // any step, the defining one or not, in a delta whose flow is unknown too.
  const classifications = (t: string, repo: string, s: FlowDelta["steps"][number], i: number) => {
    if (!o.levels?.length || !s.store) return;
    for (const [c, level] of Object.entries(s.store.classification ?? {}))
      if (!o.levels.includes(level))
        issue(
          "delta.bad-classification",
          `${t}#${i + 1}:${c}`,
          `Change ${i + 1} to ${t} classifies column ${c} as ${level}, which isn't one of the org pack's levels: ${words(o.levels)}. Write one of those words exactly.`,
          repo,
        );
  };

  const seen = new Set<string>();
  for (const d of deltas) {
    const t = d.flow;
    if (seen.has(t))
      issue("delta.twice", t, `Flow ${t} has two deltas; write one per flow.`, d.repo);
    seen.add(t);
    const today = e.flowById.get(t);
    if (d.change !== "new" && !today) {
      issue(
        "delta.unknown-flow",
        t,
        `Flow ${t} isn't in any repo's spec; a flow that doesn't exist yet is change: new.`,
        d.repo,
      );
      d.steps.forEach((s, i) => classifications(t, d.repo, s, i));
      continue;
    }
    if (d.change === "new") {
      if (today)
        issue(
          "delta.exists",
          t,
          `Flow ${t} already exists; change it with change: modify.`,
          d.repo,
        );
      if (!d.name?.trim()) issue("delta.new-no-name", t, `New flow ${t} has no name.`, d.repo);
      if (!d.trigger)
        issue(
          "delta.new-no-trigger",
          t,
          `New flow ${t} has no trigger: say what starts it.`,
          d.repo,
        );
      if (d.steps.length === 0)
        issue("delta.new-no-steps", t, `New flow ${t} has no steps.`, d.repo);
    }
    if (today && today.repo !== d.repo)
      issue("delta.wrong-repo", t, `Flow ${t} is in repo ${today.repo}, not ${d.repo}.`, d.repo);
    // ADR 0111: a delta pinned to another version of today's flow addresses steps by stale numbers.
    if (deltaBase(d, today?.flow) === "changed")
      issue("delta.stale", t, baseProblem(d, "changed")!, d.repo);
    if (isEmptyDelta(d)) out.push(...emptyDeltaIssues([d]));
    const count = today?.flow.steps.length ?? 0;
    d.steps.forEach((s, i) => {
      const at = `${t}#${i + 1}`;
      if (s.op === "add") {
        if (d.change !== "new" && s.after === undefined)
          issue(
            "delta.add-no-place",
            at,
            `Change ${i + 1} to ${t} adds a step but says not where: give after (the step it follows).`,
            d.repo,
          );
        if (s.after !== undefined && s.after > count && d.change !== "new")
          issue(
            "delta.bad-step",
            at,
            `Change ${i + 1} to ${t} goes after step ${s.after}, but the flow has ${count} steps.`,
            d.repo,
          );
        if (!s.kind || !s.what?.trim())
          issue(
            "delta.add-incomplete",
            at,
            `Change ${i + 1} to ${t} adds a step without its kind and what it does.`,
            d.repo,
          );
      } else if (s.step === undefined || s.step > count)
        issue(
          "delta.bad-step",
          at,
          `Change ${i + 1} to ${t} ${s.op}s step ${s.step ?? "?"}, which today's flow doesn't have (it has ${count}).`,
          d.repo,
        );
      classifications(t, d.repo, s, i);
      if (s.op === "remove") return;
      const kind = s.kind ?? (s.step ? today?.flow.steps[s.step - 1]?.kind : undefined);
      // A step the spec template says names a table (store) reaches no component (to).
      if (s.to && kind && storeOnly(kind, t, d.repo))
        issue(
          "delta.to-on-store-step",
          at,
          `Change ${i + 1} to ${t} is a ${kind} step: it names the table it ${kind === "write" ? "writes" : "reads"} under store: { table, columns }, and has no to (to is for call-out and publish steps).`,
          d.repo,
        );
      if ((kind === "call-out" || kind === "publish") && s.op === "add" && !s.to)
        issue(
          "delta.no-target",
          at,
          `Change ${i + 1} to ${t} is a ${kind} with no target: say which component and entry it goes to.`,
          d.repo,
        );
      if (
        s.to &&
        !s.to.new &&
        !["Component", "System"].includes(e.byId.get(s.to.component)?.kind ?? "")
      )
        issue(
          "delta.unknown-component",
          at,
          ["Table", "DataStore"].includes(e.byId.get(s.to.component)?.kind ?? "")
            ? `Change ${i + 1} to ${t} goes to ${s.to.component}, which is a ${e.byId.get(s.to.component)!.kind === "Table" ? "table" : "data store"}, not a component: a step that reads or writes it names it under store, as store: { table: ${s.to.component}, columns: [the columns] }, and has no to.`
            : `Change ${i + 1} to ${t} goes to ${s.to.component}, which the catalog doesn't have; use an id from the index, or new: true.`,
          d.repo,
        );
      // ADR 0111: the entry is resolved against the callee's endpoints, when the catalog has any.
      if (s.to) {
        const have = entriesOf(e, s.to.component);
        const known = have.has(entryKey(s.to.entry));
        if (have.size && !s.to.new && !known)
          issue(
            "delta.unknown-entry",
            at,
            `Change ${i + 1} to ${t} calls ${s.to.entry} on ${s.to.component}${/^METHOD\s/i.test(s.to.entry) ? `: write the HTTP method itself (GET, POST, PUT, PATCH or DELETE), not METHOD. ${s.to.component} has` : ", which the catalog doesn't have; it has"} ${nearestEntries(s.to.entry, [...have.values()]).join(", ")}${have.size > 8 ? ` and ${have.size - 8} more` : ""}. Use one of them, or new: true for an entry this change adds.`,
            d.repo,
          );
        if (s.to.new && known && !o.onFile)
          issue(
            "delta.entry-exists",
            at,
            `Change ${i + 1} to ${t} marks ${s.to.entry} on ${s.to.component} new, but the catalog has it; leave new out.`,
            d.repo,
          );
        // B-arch, check 1: a call to an entry the map has nothing of cites no fact. The map may
        // just not have read the callee (a vendor), so a person confirms it: shown, not blocking.
        if (
          !have.size &&
          !s.to.new &&
          ["Component", "System"].includes(e.byId.get(s.to.component)?.kind ?? "")
        )
          out.push({
            rule: "delta.entry-uncited",
            target: at,
            message: `Change ${i + 1} to ${t} calls ${s.to.entry} on ${s.to.component}, but the map has no entry of ${s.to.component}, so nothing confirms the call. Mark it new: true if this change adds it; otherwise a person confirms it.`,
            blocking: false,
            repo: d.repo,
          });
      }
      if (s.store && s.store.new && isTable(s.store.table) && !o.onFile) {
        issue(
          "delta.table-exists",
          at,
          `Change ${i + 1} to ${t} marks table ${s.store.table} new, but the catalog has it; leave new out, and give the columns it adds with their types.`,
          d.repo,
        );
      } else if (s.store) {
        const table = s.store.table;
        const def = defOf(table);
        const defining = isDef(table, t, i + 1);
        if (!s.store.new && !isTable(table) && !def)
          issue(
            "delta.unknown-table",
            at,
            `Change ${i + 1} to ${t} uses table ${table}, which the catalog doesn't have; use an id from the index, or new: true on the step that creates it.`,
            d.repo,
          );
        // B-fixes: a key-pattern store (a cache or key-value store read by key) has no columns.
        const byKey = isKeyPattern(e, table);
        if (
          (kind === "write" || kind === "read" || kind === "lookup") &&
          s.store.columns.length === 0 &&
          !byKey
        )
          issue(
            "delta.no-columns",
            at,
            `Change ${i + 1} to ${t} ${kind === "write" ? "writes" : "reads"} ${table} without naming its columns.`,
            d.repo,
          );
        const have = columnsOf(e, table);
        const reads = kind === "read" || kind === "lookup";
        // A table this change creates: its columns are the creating step's, and a step that
        // uses it names only those (A5).
        if (def && !defining) {
          const cols = def.store.columns;
          for (const c of s.store.columns)
            if (!cols.includes(c))
              issue(
                "delta.unknown-column",
                `${at}:${c}`,
                `Change ${i + 1} to ${t} uses column ${c} of ${table}, which ${ref(def)} creates without it (its columns: ${cols.join(", ")}): use one of those, or add ${c} on that step with its type and classification.`,
                d.repo,
              );
        }
        // ADR 0111: a read names columns the table has, or that a write in this change adds.
        if (reads && !def && have.size) {
          const addedHere = new Set(
            deltas.flatMap((x) =>
              x.steps.flatMap((y) =>
                y.store?.table === table ? Object.keys(y.store.types ?? {}) : [],
              ),
            ),
          );
          for (const c of s.store.columns)
            if (!have.has(c) && !addedHere.has(c))
              issue(
                "delta.unknown-column",
                `${at}:${c}`,
                `Change ${i + 1} to ${t} reads column ${c} of ${table}, which the catalog doesn't have; name a column it has (${[...have].sort().join(", ")}), or add it with a write step that gives its type.`,
                d.repo,
              );
        }
        // What this step adds: a new table's columns on the step that creates it; a catalog
        // table's columns it hasn't, on a write.
        // A key-pattern store adds no column: what it holds under a key needs no migration.
        const added = def
          ? defining
            ? s.store.columns
            : []
          : reads || byKey
            ? []
            : s.store.columns.filter((c) => !have.has(c));
        // A column "added" that is one the table has in other casing (updatedAt for updated_at).
        const fold = (c: string) => c.replace(/[_-]/g, "").toLowerCase();
        const twins = new Map(
          added.flatMap((c) => {
            const t = [...have].find((h) => h !== c && fold(h) === fold(c));
            return t ? [[c, t] as const] : [];
          }),
        );
        for (const [c, own] of twins)
          issue(
            "delta.column-name",
            `${at}:${c}`,
            `Change ${i + 1} to ${t} adds column ${c} to ${table}, but the table has ${own}: name the column as the table does.`,
            d.repo,
          );
        // A write that sends a field its own step says nothing else about has left a column out
        // (seen with a small model: the new column the brief asked for was sent but never added).
        // What a field is for is the model's to say, never guessed from its name: a field it
        // stores is a column, and a key the write matches rows by is under checks (or mapped
        // under from and to). Only a field the step says nothing about is handed back.
        if (kind === "write" && !byKey) {
          const leaf = (f: string) => fold(f.split(".").at(-1)!);
          const said = new Set(
            [
              ...s.store.columns,
              ...have,
              ...(def?.store.columns ?? []),
              ...(["checks", "from", "to", "reads"] as const).flatMap((k) => s.fields?.[k] ?? []),
            ].map(leaf),
          );
          // R3: a field sent under another name says which column it is, as a fact the delta
          // states (fields.as), never guessed from the words: { id: chat_id }.
          const columns = new Set(
            [
              ...s.store.columns,
              ...have,
              ...(def?.store.columns ?? []),
              ...(s.fields?.checks ?? []),
            ].map(leaf),
          );
          const as = s.fields?.as ?? {};
          for (const f of s.fields?.sends ?? []) {
            const col = as[f];
            if (col !== undefined) {
              if (!columns.has(leaf(col)))
                issue(
                  "delta.sent-not-stored",
                  `${at}:${f}`,
                  `Change ${i + 1} to ${t} sends ${f} as column ${col} of ${table}, but the step neither stores ${col} (store.columns) nor matches rows by it (fields.checks), and ${table} has no such column: name a column the step stores or matches by, or add ${col} to store.columns with its type, classification and migration.`,
                  d.repo,
                );
              continue;
            }
            if (!said.has(leaf(f)))
              issue(
                "delta.sent-not-stored",
                `${at}:${f}`,
                `Change ${i + 1} to ${t} sends ${f} to ${table} but stores it in no column: if it is stored as, or matches rows by, a column of another name (a path parameter id that is the order_id column), say which under fields.as: { ${f}: <the column> }, with that column under store.columns or fields.checks; if it is a new column, add it to store.columns with its type, classification and migration; or leave it out of sends.`,
                d.repo,
              );
          }
        }
        if (s.store.migration?.trim()) {
          // R4: the table's SQL name from its catalog record; a table the catalog doesn't
          // have yet has none, so the example uses its id's last part as a SQL word.
          const name = sqlNameOf(e, table);
          const example = def ? `create_${name}` : `add_${added[0] ?? "columns"}_to_${name}`;
          const why = migrationProblem(s.store.migration.trim(), table, e, example, o.onFile);
          if (why) issue("delta.bad-migration", at, `Change ${i + 1} to ${t} ${why}`, d.repo);
        }
        // S4: a foreign key is checked as facts: it is on the table's one definition, keys one of
        // the table's columns, and references a table and column the catalog or the change has.
        const keys = Object.entries(s.store.keys ?? {});
        if (keys.length && def && !defining)
          issue(
            "delta.key-not-on-definition",
            at,
            `Change ${i + 1} to ${t} gives keys for ${table}, which ${ref(def)} creates: give its keys on that step, the table's one definition.`,
            d.repo,
          );
        else
          for (const [col, key] of keys) {
            const tableCols = def ? def.store.columns : [...have, ...s.store.columns];
            if (!tableCols.includes(col)) {
              issue(
                "delta.key-unknown-column",
                `${at}:${col}`,
                `Change ${i + 1} to ${t} gives a key for column ${col}, which isn't one of ${table}'s columns (${tableCols.join(", ")}): key a column the table has, or add it under store.columns.`,
                d.repo,
              );
              continue;
            }
            const parts = key.references.split(".");
            const refCol = parts.at(-1)!;
            const refTable = parts.slice(0, -1).join(".");
            const refDef = defs.get(refTable)?.[0];
            if (!isTable(refTable) && !refDef) {
              issue(
                "delta.key-unknown-reference",
                `${at}:${col}`,
                `Change ${i + 1} to ${t} says column ${col} of ${table} references ${key.references}, but neither the catalog nor this change has a table ${refTable}. Name a table and column the catalog or this change has, as <db>.<table>.<column>.`,
                d.repo,
              );
              continue;
            }
            const refCols = new Set([
              ...columnsOf(e, refTable),
              ...(refDef?.store.columns ?? []),
              ...deltas.flatMap((x) =>
                x.steps.flatMap((y) =>
                  y.store?.table === refTable ? Object.keys(y.store.types ?? {}) : [],
                ),
              ),
            ]);
            if (!refCols.has(refCol))
              issue(
                "delta.key-unknown-reference",
                `${at}:${col}`,
                `Change ${i + 1} to ${t} says column ${col} of ${table} references ${key.references}, but ${refTable} has no column ${refCol} (its columns: ${[...refCols].sort().join(", ")}). Name a column it has, as <db>.<table>.<column>.`,
                d.repo,
              );
          }
        // Gathered for the table, so each property is asked for once (below).
        const g = gainOf(table, (def ?? d).repo);
        const own = added.filter((x) => !twins.has(x));
        for (const c of own) if (!g.cols.has(c)) g.cols.set(c, { flow: t, change: i + 1 });
        // B-arch: a type given for a column the table has, other than the catalog's, changes it.
        const retyped = def ? [] : retypedColumns(e, s.store);
        for (const r of retyped)
          if (!g.retyped.has(r.column)) g.retyped.set(r.column, { ...r, flow: t, change: i + 1 });
        if (!def || defining) {
          for (const c of Object.keys(s.store.types ?? {})) g.types.add(c);
          for (const c of Object.keys(s.store.classification ?? {})) g.classified.add(c);
          if ((own.length || retyped.length) && s.store.migration?.trim()) g.migration = true;
        }
      }
      const named = fieldNames(s.fields).length + (s.store?.columns.length ?? 0);
      if (kind && MOVES_DATA.has(kind) && named === 0)
        issue(
          "delta.no-fields",
          at,
          `Change ${i + 1} to ${t} (${kind}) names no fields: say what it sends, returns, reads or stores.`,
          d.repo,
        );
    });
    if (today && d.change === "modify")
      for (const x of fieldsFromNowhere(d, today.flow, e))
        issue(
          "delta.field-from-nowhere",
          `${t}#${x.change}:${x.field}`,
          `Change ${x.change} to ${t} returns ${x.field}, but no step of the flow receives, reads, writes or works it out, and no table the flow uses has it: add the step that gives it (a write with the new column, its type and its migration), or leave it out.`,
          d.repo,
        );
    // W3b: a field worked out from columns names columns the flow has by then.
    for (const x of derivedProblems(d, today?.flow, e, defs))
      issue(
        "delta.derived-unknown-column",
        `${t}#${x.change}:${x.field}`,
        x.unknown.length
          ? `Change ${x.change} to ${t} works out ${x.field} from ${x.expression}, but ${words(x.unknown).replace(/ or ([^,]*)$/, " and $1")} ${x.unknown.length === 1 ? "is no column" : "are no columns"} a step before it reads or writes, nor one of their tables' (${x.have.join(", ")}). Name the columns it is worked out from.`
          : `Change ${x.change} to ${t} works out ${x.field} from ${x.expression}, which names no column. Name the columns it is worked out from, as in edited_at is not null.`,
        d.repo,
      );
    // S3: what a respond returns or a call sends comes from a step before it, in merged order.
    for (const x of returnedBeforeGiven(d, today?.flow, e))
      issue(
        "delta.returned-before-given",
        `${t}#${x.change}:${x.field}`,
        x.later
          ? `Step ${x.step} of the target of ${t} (${x.kind}, change ${x.change}) ${x.verb} ${x.field}, but no step before it gives it: step ${x.later.step} (${x.later.kind}${x.later.change ? `, change ${x.later.change}` : ""}) gives it after. Adds with the same after keep the order they are written in, so write the step that gives ${x.field} first, or give it an earlier after.`
          : `Step ${x.step} of the target of ${t} (${x.kind}, change ${x.change}) ${x.verb} ${x.field}, but no step before it gives it (the trigger's input, a read, a lookup, or an earlier step's fields or store): add the step that gives it before step ${x.step}, or leave it out.`,
        d.repo,
      );
  }
  // ---- what belongs to a table, once a table (A3, A5)
  for (const [table, g] of gains) {
    const def = defOf(table);
    const store = storeOfTable(e, table);
    const types = store ? columnTypesOf(e, store) : [];
    const twice = defs.get(table) ?? [];
    if (twice.length > 1)
      issue(
        "delta.table-new-twice",
        table,
        `Table ${table} is marked new by ${words(twice.map(ref)).replace(/ or ([^,]*)$/, " and $1")}. Mark it new only on the step that creates it (${ref(def!)}); every other step names the table without new and only the columns it uses, and takes the columns' types, classification, migration and retention from there.`,
        g.repo,
      );
    // "Change 2 to F creates table T" or "Change 1 to F adds columns a, b to T".
    const whose = (cols: string[]) => {
      const steps = [...new Map(cols.map((c) => [ref(g.cols.get(c)!), g.cols.get(c)!])).keys()];
      const who = capital(words(steps).replace(/ or ([^,]*)$/, " and $1"));
      return def
        ? `${capital(ref(def))} creates table ${table}`
        : `${who} ${steps.length > 1 ? "add" : "adds"} column${cols.length > 1 ? "s" : ""} ${words(cols).replace(/ or ([^,]*)$/, " and $1")} to ${table}`;
    };
    const both = (xs: string[]) => words(xs).replace(/ or ([^,]*)$/, " and $1");
    const on = def ? " on that step" : "";
    const untyped = [...g.cols.keys()].filter((c) => !g.types.has(c));
    if (untyped.length)
      issue(
        "delta.no-type",
        table,
        `${whose(untyped)} without a type${def ? ` for ${both(untyped)}` : ""}: give ${untyped.length > 1 ? "each" : "it"} under store.types${on}${types.length && store ? `, written as ${store}'s columns are (${types.slice(0, 8).join(", ")})` : ""}.`,
        g.repo,
      );
    const unclassified = [...g.cols.keys()].filter((c) => !g.classified.has(c)).sort();
    if (unclassified.length) {
      const one = unclassified.length === 1;
      const cols = both(unclassified);
      out.push({
        rule: "delta.no-classification",
        target: `${table}:${unclassified.join(",")}`,
        message: `${whose(unclassified)} without a classification${def ? ` for ${cols}` : ""}: give ${one ? "it" : "each"} under store.classification${on}${o.levels?.length ? `, as one of ${words(o.levels)}` : ""}.`,
        blocking: true,
        repo: g.repo,
        // A person decides how a column is classified, from the org pack's levels: one question
        // for the table, listing its columns.
        ask: one
          ? `How is the new column ${cols} of ${table} classified?`
          : `How are the new columns ${cols} of ${table} classified?`,
        ...(o.levels?.length
          ? {
              options: o.levels.map((l) => ({
                label: l,
                means: `${cols} ${one ? "is" : "are"} ${l} data`,
                changes: `The plan classifies ${both(unclassified.map((c) => `${table}.${c}`))} as ${l}`,
              })),
            }
          : {}),
      });
    }
    // "Change 2 to F changes the type of quantity in T" (B-arch), after what the table gains.
    const retypedWhose = () => {
      const cols = [...g.retyped.keys()];
      const steps = [...new Set(cols.map((c) => ref(g.retyped.get(c)!)))];
      return `${both(steps)} ${steps.length > 1 ? "change" : "changes"} the type of ${both(cols)} in ${table}`;
    };
    if (
      (def || g.cols.size || g.retyped.size) &&
      !g.migration &&
      !(def && def.store.migration?.trim())
    ) {
      const what = def
        ? `${capital(ref(def))} creates table ${table}`
        : [
            ...(g.cols.size ? [whose([...g.cols.keys()])] : []),
            ...(g.retyped.size ? [retypedWhose()] : []),
          ]
            .map((x, k) => (k === 0 ? capital(x) : x))
            .join(" and ");
      issue(
        "delta.no-migration",
        table,
        `${what} without naming the migration: give store.migration${def ? " on that step" : ""}, ${migrationAdvice(e, table)}.`,
        g.repo,
      );
    }
    if (def && !def.store.retention?.trim())
      out.push({
        rule: "delta.no-retention",
        target: table,
        message: `${capital(ref(def))} creates table ${table} without saying how long its rows are kept: give store.retention on that step.`,
        blocking: true,
        repo: g.repo,
        // How long rows are kept is a person's decision, asked once for the table.
        ask: `How long are the rows of the new table ${table} kept?`,
      });
  }
  for (const f of p.flows)
    if (f.how === "changed" && !seen.has(f.id) && !reads.some((r) => r.flow === f.id))
      issue(
        "delta.flow-missing",
        f.id,
        `The feature changes flow ${f.id}, but there is no delta for it.`,
        e.flowById.get(f.id)?.repo ?? p.change,
      );
  for (const n of p.newFlows)
    if (!deltas.some((d) => d.change === "new" && d.repo === n.repo))
      issue(
        "delta.new-flow-missing",
        `${n.repo}:${n.name}`,
        `The feature needs a new flow in ${n.repo} ("${n.name}"), but no delta adds one there.`,
        n.repo,
      );
  // B-arch, check 2: every breaking contract change lists the consumers the map knows.
  out.push(...consumerIssues(deltas, e));
  return out;
}

/** Interface changes, from the deltas: a call-out or publish added, changed or removed. */
/** gRPC's status codes, as written in code and in words: INVALID_ARGUMENT and InvalidArgument. */
const GRPC_CODES = [
  "CANCELLED",
  "UNKNOWN",
  "INVALID_ARGUMENT",
  "DEADLINE_EXCEEDED",
  "NOT_FOUND",
  "ALREADY_EXISTS",
  "PERMISSION_DENIED",
  "RESOURCE_EXHAUSTED",
  "FAILED_PRECONDITION",
  "ABORTED",
  "OUT_OF_RANGE",
  "UNIMPLEMENTED",
  "INTERNAL",
  "UNAVAILABLE",
  "DATA_LOSS",
  "UNAUTHENTICATED",
];
const pascal = (c: string) =>
  c
    .toLowerCase()
    .split("_")
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join("");
/**
 * The gRPC codes a text names, each as the code (INVALID_ARGUMENT): the code, or its PascalCase
 * name (InvalidArgument); a one-word name (Internal, Unknown) only qualified (StatusCode.Internal),
 * since it is a plain word too.
 */
function grpcCodesIn(text: string): string[] {
  return GRPC_CODES.filter((c) => {
    const name = c.includes("_") ? pascal(c) : `(?:StatusCode|Status|codes|Code)\\.${pascal(c)}`;
    return new RegExp(`(^|[^A-Za-z_])(${c}|${name})([^A-Za-z_]|$)`).test(text);
  });
}

/**
 * B-run2-fixes 10: an added or changed step of a flow an rpc starts that answers a gRPC status
 * today's flow doesn't (its steps and error paths name none such) changes the rpc's contract:
 * its callers get an error they didn't. One row per rpc, with each new status.
 */
function newRpcStatuses(d: FlowDelta, e: Estate) {
  const spec = e.flowById.get(d.flow);
  const today = spec?.flow;
  const ep = e.byId.get(today?.trigger.ref ?? "") as
    { kind?: string; endpointType?: string; pathOrTopic?: string } | undefined;
  if (!today || ep?.kind !== "Endpoint" || ep.endpointType !== "grpc" || !ep.pathOrTopic) return [];
  const had = new Set(
    grpcCodesIn(
      [...today.steps.map((s) => s.what), ...today.errors.flatMap((x) => [x.when, x.then])].join(
        "\n",
      ),
    ),
  );
  const added = [
    ...new Set(
      d.steps
        .filter((s) => s.op !== "remove")
        .flatMap((s) => grpcCodesIn(s.what ?? ""))
        .filter((c) => !had.has(c)),
    ),
  ];
  return added.length
    ? [
        {
          flow: d.flow,
          caller: "its callers",
          callee: today.component,
          operation: ep.pathOrTopic,
          status: "planned-modify",
          fields: added.map((c) => `error status ${c}`),
        },
      ]
    : [];
}

export function interfaceChanges(deltas: FlowDelta[], e: Estate) {
  const out: {
    flow: string;
    caller: string;
    callee: string;
    operation: string;
    status: string;
    fields: string[];
  }[] = [];
  for (const d of deltas) {
    const today = e.flowById.get(d.flow)?.flow;
    const caller = today?.component ?? d.flow.split(".")[0]!;
    out.push(...newRpcStatuses(d, e));
    for (const s of d.steps) {
      const old = s.step ? today?.steps[s.step - 1] : undefined;
      const kind = s.kind ?? old?.kind;
      // The flow's own entry point changes when its entry or response gains or loses fields.
      if ((kind === "entry" || kind === "respond") && s.op === "change" && today) {
        const was = new Set([...(old?.data?.reads ?? []), ...(old?.data?.returns ?? [])]);
        const now = [...(s.fields?.reads ?? []), ...(s.fields?.returns ?? [])];
        const ep = e.byId.get(today.trigger.ref ?? "") as
          { method?: string; pathOrTopic?: string } | undefined;
        if (ep?.pathOrTopic && now.some((f) => !was.has(f)))
          out.push({
            flow: d.flow,
            caller: "its callers",
            callee: today.component,
            operation: `${ep.method ?? ""} ${ep.pathOrTopic}`.trim(),
            status: "planned-modify",
            fields: now.filter((f) => !was.has(f)),
          });
        continue;
      }
      if (kind !== "call-out" && kind !== "publish") continue;
      const to =
        s.to ??
        (old?.to ? { component: old.to.component, entry: old.to.entry, new: false } : undefined);
      if (!to) continue;
      out.push({
        flow: d.flow,
        caller,
        callee: to.component,
        operation: to.entry,
        status:
          s.op === "remove"
            ? "planned-retire"
            : s.op === "add" || to.new
              ? "planned-new"
              : "planned-modify",
        fields: [...(s.fields?.sends ?? []), ...(s.fields?.returns ?? [])],
      });
    }
  }
  return out;
}

/** Data changes, from the deltas: new tables, and columns the catalog doesn't have. */
/** A step that marks a table new: where the change defines it. */
export interface TableDefinition {
  flow: string;
  /** The step's place in its delta's steps, from 1. */
  change: number;
  repo: string;
  store: NonNullable<FlowDelta["steps"][number]["store"]>;
}

/**
 * The tables the change creates, each with the steps that mark it new, the definition first
 * (ADR 0111 addendum). Every delta of the change is read before any is rendered or checked, so
 * a table created by a flow that sorts after the flows that use it is still the change's new
 * table. Where several steps mark it new, the definition is the one that carries a migration,
 * then the one with the most columns, then the first in flow order: the facts it holds, not
 * where it sorts.
 */
export function tableDefinitions(
  deltas: FlowDelta[],
  counts: (table: string) => boolean = () => true,
): Map<string, TableDefinition[]> {
  const defs = new Map<string, TableDefinition[]>();
  for (const d of deltas)
    d.steps.forEach((s, i) => {
      if (s.op === "remove" || !s.store?.new || !counts(s.store.table)) return;
      const list = defs.get(s.store.table) ?? [];
      list.push({ flow: d.flow, change: i + 1, repo: d.repo, store: s.store });
      defs.set(s.store.table, list);
    });
  const weight = (x: TableDefinition) => [
    x.store.migration?.trim() ? 1 : 0,
    x.store.columns.length,
  ];
  for (const [t, list] of defs)
    defs.set(
      t,
      list
        .map((x, i) => ({ x, i }))
        .sort((a, b) => {
          const [ma, ca] = weight(a.x);
          const [mb, cb] = weight(b.x);
          return mb! - ma! || cb! - ca! || a.i - b.i;
        })
        .map((y) => y.x),
    );
  return defs;
}

export function dataChanges(deltas: FlowDelta[], e: Estate) {
  const out: {
    flow: string;
    table: string;
    /** changed columns: the step only gives columns the table has other types (B-arch). */
    change: "new table" | "new columns" | "changed columns";
    columns: string[];
    types: Record<string, string>;
    classification: Record<string, string>;
    migration?: string;
    retention?: string;
    keys?: Record<string, { references: string; onDelete: string }>;
    /** Columns the table has that get another type, from and to (B-arch). */
    retyped?: Record<string, { from: string; to: string }>;
  }[] = [];
  // R1: every table the change creates is known before any block is read, and is written once,
  // from its definition; a block that uses it (in any flow, before or after) adds no columns.
  const defs = tableDefinitions(deltas);
  const extraOf = (store: TableDefinition["store"]) => ({
    types: store.types ?? {},
    classification: store.classification ?? {},
    ...(store.migration ? { migration: store.migration } : {}),
    ...(store.retention ? { retention: store.retention } : {}),
    ...(store.keys && Object.keys(store.keys).length ? { keys: store.keys } : {}),
  });
  /** A step's kind: its own, else today's step's it changes. */
  const kindOf = (d: FlowDelta, s: DeltaStep) =>
    s.kind ?? (s.step ? e.flowById.get(d.flow)?.flow.steps[s.step - 1]?.kind : undefined);
  /** The columns each table's writes in this change name (B-fixes, problem 4). */
  const written = new Map<string, Set<string>>();
  for (const d of deltas)
    for (const s of d.steps)
      if (s.store && s.op !== "remove" && kindOf(d, s) === "write")
        for (const c of s.store.columns)
          written.set(s.store.table, (written.get(s.store.table) ?? new Set()).add(c));
  for (const d of deltas)
    for (const s of d.steps) {
      if (!s.store || s.op === "remove") continue;
      // A key-pattern store has no columns and no migrations: what it holds is no data change.
      if (isKeyPattern(e, s.store.table)) continue;
      const def = defs.get(s.store.table)?.[0];
      if (def) {
        if (!out.some((x) => x.table === def.store.table && x.change === "new table"))
          out.push({
            flow: def.flow,
            table: def.store.table,
            change: "new table",
            columns: def.store.columns,
            ...extraOf(def.store),
          });
        continue;
      }
      const extra = extraOf(s.store);
      const have = columnsOf(e, s.store.table);
      // A read or lookup naming a column a write of this change adds leaves it to the write,
      // whose migration, types and classification data.md gives (B-fixes, problem 4).
      const reads = kindOf(d, s) === "read" || kindOf(d, s) === "lookup";
      const add = s.store.columns.filter(
        (c) => !have.has(c) && !(reads && written.get(s.store!.table)?.has(c)),
      );
      const ret = retypedColumns(e, s.store);
      const retyped = ret.length
        ? { retyped: Object.fromEntries(ret.map((r) => [r.column, { from: r.from, to: r.to }])) }
        : {};
      if (
        add.length &&
        !out.some((x) => x.table === s.store!.table && add.every((c) => x.columns.includes(c)))
      )
        out.push({
          flow: d.flow,
          table: s.store.table,
          change: "new columns",
          columns: add,
          ...extra,
          ...retyped,
        });
      else if (
        !add.length &&
        ret.length &&
        !out.some(
          (x) =>
            x.table === s.store!.table && ret.every((r) => x.retyped?.[r.column] !== undefined),
        )
      )
        out.push({
          flow: d.flow,
          table: s.store.table,
          change: "changed columns",
          columns: ret.map((r) => r.column),
          ...extra,
          ...retyped,
        });
    }
  return out;
}

/** "new columns hold_id", and the types it changes after them (B-arch). */
function dataChangeWords(c: ReturnType<typeof dataChanges>[number]): string {
  const retyped = Object.keys(c.retyped ?? {});
  if (c.change === "changed columns") return `changed types of ${retyped.join(", ")}`;
  const base = `${c.change} ${c.columns.join(", ")}`;
  return retyped.length ? `${base}; changed types of ${retyped.join(", ")}` : base;
}

/** data.md in the shape the critic and the story planner read (a Data store | Table | Change table). */
export function renderData(deltas: FlowDelta[], e: Estate): string | undefined {
  const changes = dataChanges(deltas, e);
  if (!changes.length) return undefined;
  const rec = (table: string) =>
    e.byId.get(table) as { dataStore?: string; name?: string } | undefined;
  const store = (table: string) => rec(table)?.dataStore ?? table.split(".")[0]!;
  const name = (table: string) => rec(table)?.name ?? table.split(".").pop()!;
  const retypes = (c: (typeof changes)[number]) =>
    Object.entries(c.retyped ?? {}).map(([x, r]) => `change column ${x} from ${r.from} to ${r.to}`);
  const rows = changes.map((c) => {
    const cols = c.columns
      .filter((x) => !c.retyped?.[x])
      .map((x) => `${x} ${c.types[x] ?? ""}`.trim());
    const what =
      c.change === "new table"
        ? `new table ${name(c.table)} (${cols.join(", ")})`
        : [...cols.map((x) => `add column ${x}`), ...retypes(c)].join("; ");
    return `| ${store(c.table)} | ${name(c.table)} | ${what} | ${c.migration ?? ""} |`;
  });
  const classified = changes.flatMap((c) =>
    c.columns
      .filter((x) => c.classification[x] && !c.retyped?.[x])
      .map((x) => `- ${x} in ${name(c.table)} is ${c.classification[x]}.`),
  );
  const kept = changes
    .filter((c) => c.retention)
    .map(
      (c) =>
        `- Rows of ${name(c.table)} are kept for ${c.retention!.replace(/^kept for\s+/i, "")}.`,
    );
  const keyed = changes.flatMap((c) =>
    Object.entries(c.keys ?? {}).map(
      ([col, k]) =>
        `- ${name(c.table)}.${col} references ${k.references}; on delete ${k.onDelete}.`,
    ),
  );
  return [
    `${MARK} from the target flows (target-flows/). Edit the flows and run the stage again. -->`,
    "# Data",
    "",
    "## Changes",
    "",
    "| Data store | Table | Change | Migration |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    "## Backfill, classification and retention",
    "",
    ...(classified.length || kept.length ? [...classified, ...kept] : ["- Nothing stated yet."]),
    "",
    // S4: the foreign keys the change declares, from the table's one definition.
    ...(keyed.length ? ["## Keys", "", ...keyed, ""] : []),
    "## Where each change comes from",
    "",
    ...changes.map((c) => `- ${c.table}: ${dataChangeWords(c)}, for flow ${c.flow}.`),
    "",
  ].join("\n");
}

export function renderArchitecture(
  deltas: FlowDelta[],
  e: Estate,
  reads: ReadFlow[] = [],
  deploy?: DeployStep[],
): string {
  const lines = [
    `${MARK} from feature.yaml and the repos' specs. The target-flows/ files are the source; edit them and run the stage again. -->`,
    "# Design",
    "",
    "## Target flows",
    "",
  ];
  for (const d of deltas) {
    const today = e.flowById.get(d.flow)?.flow;
    lines.push(
      `### ${d.change === "new" ? `New flow ${d.flow}: ${d.name ?? ""}` : `${d.flow}: ${today?.name ?? ""}`} (${d.repo}, ${d.change})`,
      "",
      d.why,
      "",
    );
    for (const s of d.steps) {
      const fields = [...fieldNames(s.fields), ...(s.store?.columns ?? [])];
      const where = s.op === "add" ? `after step ${s.after ?? 0}` : `step ${s.step}`;
      lines.push(
        `- ${s.op} ${where}${s.kind ? ` (${s.kind})` : ""}: ${s.what ?? today?.steps[(s.step ?? 1) - 1]?.what ?? ""}${s.to ? ` → ${s.to.component} ${s.to.entry}${s.to.new ? " (new)" : ""}` : ""}${s.store ? ` [${s.store.table}${s.store.new ? ", new" : ""}]` : ""}${fields.length ? `; fields ${[...new Set(fields)].join(", ")}` : ""}`,
      );
    }
    lines.push("");
  }
  const readName = (id: string) => {
    const n = e.flowById.get(id)?.flow.name;
    return n ? ` (${n})` : "";
  };
  if (reads.length) {
    lines.push(
      "## Flows read, unchanged",
      "",
      "The change reads or relies on these flows without changing a step, so they have no target flow.",
      "",
    );
    for (const r of reads) lines.push(`- ${r.flow}${readName(r.flow)}: ${r.why}`);
    lines.push("");
  }
  const ifs = interfaceChanges(deltas, e);
  lines.push("## Interface changes", "");
  if (ifs.length) {
    lines.push(
      "| Caller | Callee | Operation | Status | Fields | Flow |",
      "| --- | --- | --- | --- | --- | --- |",
    );
    for (const i of ifs)
      lines.push(
        `| ${i.caller} | ${i.callee} | ${i.operation} | ${i.status} | ${i.fields.join(", ")} | ${i.flow} |`,
      );
  } else lines.push("None.");
  const data = dataChanges(deltas, e);
  lines.push("", "## Data changes", "");
  if (data.length)
    for (const x of data) lines.push(`- ${x.table}: ${dataChangeWords(x)} (${x.flow})`);
  else lines.push("None.");
  lines.push("");
  // B-arch: the breaking contract changes with who they break, and the deploy order drafted.
  lines.push(...renderBreaking(deltas, e), ...renderDeploy(deploy));
  return lines.join("\n");
}

/**
 * Write the target flows (one flow delta per file), design.md and data.md (unless a person wrote
 * them) and the flows only read. Shared by the architecture stage and the fast path (ADR 0113).
 */
export async function writeTargetFlows(
  dir: string,
  answer: { flows: FlowDelta[]; reads?: ReadFlow[]; deploy?: DeployStep[] },
  estate: Estate,
  by = "atticus change architecture",
): Promise<string[]> {
  const readsFile = join(dir, ...READS_FILE.split("/"));
  const deployFile = join(dir, ...DEPLOY_FILE.split("/"));
  const deploy = answer.deploy?.length ? answer.deploy : undefined;
  const a = splitAnswer(answer);
  const keep = new Set(a.deltas.map((d) => `${d.flow}.yaml`));
  for (const f of await readdir(join(dir, TARGET_DIR)).catch(() => [] as string[]))
    if (f.endsWith(".yaml") && !keep.has(f)) await rm(join(dir, TARGET_DIR, f), { force: true });
  const files: string[] = [];
  for (const d of a.deltas) {
    // ADR 0111: pinned to the version of today's flow it was written against.
    const today = d.change === "new" ? undefined : estate.flowById.get(d.flow)?.flow;
    const pinned: FlowDelta = {
      ...d,
      schemaVersion: FLOW_DELTA_SCHEMA_VERSION,
      ...(today ? { base: { steps: flowBase(today) } } : {}),
    };
    await writeFileAtomic(
      join(dir, TARGET_DIR, `${d.flow}.yaml`),
      `# The target of flow ${d.flow} (ADR 0087): the steps this change adds, changes or removes. Drafted by ${by}; base pins the version of today's flow it was written against (ADR 0111).\n${stringify(FlowDelta.parse(pinned), { lineWidth: 0 })}`,
    );
    files.push(`${TARGET_DIR}/${d.flow}.yaml`);
  }
  // design.md carries the target flows for people and the critic, unless a person wrote it.
  const own = await readFile(join(dir, "design.md"), "utf8").catch(() => undefined);
  if (own === undefined || own.startsWith(MARK)) {
    await writeFileAtomic(
      join(dir, "design.md"),
      renderArchitecture(a.deltas, estate, a.reads, deploy),
    );
    files.push("design.md");
  }
  // B-arch: the deploy order as drafted, read back with the target flows.
  if (deploy)
    await writeFileAtomic(
      deployFile,
      `# The order the change deploys in across its repos (ADR 0124 addendum B-arch), as the architecture stage drafted it and its checks passed. Atticus writes this file.\n${stringify({ deploy }, { lineWidth: 0 })}`,
    );
  else await rm(deployFile, { force: true });
  if (a.reads.length)
    await writeFileAtomic(
      readsFile,
      `# The flows the change reads without changing a step (ADR 0087): context, not target flows. Atticus writes this file.\n${stringify({ reads: a.reads }, { lineWidth: 0 })}`,
    );
  else await rm(readsFile, { force: true });
  // data.md too, from the data changes, unless a person wrote it.
  const data = renderData(a.deltas, estate);
  const ownData = await readFile(join(dir, "data.md"), "utf8").catch(() => undefined);
  if (data && (ownData === undefined || ownData.startsWith(MARK))) {
    await writeFileAtomic(join(dir, "data.md"), data);
    files.push("data.md");
  } else if (!data && ownData?.startsWith(MARK)) await rm(join(dir, "data.md"), { force: true });
  return files;
}

/**
 * Where a finding's target is in the target-flow files, as metarepo path:line (P1): "flow#n"
 * and "flow#n:column" are the n-th step of that flow's file; "flow" is the file's first line;
 * a table ("store.table[:columns]") is the first step that marks it new, else the first that
 * names it. Read off the files' syntax tree: a fact, not a guess.
 */
export async function locateInTargetFlows(
  dir: string,
  rel: string,
  target: string,
): Promise<string | undefined> {
  const files = (await readdir(join(dir, TARGET_DIR)).catch(() => [] as string[]))
    .filter((f) => f.endsWith(".yaml"))
    .sort();
  type Doc = { file: string; text: string; doc: ReturnType<typeof parseDocument>; lc: LineCounter };
  const docs: Doc[] = [];
  for (const f of files) {
    const text = await readFile(join(dir, TARGET_DIR, f), "utf8").catch(() => undefined);
    if (text === undefined) continue;
    const lc = new LineCounter();
    docs.push({ file: f, text, doc: parseDocument(text, { lineCounter: lc }), lc });
  }
  const at = (d: Doc, offset: number) =>
    `${rel}/${TARGET_DIR}/${d.file}:${d.lc.linePos(offset).line}`;
  const steps = (d: Doc) => {
    const s = d.doc.get("steps");
    return isSeq(s) ? s.items : [];
  };
  const m = /^(.+?)#(\d+)(?::.*)?$/.exec(target);
  const flow = m ? m[1]! : target;
  const own = docs.find((d) => d.doc.get("flow") === flow);
  if (own) {
    if (!m) return `${rel}/${TARGET_DIR}/${own.file}:1`;
    const item = steps(own)[Number(m[2]) - 1] as { range?: [number, number, number] } | undefined;
    return item?.range ? at(own, item.range[0]) : `${rel}/${TARGET_DIR}/${own.file}:1`;
  }
  const table = target.split(":")[0]!;
  let first: string | undefined;
  for (const d of docs)
    for (const item of steps(d)) {
      const store = isMap(item) ? item.get("store") : undefined;
      if (!isMap(store) || store.get("table") !== table) continue;
      const where = (item as { range?: [number, number, number] }).range;
      const here = where ? at(d, where[0]) : undefined;
      if (store.get("new") === true) return here;
      first ??= here;
    }
  return first;
}

/** The target flows and the flows only read, as they are in the change folder. */
export async function readTargetFlows(dir: string): Promise<ArchitectureAnswer | undefined> {
  const r = await readDeltas(dir);
  if (!r.deltas.length) return undefined;
  const t = await readFile(join(dir, ...READS_FILE.split("/")), "utf8").catch(() => undefined);
  const reads = t === undefined ? undefined : z.array(ReadFlow).safeParse(parse(t)?.reads);
  const dt = await readFile(join(dir, ...DEPLOY_FILE.split("/")), "utf8").catch(() => undefined);
  const deploy = dt === undefined ? undefined : z.array(DeployStep).safeParse(parse(dt)?.deploy);
  return {
    flows: r.deltas,
    reads: reads?.success ? reads.data : [],
    ...(deploy?.success && deploy.data.length ? { deploy: deploy.data } : {}),
  };
}

export async function architectureStage(
  root: string,
  changeId: string,
  o: StageOptions,
): Promise<StageResult<ArchitectureAnswer>> {
  const change = await changeStore(root)
    .read(changeId)
    .catch((e: Error) => {
      throw new PlannerError("not-found", e.message);
    });
  const dir = changeFolder(root, change.id);
  const rel = `${changesRelOf(root)}/${change.id}`;
  await refuseWhileEarlierStuck(root, await loadChangeContext(root), change, "architecture");
  const placement = await readPlacement(dir);
  if (!placement)
    throw new PlannerError(
      "refused",
      `${change.id} has no feature yet: run atticus change feature ${change.id} first.`,
    );
  const ctx = await loadChangeContext(root);
  const estate = await loadEstate(root, ctx.records);
  const knowledge = await readKnowledge(root);
  const patterns = knowledge.items.filter((i) => i.kind === "Pattern" || i.kind === "Decision");

  const touched = placement.flows.map((f) => estate.flowById.get(f.id)).filter((x) => !!x);
  const flowsText = touched
    .map(
      (f) =>
        `# ${f!.flow.id} (repo ${f!.repo}). Steps are numbered from 1 in the order listed.\n${serializeRecord(f!.flow)}`,
    )
    .join("\n---\n");
  const sources: SourceInput[] = [
    {
      // As it is on disk, so a line the drafter cites (feature.yaml:N) is the file's line N.
      id: "feature.yaml",
      kind: "artifact",
      origin: `${rel}/feature.yaml`,
      text: (await readFile(join(dir, "feature.yaml"), "utf8")).replace(/\r\n/g, "\n"),
      classification: "internal",
      priority: 100,
    },
    {
      id: "flows",
      kind: "catalog",
      origin: "the repos' specs (specs/<repo>/)",
      text: flowsText || "The feature touches no existing flow.",
      classification: "internal",
      priority: 95,
    },
    // ADR 0111 addendum: how the stores the change may write name their migrations and types.
    ...storeFactsSource(estate, placement),
    // S2: the values the code allows in the columns of the tables the change may store into.
    ...allowedValuesSource(estate, tablesFor(estate, placement)),
    // B-arch: who calls the entries and uses the tables of the flows the change touches.
    ...consumersSource(estate, placement),
    // ADR 0113: the files attached to the change, each cited by file and line or page.
    ...(await changeInputSources(dir, rel)).map((s): SourceInput => ({
      id: s.id,
      kind: "document",
      origin: s.origin,
      text: s.text,
      classification: "internal",
      priority: 85,
    })),
  ];
  // B2 (c): a pattern sent in full carries its rules, a decision what it decided, since the
  // drafter is told to follow them; in one line, its title and when it applies, as before.
  const lineOf = (i: (typeof patterns)[number], level: Level) =>
    i.kind === "Pattern" || i.kind === "Decision" ? patternLine(i, level) : "";
  // B-run2-fixes 11: the estate of the repos the change touches, their systems and neighbours.
  const scope = scopeRepos(estate, [
    ...placement.flows.flatMap((f) => {
      const r = estate.flowById.get(f.id)?.repo;
      return r ? [r] : [];
    }),
    ...placement.newFlows.map((f) => f.repo),
  ]);
  const whole: SourceInput[] = [
    {
      id: "estate-index",
      kind: "catalog",
      origin: "atticus change architecture (deterministic)",
      text: estateIndex(estate, scope),
      classification: "internal",
      priority: 80,
    },
    ...(patterns.length
      ? [
          {
            id: "patterns",
            kind: "document" as const,
            origin: "knowledge/items (ADR 0083)",
            text: patterns.map((i) => lineOf(i, "full")).join("\n"),
            classification: "internal",
            priority: 70,
          },
        ]
      : []),
  ];
  // H2: the closest past corrections of this stage, when there are any (else nothing changes).
  const past = await pastCorrectionsSource(root, {
    stage: "architecture",
    change: change.id,
    touches: {
      repos: [
        ...touched.map((f) => f!.repo),
        ...placement.newFlows.map((f) => f.repo),
        ...change.touches.repos,
      ],
      tables: [...tablesFor(estate, placement), ...change.touches.tables],
      flows: placement.flows.map((f) => f.id),
      systems: change.systems,
    },
    budget: stageBudget(ctx, ARCHITECTURE_AGENT),
  });
  if (past) sources.push(past.source);
  const instructions = [
    "# Flow architect",
    "",
    `Write the target flows for the change "${change.title}": for every flow the feature touches, the steps added, changed or removed, with their fields; and the new flows. The feature, today's flows and the estate are below, as data.`,
    "",
    formatFor(classificationLevels(ctx)),
    "",
    SELF_CHECK_RULE,
    ...(past ? ["", past.rule] : []),
  ].join("\n");
  // The estate and the patterns the placement and today's flows lead to (ADR 0107), or all.
  const patternById = new Map(patterns.map((i) => [i.id, i]));
  const selected = await estateContext(
    root,
    "architecture",
    {
      text: [stringify(placement, { lineWidth: 0 }), flowsText].join("\n\n"),
      title: change.title,
      ids: [...placement.flows.map((f) => f.id), ...placement.features.map((f) => f.id)],
    },
    {
      estate,
      budget: stageBudget(ctx, ARCHITECTURE_AGENT),
      others: [instructionSource(instructions), ...sources],
      ...(o.context ? { context: o.context } : {}),
      exclude: [change.id, ...inScope(estate, scope).outside],
      change: change.id,
      ai: stageRetrievalAi(ctx, o, `change architecture ${change.id}`),
      origin: "atticus change architecture (context engine)",
      priority: 80,
      knowledge: {
        kinds: ["Pattern", "Decision"],
        line: (id, level) => {
          const i = patternById.get(id);
          return i ? lineOf(i, level) : undefined;
        },
        id: "patterns",
        origin: "knowledge/items (ADR 0083), selected",
        priority: 70,
      },
      sections: { origin: "the wikis and documents (ADR 0116), selected", priority: 69 },
    },
  );
  if (selected && "waiting" in selected)
    return retrievalWaiting(change.id, "architecture", selected);
  let context: ContextReport = wholeLists();
  if (selected && "sources" in selected) {
    sources.push(...selected.sources);
    context = selected.report;
  } else {
    sources.push(...whole);
    if (selected) context = { ...context, note: selected.note };
  }
  const approved = change.handoffs.some((h) => h.phase === "define" && h.state === "merged");

  const spec: StageSpec<ArchitectureAnswer> = {
    stage: "architecture",
    agent: ARCHITECTURE_AGENT,
    description:
      "Writes a change's target flows: the steps each touched flow adds, changes or removes, with fields.",
    output: "architecture-answer.yaml",
    source: `${TARGET_DIR}/`,
    instructions,
    ...(context.gaps?.length ? { gaps: context.gaps } : {}),
    sources,
    parse: (text) => {
      const r = parseYamlAs(
        text,
        Answer,
        (d) => ({
          // The version and the pin are Atticus's (ADR 0111), never the assistant's.
          flows: (Array.isArray(d.flows) ? d.flows : []).map((f: Record<string, unknown>) => {
            const { base: _base, schemaVersion: _v, ...rest } = f ?? {};
            return { ...rest, schemaVersion: FLOW_DELTA_SCHEMA_VERSION };
          }),
          ...(d.reads !== undefined && d.reads !== null ? { reads: d.reads } : {}),
          ...(d.deploy !== undefined && d.deploy !== null ? { deploy: d.deploy } : {}),
        }),
        "target-flows",
      );
      if (!r.value) return { issues: r.issues };
      // An empty modify delta is handed back (the check refuses it) and is never written: it
      // moves to the reads, so the answer the stage keeps has no empty delta.
      const issues = [...r.issues, ...emptyDeltaIssues(r.value.flows)];
      const { deltas, reads } = splitAnswer(r.value);
      return {
        answer: { flows: deltas, reads, ...(r.value.deploy ? { deploy: r.value.deploy } : {}) },
        issues,
      };
    },
    check: async (a, c) => [
      ...checkDeltas(a.flows, estate, placement, a.reads, {
        levels: classificationLevels(ctx),
        templates: ctx.orgPack.specTemplates,
        ...(c?.onFile ? { onFile: true } : {}),
      }),
      // B-arch, check 4: the deploy order puts a callee before its caller, a migration first.
      ...deployIssues(a.flows, a.deploy, estate),
      // B-places: an added step's place is a file of its repo, a line it has, a function in it.
      ...(await placeIssues(a.flows, estate, root)),
      // W5: an endpoint the brief names whose flow the design leaves alone (a note, not blocking).
      ...briefEndpointNotes(
        await readFile(join(dir, "brief.md"), "utf8").catch(() => ""),
        estate,
        a.flows,
      ),
    ],
    write: (answer) => writeTargetFlows(dir, answer, estate),
    reviewSources: (a) => [mergedFlowsSource(a.flows, estate, rel)],
    current: () => readTargetFlows(dir),
    currentProblems: async () => (await readDeltas(dir)).problems,
    locate: (i) => locateInTargetFlows(dir, rel, i.target),
  };
  const retrieved = selected && "sources" in selected ? selected : undefined;
  if (retrieved?.retrieval && (retrieved.retrieval.expansion || retrieved.retrieval.rerank))
    spec.retrieval = retrieved.retrieval;
  const res = await runStageLoop(
    root,
    change.id,
    spec,
    retrieved?.consumed || (selected && "consumed" in selected && selected.consumed)
      ? withoutResume(o)
      : o,
  );
  res.context = context;
  await recordKnowledge(root, change.id, "architecture", context);
  if (!approved)
    res.notes.unshift(
      `The feature PR of ${change.id} isn't merged yet, so these target flows rest on a feature a person hasn't approved.`,
    );
  return res;
}

/** The org pack's data classification levels (pack.yaml), or the built-in four without one. */
export const classificationLevels = (ctx: { orgPack: { pack?: { classification: string[] } } }) =>
  ctx.orgPack.pack?.classification ?? ["public", "internal", "confidential", "restricted"];
