/** A modify delta that adds, changes and removes nothing: context, not a delta. */
export const isEmptyDelta = (d: FlowDelta) => d.change === "modify" && d.steps.length === 0;

/** The check's refusal of each empty modify delta, handed back to the assistant. */
export function emptyDeltaIssues(deltas: FlowDelta[]): StageIssue[] {
  return deltas.filter(isEmptyDelta).map((d) => ({
    rule: "delta.empty",
    target: d.flow,
    message: `Flow ${d.flow} is marked modify but adds, changes and removes no step. A flow the change only reads or relies on is context, not a target flow: list it under reads with why. If the change does change it, give the steps.`,
    blocking: true,
    repo: d.repo,
  }));
}

/**
 * The deltas to write and the flows only read: an empty modify delta moves to the reads
 * (with its why), so it is never written as a target flow.
 */
export function splitAnswer(a: { flows: FlowDelta[]; reads?: ReadFlow[] }): {
  deltas: FlowDelta[];
  reads: ReadFlow[];
} {
  const reads = [...(a.reads ?? [])];
  for (const d of a.flows.filter(isEmptyDelta))
    if (!reads.some((r) => r.flow === d.flow)) reads.push({ flow: d.flow, why: d.why });
  return { deltas: a.flows.filter((d) => !isEmptyDelta(d)), reads };
}

export async function readDeltas(
  dir: string,
): Promise<{ deltas: FlowDelta[]; problems: string[] }> {
  const deltas: FlowDelta[] = [];
  const problems: string[] = [];
  for (const f of (await readdir(join(dir, TARGET_DIR)).catch(() => [] as string[])).sort()) {
    if (!f.endsWith(".yaml")) continue;
    try {
      const r = FlowDelta.safeParse(parse(await readFile(join(dir, TARGET_DIR, f), "utf8")));
      if (r.success) deltas.push(r.data);
      else
        problems.push(
          `${TARGET_DIR}/${f}: ${r.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`,
        );
    } catch (e) {
      problems.push(`${TARGET_DIR}/${f}: ${(e as Error).message.split("\n")[0]}`);
    }
  }
  return { deltas, problems };
}

