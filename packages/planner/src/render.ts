import type { PlanContext } from "./context.js";
import type { StoryProse } from "./prose.js";
import type { PlanSkeleton, StorySkeleton, TaskPlan } from "./skeleton.js";

/**
 * The planning artifacts as Markdown, in the shapes the critic, the Spec Kit hand-down and
 * Run with AI read: `stories/<id>.md` (title, the As a / I want / so that line, an
 * "Acceptance criteria" list in Given/When/Then form), `stories.md` (a Story | Title | Repos |
 * Depends on table) and `tasks.md` (checkbox tasks with ids under a `## <repo>` heading).
 */

export const GENERATED_MARK = "<!-- Generated by atticus plan";

const sentence = (s: string) => (/[.!?]$/.test(s) ? s : `${s}.`);
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const ENGINE_LINE: Record<string, string> = {
  speckit:
    "Build engine: speckit (each task runs as a Spec Kit feature in the repo, under specs/<task id>/).",
  atticus:
    "Build engine: atticus (each task is handed down as .atticus/tasks/<task id>.md in the repo).",
};

export function renderStory(ctx: PlanContext, s: StorySkeleton, p: StoryProse): string {
  const lines = [
    `${GENERATED_MARK} stories from the approved design. Edit the wording freely; links, systems and repos come from the design. -->`,
    `# ${p.title}`,
    "",
    `As ${/^[aeiou]/i.test(p.asA) ? "an" : "a"} ${p.asA} I want ${p.iWant} so that ${sentence(p.soThat)}`,
    "",
    "## Acceptance criteria",
    "",
    ...(p.criteria.length
      ? p.criteria.map(
          (c) =>
            `- Given ${c.given}, when ${c.when}, then ${sentence(c.then)}${c.trace ? ` (${c.trace})` : ""}`,
        )
      : ["- None yet."]),
    "",
    "## Traces to",
    "",
    s.trace
      ? `${s.trace.path}:${s.trace.line} (${s.trace.text})`
      : "Nothing in the brief, proposal or specs yet.",
    "",
    "## Links",
    "",
    ...s.interfaces.map(
      (i) =>
        `- Interface ${i.id === "new" ? "(new)" : i.id}: ${i.caller} → ${i.callee} ${i.operation} (${i.status}, interfaces.md:${i.line})`,
    ),
    ...s.data.map((d) => `- Record ${d.tableId}: ${d.change} (data.md:${d.line})`),
    ...s.features.map((f) => `- Feature ${f}`),
    ...(s.interfaces.length + s.data.length + s.features.length === 0 ? ["- None"] : []),
    "",
    "## Systems and repos",
    "",
    `${s.systems.join(", ") || "none"}${s.repos.length ? ` (${s.repos.join(", ")})` : ""}`,
    "",
    "## Tests",
    "",
    s.tests.join(", ") || "none required by the test strategy",
    "",
    "## Depends on",
    "",
    s.dependsOn.length ? s.dependsOn.join(", ") : "Nothing.",
    "",
  ];
  if (s.openQuestions.length)
    lines.push(
      "## Open questions",
      "",
      ...s.openQuestions.map(
        (q) =>
          `- ${sentence(q.text)}${q.owner || q.from ? ` (${[q.owner, q.from].filter(Boolean).join("; ")})` : ""}`,
      ),
      "",
    );
  if (p.notes) lines.push("## Notes", "", p.notes, "");
  if (p.by === "fallback")
    lines.push(
      "## Wording",
      "",
      "The story writer gave no prose for this story; a person words it.",
      "",
    );
  return lines.join("\n").replace(/\n+$/, "\n");
}

export function renderIndex(skeleton: PlanSkeleton, prose: Map<string, StoryProse>): string {
  const lines = [
    `${GENERATED_MARK} stories from the approved design. -->`,
    "# Stories",
    "",
    "| Story | Title | Repos | Depends on |",
    "| --- | --- | --- | --- |",
    ...skeleton.stories.map(
      (s) =>
        `| ${s.id} | ${cell(prose.get(s.id)?.title ?? s.key)} | ${s.repos.join(", ")} | ${s.dependsOn.join(", ")} |`,
    ),
    "",
  ];
  if (skeleton.notPlanned.length)
    lines.push(
      "## Not planned",
      "",
      ...skeleton.notPlanned.map((n) => `- ${n.what}: ${n.why} (interfaces.md:${n.line}).`),
      "",
    );
  if (skeleton.uncoveredTests.length)
    lines.push(
      "## Tests no story needs",
      "",
      `The test strategy asks for ${skeleton.uncoveredTests.join(", ")}, which no story needs; check the strategy or add the work.`,
      "",
    );
  return lines.join("\n").replace(/\n+$/, "\n");
}

export function renderTasks(skeleton: PlanSkeleton, tasks: TaskPlan[]): string {
  const lines = [
    `${GENERATED_MARK} tasks from the stories. Tick them as they are done. -->`,
    "# Tasks",
    "",
  ];
  for (const r of skeleton.repos) {
    lines.push(`## ${r.id}`, "", ENGINE_LINE[r.engine] ?? `Build engine: ${r.engine}.`, "");
    for (const t of tasks.filter((x) => x.repo === r.id)) {
      lines.push(`- [ ] ${t.id} ${t.title} (story ${t.story})`);
      if (t.waitsFor.length) lines.push(`  - Waits for: ${t.waitsFor.join("; ")}`);
    }
    lines.push("");
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}
