import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { storyBar } from "../src/index.js";
import { CHANGE, changeDir, forgeChangeRoot } from "./helpers.js";

/**
 * The story bar reads the stories stage's current format (seventh UX walk, finding 9): a story
 * written from the target flows traces to its flow file and spec with no line number, names its
 * repo alone on the first line of "Systems and repos" with the build command under it, and its
 * tasks and criteria carry the change id, concrete example paths and the gateway's match
 * pattern. A story the stage and its critic passed is ready, and neither the change id nor the
 * generated lines count as names the catalog lacks.
 */

const ID = "show-the-status-in-the-portal-app";

const FLOW = `# The target of flow ledger-api.read-account-status (ADR 0087).
schemaVersion: 2
flow: ledger-api.read-account-status
repo: forge-ledger
change: new
name: Read an account's status
trigger:
  kind: endpoint
  what: the portal asks for an account's status
  entry: GET /accounts/{id}/status
steps:
  - op: add
    after: 0
    kind: entry
    what: Matches GET /accounts/*/status.
`;

const STORY = `<!-- Generated by atticus plan stories from the target flows (target-flows/). Edit the wording freely; tasks, fields and evidence come from the flows. -->
# The ledger answers an account's status

As a portal customer I want the ledger to answer my account's status so that I can see whether my account is open.

## Context

The new flow ledger-api.read-account-status, started by GET /accounts/{id}/status, has 1 step.

## Tasks

### Task 1.1: Add the entry step: Matches GET /accounts/*/status

- Step: add (entry), item 1 of target-flows/ledger-api.read-account-status.yaml
- Prompt: tasks/1.1.prompt.md (atticus task ${ID} 1.1)

## Acceptance criteria

Task 1.1:

- Given account 42 is open, when GET /accounts/42/status arrives, then it answers status open.
- Given the path has no account id, when GET /accounts//status arrives, then the ledger answers 404.

## Tests

unit, contract

## Depends on

None.

## Definition of done

- Integration tests across the repos in their deploy order (1 repo (forge-ledger)).

## Traces to

target-flows/ledger-api.read-account-status.yaml (new flow ledger-api.read-account-status: Read an account's status); specs/transfer-limits/spec.md

## Systems and repos

forge-ledger

Build and test with \`node -e "console.log('ledger build ok')"\`.
`;

async function currentFormatRoot(story = STORY): Promise<string> {
  const root = await forgeChangeRoot();
  const from = changeDir(root);
  const dir = changeDir(root, ID);
  await cp(from, dir, { recursive: true });
  await rm(from, { recursive: true, force: true });
  const yaml = await readFile(join(dir, "change.yaml"), "utf8");
  await writeFile(join(dir, "change.yaml"), yaml.replaceAll(CHANGE, ID));
  await mkdir(join(dir, "target-flows"), { recursive: true });
  await mkdir(join(dir, "stories"), { recursive: true });
  await writeFile(join(dir, "target-flows/ledger-api.read-account-status.yaml"), FLOW);
  await writeFile(join(dir, "stories/s1-read-account-status.md"), story);
  return root;
}

describe("the story bar on a story in the stories stage's current format", () => {
  it("is ready: traced to its flow and spec, its repo named, nothing invented", async () => {
    const root = await currentFormatRoot();
    const bar = await storyBar(root, ID);
    expect(bar.stories).toEqual([
      expect.objectContaining({ id: "s1-read-account-status", problems: [], invented: [] }),
    ]);
    expect(bar.ready).toMatchObject({ passed: 1, total: 1 });
  });

  it("still flags a trace to a file the change doesn't have and a name nothing knows", async () => {
    const root = await currentFormatRoot(
      STORY.replace(
        "target-flows/ledger-api.read-account-status.yaml (new flow",
        "target-flows/ledger-api.gone.yaml (new flow",
      )
        .replace("; specs/transfer-limits/spec.md", "")
        .replace("Read an account's status", "Read the fraud-engine status"),
    );
    const [s] = (await storyBar(root, ID)).stories;
    expect(s!.problems).toEqual([
      "traces to target-flows/ledger-api.gone.yaml, which isn't in the change",
      "names what neither the catalog nor the design has: fraud-engine",
    ]);
  });
});
