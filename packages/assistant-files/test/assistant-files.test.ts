/** The Forge org pack with the forge-change and forge-speckit additions laid over it. */
async function metarepo(): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "atticus-assistant-files-"));
  await cp(join(FIXTURES, "forge/metarepo/org-pack"), join(root, "org-pack"), { recursive: true });
  await cp(join(FIXTURES, "forge-change/org-pack"), join(root, "org-pack"), { recursive: true });
  await cp(join(FIXTURES, "forge-speckit/org-pack"), join(root, "org-pack"), { recursive: true });
  return root;
}

const read = (root: string, rel: string) => readFile(join(root, rel), "utf8");

async function filesUnder(root: string, paths: string[]) {
  return Promise.all(paths.map(async (path) => ({ path, content: await read(root, path) })));
}

