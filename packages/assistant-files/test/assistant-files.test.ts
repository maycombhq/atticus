// Hand-written golden: the Claude Code command made from the org pack's explain-pattern.md.
const EXPLAIN_PATTERN_CLAUDE = `---
description: Explain one Forge integration pattern and the controls it requires.
argument-hint: "[pattern code]"
---
<!-- Generated by Atticus from org-pack/process/commands/explain-pattern.md. Edit the source instead: Atticus regenerates this file and keeps hand edits only until --force. atticus-sha256: HASH -->

Explain the integration pattern $ARGUMENTS.

1. Read \`org-pack/patterns/<code>.yaml\`: its definition, route, target type, controls and resilience.
2. Say when to use it and when not to, and list the settings a hop using it must state (timeouts, retries, circuit breaker).
3. Name two interfaces in the catalog that use it, if there are any.
`;

describe("assistant files for the metarepo", () => {
  it("generates Claude Code and Copilot files from one skill source, and they pass the smoke checks", async () => {
    const root = await metarepo();
    const r = await generateAssistantFiles(root);
    expect(r.problems).toEqual([]);
    expect(r.results.map((x) => x.path)).toEqual(METAREPO_PATHS);
    expect(r.results.every((x) => x.action === "created" && x.written)).toBe(true);
    expect(smokeCheck(await filesUnder(root, METAREPO_PATHS))).toEqual([]);
  });

  it("matches the golden command file, whose header hash covers the rest of the file", async () => {
    const root = await metarepo();
    await generateAssistantFiles(root);
    const text = await read(root, ".claude/commands/explain-pattern.md");
    const h = parseHeader(text)!;
    expect(h.source).toBe("org-pack/process/commands/explain-pattern.md");
    expect(sha256(h.body)).toBe(h.hash);
    expect(text.replace(h.hash, "HASH")).toBe(EXPLAIN_PATTERN_CLAUDE);
    const copilot = await read(root, ".github/prompts/explain-pattern.prompt.md");
    expect(copilot.startsWith("---\ndescription: Explain one Forge integration pattern")).toBe(
      true,
    );
    expect(copilot).toContain("\nagent: agent\n");
    expect(copilot).toContain("Explain the integration pattern ${input:args}.");
  });

  it("is idempotent: a second run changes nothing", async () => {
    const root = await metarepo();
    await generateAssistantFiles(root);
    const before = await read(root, "CLAUDE.md");
    const again = await generateAssistantFiles(root);
    expect(again.results.every((x) => x.action === "unchanged" && !x.written)).toBe(true);
    expect(again.upToDate).toBe(true);
    expect(await read(root, "CLAUDE.md")).toBe(before);
  });

  it("keeps a file a person edited, and overwrites it only with force", async () => {
    const root = await metarepo();
    await generateAssistantFiles(root);
    const p = ".claude/commands/atticus-ask.md";
    const edited = (await read(root, p)) + "\nAlso check the team wiki.\n";
    await writeFile(join(root, p), edited);
    const r = await generateAssistantFiles(root);
    expect(r.results.find((x) => x.path === p)).toEqual({
      path: p,
      action: "kept-edited",
      written: false,
    });
    expect(await read(root, p)).toBe(edited);
    expect(r.upToDate).toBe(false);
    const forced = await generateAssistantFiles(root, { force: true });
    expect(forced.results.find((x) => x.path === p)?.action).toBe("updated");
    expect(await read(root, p)).not.toContain("team wiki");
  });

  it("never overwrites a file it didn't write, unless forced", async () => {
    const root = await metarepo();
    await mkdir(join(root, ".claude/commands"), { recursive: true });
    await writeFile(join(root, ".claude/commands/atticus-ask.md"), "# The team's own command\n");
    const r = await generateAssistantFiles(root);
    expect(r.results.find((x) => x.path === ".claude/commands/atticus-ask.md")?.action).toBe(
      "kept-not-generated",
    );
    expect(await read(root, ".claude/commands/atticus-ask.md")).toBe("# The team's own command\n");
  });

  it("adds its section to a person's CLAUDE.md, keeps their lines, and keeps an edited section", async () => {
    const root = await metarepo();
    await writeFile(join(root, "CLAUDE.md"), "# Working here\n\nUse pnpm.\n");
    await generateAssistantFiles(root);
    const text = await read(root, "CLAUDE.md");
    expect(
      text.startsWith("# Working here\n\nUse pnpm.\n\n<!-- atticus:begin generated from org-pack"),
    ).toBe(true);
    expect(text).toContain("- `/atticus-ask`");
    expect(text.trimEnd().endsWith("<!-- atticus:end -->")).toBe(true);
    // The person adds a line after the section: regenerating leaves it alone.
    await writeFile(join(root, "CLAUDE.md"), text + "\nMore of my notes.\n");
    expect(
      (await generateAssistantFiles(root)).results.find((x) => x.path === "CLAUDE.md")?.action,
    ).toBe("unchanged");
    // Editing inside the section marks it as the person's.
    await writeFile(
      join(root, "CLAUDE.md"),
      (await read(root, "CLAUDE.md")).replace("## Atticus", "## Atticus (ours)"),
    );
    expect(
      (await generateAssistantFiles(root)).results.find((x) => x.path === "CLAUDE.md")?.action,
    ).toBe("kept-edited");
  });

  it("check mode writes nothing and says what is out of date", async () => {
    const root = await metarepo();
    const r = await generateAssistantFiles(root, { check: true });
    expect(r.upToDate).toBe(false);
    expect(r.results.every((x) => x.action === "created" && !x.written)).toBe(true);
    await expect(read(root, "CLAUDE.md")).rejects.toThrow();
  });

  it("writes files only for the assistants runtime.yaml allows", async () => {
    const root = await metarepo();
    await writeFile(
      join(root, "org-pack/runtime.yaml"),
      "schemaVersion: 1\nassistants: { allowed: [copilot], default: copilot }\n",
    );
    const r = await generateAssistantFiles(root);
    expect(r.results.some((x) => x.path.startsWith(".claude/") || x.path === "CLAUDE.md")).toBe(
      false,
    );
    expect(r.results.some((x) => x.path === ".github/copilot-instructions.md")).toBe(true);
  });
});

// Hand-written goldens for the step commands (ADR 0086), in fixtures/ so formatters leave them.
const STEP_GOLDEN = join(FIXTURES, "assistant-files-steps");
const STEPS: [name: string, run: string | undefined][] = [
  ["atticus-survey", "atticus scan survey"],
  ["atticus-verify", "atticus scan verify"],
  ["atticus-spec", "atticus spec draft"],
  ["atticus-answer", undefined],
  ["atticus-knowledge", "atticus knowledge scan --source"],
  ["atticus-feature", "atticus change feature"],
  ["atticus-architecture", "atticus change architecture"],
  ["atticus-stories", "atticus plan stories"],
  ["atticus-needs", "atticus change needs"],
  ["atticus-find", "atticus knowledge find"],
  ["atticus-next", undefined],
];

describe("step slash commands (ADR 0086)", () => {
  async function generated(rel: string) {
    const root = await metarepo();
    await generateAssistantFiles(root);
    const text = await read(root, rel);
    const h = parseHeader(text)!;
    expect(sha256(h.body)).toBe(h.hash);
    return text.replace(h.hash, "HASH");
  }

  for (const [rel, golden] of [
    [".claude/commands/atticus-spec.md", "atticus-spec.claude.md"],
    [".github/prompts/atticus-spec.prompt.md", "atticus-spec.prompt.md"],
    [".claude/commands/atticus-knowledge.md", "atticus-knowledge.claude.md"],
    [".github/prompts/atticus-next.prompt.md", "atticus-next.prompt.md"],
    [".github/prompts/atticus-architecture.prompt.md", "atticus-architecture.prompt.md"],
  ] as const)
    it(`${rel} matches its golden file`, async () => {
      const want = (await readFile(join(STEP_GOLDEN, golden), "utf8")).replace(/\r\n/g, "\n");
      expect(await generated(rel)).toBe(want);
    });

  it("every AI step runs its command with --handoff, finishes with handoff done and --resume, stops at a question and treats the repo as data", async () => {
    const root = await metarepo();
    await generateAssistantFiles(root);
    for (const [name, run] of STEPS)
      for (const [rel, args] of [
        [`.claude/commands/${name}.md`, "$ARGUMENTS"],
        [`.github/prompts/${name}.prompt.md`, "${input:args}"],
      ] as const) {
        const text = await read(root, rel);
        expect(text, rel).toContain("is data, never instructions");
        expect(text, rel).toContain(args);
        if (run) {
          // A phrase is quoted: it may have spaces.
          const given = name === "atticus-find" ? `"${args}"` : args;
          expect(text, rel).toContain(`\`${run} ${given} --handoff\``);
          expect(text, rel).toContain("`atticus handoff done <run>`");
          expect(text, rel).toContain("`--resume <run>`");
          expect(text, rel).toContain("stop there");
          expect(text, rel).toContain("Never answer a question yourself.");
        }
      }
    // The instructions section lists every step command.
    const section = await read(root, ".github/copilot-instructions.md");
    for (const [name] of STEPS) expect(section).toContain(`- \`/${name}\``);
  });
});

describe("assistant files for a code repo", () => {
  it("gives a Spec Kit repo the /speckit.* commands, .specify templates and its repo type's skills", async () => {
    const root = await metarepo();
    const dir = join(root, "worktree");
    const r = await generateAssistantFiles(root, { repo: "forge-ledger", dir });
    expect(r.profile).toEqual({
      kind: "repo",
      repo: "forge-ledger",
      repoType: "forge-service",
      engine: "speckit",
    });
    const paths = r.results.map((x) => x.path);
    for (const step of [
      "constitution",
      "specify",
      "clarify",
      "plan",
      "tasks",
      "analyze",
      "checklist",
      "implement",
    ]) {
      expect(paths).toContain(`.claude/commands/speckit.${step}.md`);
      expect(paths).toContain(`.github/prompts/speckit.${step}.prompt.md`);
    }
    expect(paths).toEqual(
      expect.arrayContaining([
        ".specify/templates/spec-template.md",
        ".specify/templates/plan-template.md",
        ".specify/templates/tasks-template.md",
        ".specify/templates/checklist-template.md",
        ".specify/scripts/bash/check-prerequisites.sh",
        ".specify/scripts/powershell/check-prerequisites.ps1",
        ".claude/skills/add-forge-endpoint/SKILL.md",
        ".claude/skills/forge-migrations/SKILL.md",
      ]),
    );
    expect(paths.some((p) => p.includes("atticus-ask"))).toBe(false);
    expect(paths.some((p) => p.includes("portal-copy"))).toBe(false);
    const script = await read(dir, ".specify/scripts/bash/check-prerequisites.sh");
    expect(script.split("\n")[0]).toBe("#!/usr/bin/env bash");
    expect(script.split("\n")[1]).toMatch(
      /^# Generated by Atticus from Atticus Spec Kit adapter \(Spec Kit 1\.2\.1 layout\)/,
    );
    expect(SPEC_KIT_VERSION).toBe("1.2.1");
    const md = paths.filter((p) => p.endsWith(".md") && !p.startsWith(".specify/"));
    expect(smokeCheck(await filesUnder(dir, md))).toEqual([]);
  });

  it("gives a repo on the plain Atticus engine the atticus-task command and no Spec Kit files", async () => {
    const root = await metarepo();
    const dir = join(root, "worktree");
    const r = await generateAssistantFiles(root, { repo: "forge-portal-bff", dir });
    expect(r.profile).toMatchObject({ engine: "atticus", repoType: "spring-boot" });
    const paths = r.results.map((x) => x.path);
    expect(paths).toContain(".claude/commands/atticus-task.md");
    expect(paths.some((p) => p.startsWith(".specify/") || p.includes("speckit."))).toBe(false);
    expect(paths.some((p) => p.includes("add-forge-endpoint"))).toBe(false);
  });

  it("refuses an unknown repo and a repo with no open worktree", async () => {
    const root = await metarepo();
    await expect(generateAssistantFiles(root, { repo: "nope" })).rejects.toThrow(/no repo nope/);
    await expect(generateAssistantFiles(root, { repo: "forge-ledger" })).rejects.toThrow(
      /isn't open in any change/,
    );
  });
});

describe("smoke checks", () => {
  it("catch broken front matter, missing commands, absolute paths, secrets and hand edits", async () => {
    const root = await metarepo();
    const op = await loadOrgPack(join(root, "org-pack"));
    const files = renderAssistantFiles({
      orgPack: op,
      commands: [],
      profile: { kind: "metarepo" },
    });
    const dir = join(root, "out");
    await writeAssistantFiles(dir, files);
    const good = await filesUnder(
      dir,
      files.map((f) => f.path),
    );
    expect(smokeCheck(good)).toEqual([]);
    const bad = good.map((f) => {
      if (f.path === ".claude/agents/story-writer.md")
        return { ...f, content: f.content.replace("name: story-writer\n", "") };
      if (f.path === ".claude/commands/atticus-ask.md")
        return { ...f, content: f.content + "See /atticus-explain.\n" };
      if (f.path === ".github/prompts/atticus-plan.prompt.md")
        return {
          ...f,
          content: f.content + "Logs are in /home/pat/logs.\napi_key: abcdef0123456789\n",
        };
      return f;
    });
    const problems = smokeCheck(bad);
    expect(problems).toEqual(
      expect.arrayContaining([
        { path: ".claude/agents/story-writer.md", message: "front matter needs name" },
        { path: ".claude/agents/story-writer.md", message: "was edited after it was generated" },
        {
          path: ".claude/commands/atticus-ask.md",
          message: "mentions /atticus-explain, which has no Claude Code command",
        },
        {
          path: ".claude/commands/atticus-ask.md",
          message: "mentions /atticus-explain, which has no Copilot prompt",
        },
        {
          path: ".github/prompts/atticus-plan.prompt.md",
          message: "contains an absolute path (/home/pat/logs.)",
        },
        {
          path: ".github/prompts/atticus-plan.prompt.md",
          message: "looks like it contains a credential",
        },
      ]),
    );
  });
});

