import { describe, expect, it } from "vitest";
import { candidatesIn, commentLinesOf, commentStyleOf, isCommentLine } from "../src/index.js";

// Fifth review of ADR 0196: a C-family file's comment lines are read by a small lexer that keeps
// its state across lines (strings, template literals, raw strings, block comments, nesting where
// the language nests them), not by a regex per line. Each case is in Forge and Northwind names.

/** The lines of a file, each with whether it reads as all comment. */
const flags = (file: string, ...ls: string[]) => {
  const got = commentLinesOf(file, ls);
  return ls.map((l, i) => [l, got[i]] as const);
};
/** Lines marked `C` read as comment, the rest as code. */
const expectLines = (file: string, ...ls: [mark: "C" | "-", line: string][]) =>
  expect(flags(file, ...ls.map(([, l]) => l))).toEqual(ls.map(([m, l]) => [l, m === "C"]));

describe("a `/*` that opens no block (fifth review of ADR 0196)", () => {
  it("inside a string, in JavaScript, TypeScript and Java", () => {
    expectLines(
      "scripts/forge-build.js",
      ["-", 'const CLEAN = "rm -rf build /*";'],
      ["-", "const app = express();"],
      ["-", 'app.get("/api/live", live);'],
    );
    expectLines(
      "src/portal/files.js",
      ["-", "const ROOT = '/files /*';"],
      ["-", "router.get('/live', live);"],
      ["-", "app.use('/api', router);"],
    );
    expectLines(
      "src/main/java/forge/ledger/LiveResource.java",
      ["-", '@RequestMapping("/api")'],
      ["-", "class LiveResource {"],
      ["-", '  static final String Q = "SELECT a /*+ FIRST_ROWS";'],
      ["-", '  @GetMapping("/live")'],
      ["-", "  public String live() { return Q; }"],
      ["-", "}"],
    );
    // an escaped quote doesn't end the string
    expectLines(
      "src/portal/a.ts",
      ["-", 'const s = "say \\" /* hi";'],
      ["-", 'app.get("/api/live", live);'],
    );
  });

  it("after a line comment with no space before it", () => {
    expectLines(
      "src/portal/server.ts",
      ["-", "foo();// legacy /* note"],
      ["-", 'app.get("/api/live", live);'],
      ["C", "// a line comment /* still no block"],
      ["-", 'app.get("/api/ready", ready);'],
    );
  });

  it("inside a template literal across lines, and with `${…}` nested in it", () => {
    expectLines(
      "src/portal/banner.ts",
      ["-", "const banner = `"],
      ["-", "  build output /*"],
      ["-", "`;"],
      ["-", 'app.get("/api/live", live);'],
    );
    expectLines(
      "src/portal/list.js",
      ["-", 'const msg = `total ${items.map((i) => `${i.name} /* `).join(",")}`;'],
      ["-", 'app.get("/api/live", live);'],
      ["-", "const page = `"],
      ["-", "  <p>${user.name /* who */}</p>"],
      ["-", "  /* template text, no comment"],
      ["-", "`;"],
      ["-", "const o = `${{ a: 1 }.a} /*`;"],
      ["-", 'app.get("/api/ready", ready);'],
    );
  });

  it("inside a Go raw string, a Java text block, a C# verbatim string and a regex literal", () => {
    expectLines(
      "cmd/forge/main.go",
      ["-", "const usage = `"],
      ["-", "  globs: /*"],
      ["-", "`"],
      ["-", 'func main() { http.HandleFunc("/api/live", live) }'],
    );
    expectLines(
      "src/main/java/forge/ledger/Queries.java",
      ["-", '  static final String Q = """'],
      ["-", "      SELECT a /*+ FIRST_ROWS"],
      ["-", "      FROM ledger"],
      ["-", '      """;'],
      ["-", '  @GetMapping("/live")'],
    );
    expectLines(
      "src/Northwind.Api/Paths.cs",
      ["-", '    var dir = @"C:\\ledger\\"; var q = "/*";'],
      ["-", '    app.MapGet("/api/live", Live);'],
    );
    expectLines(
      "src/portal/trim.js",
      ["-", 'const trim = (s) => s.replace(/\\/*$/, "");'],
      ["-", "const half = total / 2; // a /* in a comment"],
      ["-", 'app.get("/api/live", live);'],
    );
  });

  it("closes a triple-quoted string at the last of its quotes, and reads a byte-order mark as space", () => {
    expectLines(
      "gradle/release.gradle.kts",
      ["-", '  .replace("""name = "$old"""", """name = "$new""""))'],
      ["C", "  // Update the ledger's version"],
      ["-", '  ledger.writeText("forge")'],
    );
    expectLines(
      "src/Northwind.Api/Program.cs",
      ["C", "﻿// <auto-generated />"],
      ["-", "﻿using System;"],
    );
  });

  it("still opens a real block comment, after code, and reads its inner lines as comment", () => {
    expectLines(
      "src/portal/routes.js",
      ["-", 'const CLEAN = "rm -rf build /*";'],
      ["C", "/* removed:"],
      ["C", '   app.get("/api/balances", balances) */'],
      ["-", 'app.get("/api/live", live);'],
      ["-", "live(); /* trailing"],
      ["C", '   app.get("/api/old", old);'],
      ["-", "*/ app.get('/api/ready', ready);"],
    );
  });
});

describe("JSX comments (fifth review of ADR 0196)", () => {
  it("reads `{/* … */}` and its multi-line form as comment", () => {
    expectLines(
      "src/portal/App.tsx",
      ["-", "<Routes>"],
      ["C", '  {/* <Route path="/old" element={<Old />} /> */}'],
      ["C", "  {/*"],
      ["C", '  <Route path="/old-balances" element={<OldBalances />} />'],
      ["C", "  */}"],
      ["-", '  <Route path="/balances" element={<Balances />} />'],
      ["-", "</Routes>"],
    );
  });
});

describe("nested block comments (fifth review of ADR 0196)", () => {
  it("nest in Kotlin, Rust, Swift, Scala and Dart", () => {
    for (const file of [
      "src/main/kotlin/forge/Ledger.kt",
      "src/ledger.rs",
      "Sources/Ledger/Ledger.swift",
      "src/main/scala/forge/Ledger.scala",
      "lib/ledger.dart",
    ])
      expectLines(
        file,
        ["C", "/* outer"],
        ["C", "   /* inner */"],
        ["C", '   @GetMapping("/balances")'],
        ["C", "*/"],
        ["-", "fun balances() {}"],
      );
  });

  it("don't nest in Java, C#, JavaScript or Go: the first `*/` closes", () => {
    for (const file of [
      "src/main/java/forge/Ledger.java",
      "src/Ledger.cs",
      "src/ledger.js",
      "ledger.go",
    ])
      expectLines(
        file,
        ["C", "/* outer"],
        ["C", "   /* inner */"],
        ["-", '   @GetMapping("/balances")'],
      );
  });

  it("reads a Rust lifetime as no quote", () => {
    expectLines(
      "src/ledger.rs",
      ["-", "fn name<'a>(x: &'a str) -> &'a str { x }"],
      ["C", "/* removed:"],
      ["C", '   #[get("/balances")] */'],
      ["-", "let c = '\\''; let d = '/';"],
      ["-", '#[get("/live")]'],
    );
  });
});

describe("PHP docblocks and `.inc` files (fifth review of ADR 0196)", () => {
  it("reads a docblock's annotation route as code, the rest of the docblock as comment", () => {
    const F = "src/Controller/BlogController.php";
    expectLines(
      F,
      ["-", "<?php"],
      ["C", "/**"],
      ["C", " * Lists the posts."],
      ["-", ' * @Route("/blog", name="blog_list")'],
      ["-", ' * @Method({"GET"})'],
      ["C", " * @param int $page"],
      ["C", " */"],
      ["-", "public function list(int $page) {}"],
      ["-", '/** @Route("/blog/{id}", name="blog_show") */'],
      ["C", '// @Route("/old")'],
      ["C", '# @Route("/older")'],
      ["C", '/* @Route("/oldest") */'],
      ["-", '#[Route("/live")]'],
      ["C", "/**"],
      ["-", ' * @ORM\\Table(name="posts")'],
      ["-", ' * @Rest\\Get("/api/posts")'],
      ["C", " */"],
    );
    expect(isCommentLine(' * @Route("/blog", name="blog_list")', F)).toBe(false);
    expect(isCommentLine(" * Lists the posts.", F)).toBe(true);
  });

  it("reads a `.inc` file as PHP only when it holds `<?php`", () => {
    const php = ["<?php", "# a comment", "$x = 1;"];
    const c = ["#define LEDGER 1", "/* a", "   block */", "int ledger;"];
    expect(commentStyleOf("includes/ledger.inc", php.join("\n"))).toBe("php");
    expect(commentStyleOf("include/ledger.inc", c.join("\n"))).toBe("c");
    expect(commentStyleOf("include/ledger.inc")).toBe("c");
    expect(commentLinesOf("includes/ledger.inc", php)).toEqual([false, true, false]);
    expect(commentLinesOf("include/ledger.inc", c)).toEqual([false, true, true, false]);
    expect(isCommentLine("# a comment", "includes/ledger.inc", php)).toBe(true);
    expect(isCommentLine("# a comment", "include/ledger.inc", c)).toBe(false);
  });
});

describe("the skipped lines read by the lexer too (fifth review of ADR 0196)", () => {
  it("lists a path below a `/*` in a string, and none from a comment", () => {
    const ls = [
      'const CLEAN = "rm -rf build /*";',
      'app.get("/api/live", live);',
      'foo(); /* was app.get("/api/old") */ app.get("/api/ready", ready);',
      "/* removed:",
      '   app.get("/api/balances", balances) */',
      '{/* <Route path="/old-balances" /> */}',
    ];
    expect(candidatesIn("src/portal/server.js", ls).map((c) => [c.line, c.value])).toEqual([
      [2, "/api/live"],
      [3, "/api/ready"],
    ]);
  });
});

describe("the lexer's cost (fifth review of ADR 0196)", () => {
  it("reads a 60,000-line TypeScript file in linear time", () => {
    const block = [
      "/**",
      " * A ledger handler.",
      " */",
      'const CLEAN = "rm -rf build /*";',
      "const msg = `total ${items.map((i) => `${i.name}`).join(',')}`;",
      "foo();// legacy /* note",
      'app.get("/api/live", (req, res) => res.send(`/* ${req.id} */`));',
      "{/* <Route path='/old' /> */}",
      "const re = /\\/*$/;",
      "",
    ];
    const make = (n: number) => Array.from({ length: n }, (_, i) => block[i % block.length]!);
    const small = make(60_000);
    const big = make(240_000);
    commentLinesOf("src/portal/big.ts", small); // warm
    let t = performance.now();
    const got = commentLinesOf("src/portal/big.ts", small);
    const tSmall = performance.now() - t;
    t = performance.now();
    commentLinesOf("src/portal/big.ts", big);
    const tBig = performance.now() - t;
    expect(got.slice(0, 10)).toEqual([
      true,
      true,
      true,
      false,
      false,
      false,
      false,
      true,
      false,
      false,
    ]);
    // a generous bound on a loaded machine; linear: four times the lines, not sixteen times the time
    expect(tSmall).toBeLessThan(2000);
    expect(tBig).toBeLessThan(Math.max(tSmall * 10, 200));
  });
});
