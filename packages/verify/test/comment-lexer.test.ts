import { describe, expect, it } from "vitest";
import { candidatesIn, commentLinesOf, commentStyleOf, isCommentLine } from "../src/index.js";

// Fifth review of ADR 0196: a C-family file's comment lines are read by a small lexer that keeps
// its state across lines (strings, template literals, raw strings, block comments, nesting where
// the language nests them), not by a regex per line. Each case is in Forge and Northwind names.

/** The lines of a file, each with whether it reads as all comment. */
const flags = (file: string, ...ls: string[]) => {
  const got = commentLinesOf(file, ls);
  return ls.map((l, i) => [l, got[i]] as const);
};
/** Lines marked `C` read as comment, the rest as code. */
const expectLines = (file: string, ...ls: [mark: "C" | "-", line: string][]) =>
  expect(flags(file, ...ls.map(([, l]) => l))).toEqual(ls.map(([m, l]) => [l, m === "C"]));

describe("a `/*` that opens no block (fifth review of ADR 0196)", () => {
  it("inside a string, in JavaScript, TypeScript and Java", () => {
    expectLines(
      "scripts/forge-build.js",
      ["-", 'const CLEAN = "rm -rf build /*";'],
      ["-", "const app = express();"],
      ["-", 'app.get("/api/live", live);'],
    );
    expectLines(
      "src/portal/files.js",
      ["-", "const ROOT = '/files /*';"],
      ["-", "router.get('/live', live);"],
      ["-", "app.use('/api', router);"],
    );
    expectLines(
      "src/main/java/forge/ledger/LiveResource.java",
      ["-", '@RequestMapping("/api")'],
      ["-", "class LiveResource {"],
      ["-", '  static final String Q = "SELECT a /*+ FIRST_ROWS";'],
      ["-", '  @GetMapping("/live")'],
      ["-", "  public String live() { return Q; }"],
      ["-", "}"],
    );
    // an escaped quote doesn't end the string
    expectLines(
      "src/portal/a.ts",
      ["-", 'const s = "say \\" /* hi";'],
      ["-", 'app.get("/api/live", live);'],
    );
  });

  it("after a line comment with no space before it", () => {
    expectLines(
      "src/portal/server.ts",
      ["-", "foo();// legacy /* note"],
      ["-", 'app.get("/api/live", live);'],
      ["C", "// a line comment /* still no block"],
      ["-", 'app.get("/api/ready", ready);'],
    );
  });

  it("inside a template literal across lines, and with `${…}` nested in it", () => {
    expectLines(
      "src/portal/banner.ts",
      ["-", "const banner = `"],
      ["-", "  build output /*"],
      ["-", "`;"],
      ["-", 'app.get("/api/live", live);'],
    );
    expectLines(
      "src/portal/list.js",
      ["-", 'const msg = `total ${items.map((i) => `${i.name} /* `).join(",")}`;'],
      ["-", 'app.get("/api/live", live);'],
      ["-", "const page = `"],
      ["-", "  <p>${user.name /* who */}</p>"],
      ["-", "  /* template text, no comment"],
      ["-", "`;"],
      ["-", "const o = `${{ a: 1 }.a} /*`;"],
      ["-", 'app.get("/api/ready", ready);'],
    );
  });

  it("inside a Go raw string, a Java text block, a C# verbatim string and a regex literal", () => {
    expectLines(
      "cmd/forge/main.go",
      ["-", "const usage = `"],
      ["-", "  globs: /*"],
      ["-", "`"],
      ["-", 'func main() { http.HandleFunc("/api/live", live) }'],
    );
    expectLines(
      "src/main/java/forge/ledger/Queries.java",
      ["-", '  static final String Q = """'],
      ["-", "      SELECT a /*+ FIRST_ROWS"],
      ["-", "      FROM ledger"],
      ["-", '      """;'],
      ["-", '  @GetMapping("/live")'],
    );
    expectLines(
      "src/Northwind.Api/Paths.cs",
      ["-", '    var dir = @"C:\\ledger\\"; var q = "/*";'],
      ["-", '    app.MapGet("/api/live", Live);'],
    );
    expectLines(
      "src/portal/trim.js",
      ["-", 'const trim = (s) => s.replace(/\\/*$/, "");'],
      ["-", "const half = total / 2; // a /* in a comment"],
      ["-", 'app.get("/api/live", live);'],
    );
  });

  it("closes a triple-quoted string at the last of its quotes, and reads a byte-order mark as space", () => {
    expectLines(
      "gradle/release.gradle.kts",
      ["-", '  .replace("""name = "$old"""", """name = "$new""""))'],
      ["C", "  // Update the ledger's version"],
      ["-", '  ledger.writeText("forge")'],
    );
    expectLines(
      "src/Northwind.Api/Program.cs",
      ["C", "﻿// <auto-generated />"],
      ["-", "﻿using System;"],
    );
  });

  it("still opens a real block comment, after code, and reads its inner lines as comment", () => {
    expectLines(
      "src/portal/routes.js",
      ["-", 'const CLEAN = "rm -rf build /*";'],
      ["C", "/* removed:"],
      ["C", '   app.get("/api/balances", balances) */'],
      ["-", 'app.get("/api/live", live);'],
      ["-", "live(); /* trailing"],
      ["C", '   app.get("/api/old", old);'],
      ["-", "*/ app.get('/api/ready', ready);"],
    );
  });
});

