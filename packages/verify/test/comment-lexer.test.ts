describe("nested block comments (fifth review of ADR 0196)", () => {
  it("nest in Kotlin, Rust, Swift, Scala and Dart", () => {
    for (const file of [
      "src/main/kotlin/forge/Ledger.kt",
      "src/ledger.rs",
      "Sources/Ledger/Ledger.swift",
      "src/main/scala/forge/Ledger.scala",
      "lib/ledger.dart",
    ])
      expectLines(
        file,
        ["C", "/* outer"],
        ["C", "   /* inner */"],
        ["C", '   @GetMapping("/balances")'],
        ["C", "*/"],
        ["-", "fun balances() {}"],
      );
  });

  it("don't nest in Java, C#, JavaScript or Go: the first `*/` closes", () => {
    for (const file of [
      "src/main/java/forge/Ledger.java",
      "src/Ledger.cs",
      "src/ledger.js",
      "ledger.go",
    ])
      expectLines(
        file,
        ["C", "/* outer"],
        ["C", "   /* inner */"],
        ["-", '   @GetMapping("/balances")'],
      );
  });

  it("reads a Rust lifetime as no quote", () => {
    expectLines(
      "src/ledger.rs",
      ["-", "fn name<'a>(x: &'a str) -> &'a str { x }"],
      ["C", "/* removed:"],
      ["C", '   #[get("/balances")] */'],
      ["-", "let c = '\\''; let d = '/';"],
      ["-", '#[get("/live")]'],
    );
  });
});

describe("PHP docblocks and `.inc` files (fifth review of ADR 0196)", () => {
  it("reads a docblock's annotation route as code, the rest of the docblock as comment", () => {
    const F = "src/Controller/BlogController.php";
    expectLines(
      F,
      ["-", "<?php"],
      ["C", "/**"],
      ["C", " * Lists the posts."],
      ["-", ' * @Route("/blog", name="blog_list")'],
      ["-", ' * @Method({"GET"})'],
      ["C", " * @param int $page"],
      ["C", " */"],
      ["-", "public function list(int $page) {}"],
      ["-", '/** @Route("/blog/{id}", name="blog_show") */'],
      ["C", '// @Route("/old")'],
      ["C", '# @Route("/older")'],
      ["C", '/* @Route("/oldest") */'],
      ["-", '#[Route("/live")]'],
      ["C", "/**"],
      ["-", ' * @ORM\\Table(name="posts")'],
      ["-", ' * @Rest\\Get("/api/posts")'],
      ["C", " */"],
    );
    expect(isCommentLine(' * @Route("/blog", name="blog_list")', F)).toBe(false);
    expect(isCommentLine(" * Lists the posts.", F)).toBe(true);
  });

  it("reads a `.inc` file as PHP only when it holds `<?php`", () => {
    const php = ["<?php", "# a comment", "$x = 1;"];
    const c = ["#define LEDGER 1", "/* a", "   block */", "int ledger;"];
    expect(commentStyleOf("includes/ledger.inc", php.join("\n"))).toBe("php");
    expect(commentStyleOf("include/ledger.inc", c.join("\n"))).toBe("c");
    expect(commentStyleOf("include/ledger.inc")).toBe("c");
    expect(commentLinesOf("includes/ledger.inc", php)).toEqual([false, true, false]);
    expect(commentLinesOf("include/ledger.inc", c)).toEqual([false, true, true, false]);
    expect(isCommentLine("# a comment", "includes/ledger.inc", php)).toBe(true);
    expect(isCommentLine("# a comment", "include/ledger.inc", c)).toBe(false);
  });
});

describe("the skipped lines read by the lexer too (fifth review of ADR 0196)", () => {
  it("lists a path below a `/*` in a string, and none from a comment", () => {
    const ls = [
      'const CLEAN = "rm -rf build /*";',
      'app.get("/api/live", live);',
      'foo(); /* was app.get("/api/old") */ app.get("/api/ready", ready);',
      "/* removed:",
      '   app.get("/api/balances", balances) */',
      '{/* <Route path="/old-balances" /> */}',
    ];
    expect(candidatesIn("src/portal/server.js", ls).map((c) => [c.line, c.value])).toEqual([
      [2, "/api/live"],
      [3, "/api/ready"],
    ]);
  });
});

describe("the lexer's cost (fifth review of ADR 0196)", () => {
  it("reads a 60,000-line TypeScript file in linear time", () => {
    const block = [
      "/**",
      " * A ledger handler.",
      " */",
      'const CLEAN = "rm -rf build /*";',
      "const msg = `total ${items.map((i) => `${i.name}`).join(',')}`;",
      "foo();// legacy /* note",
      'app.get("/api/live", (req, res) => res.send(`/* ${req.id} */`));',
      "{/* <Route path='/old' /> */}",
      "const re = /\\/*$/;",
      "",
    ];
    const make = (n: number) => Array.from({ length: n }, (_, i) => block[i % block.length]!);
    const small = make(60_000);
    const big = make(240_000);
    commentLinesOf("src/portal/big.ts", small); // warm
    let t = performance.now();
    const got = commentLinesOf("src/portal/big.ts", small);
    const tSmall = performance.now() - t;
    t = performance.now();
    commentLinesOf("src/portal/big.ts", big);
    const tBig = performance.now() - t;
    expect(got.slice(0, 10)).toEqual([
      true,
      true,
      true,
      false,
      false,
      false,
      false,
      true,
      false,
      false,
    ]);
    // a generous bound on a loaded machine; linear: four times the lines, not sixteen times the time
    expect(tSmall).toBeLessThan(2000);
    expect(tBig).toBeLessThan(Math.max(tSmall * 10, 200));
  });
});

// Sixth review of ADR 0196: a doc block's annotation read by hand (the regex backtracked cubically
// on a long run of spaces), PHP heredocs and backticks, Rust raw strings and strings across lines,
// a `/` after `}` or `++` read as a division, Dart raw strings, and a leading `*` outside a block.
describe("the sixth review of ADR 0196", () => {
  const spaces = " ".repeat(10_000);

  it("reads a doc block's line of 10,000 spaces in PHP at once", () => {
    const F = "src/Controller/LedgerController.php";
    for (const ls of [
      ["<?php", "/**", spaces, " */"],
      ["<?php", "/**", `${spaces}x`, " */"],
      ["<?php", "/**", `${spaces}*${spaces}*${spaces}`, " */"],
      ["<?php", `/**${spaces}*${spaces}@Rout`, " */"],
    ]) {
      const t = performance.now();
      const got = commentLinesOf(F, ls);
      expect(performance.now() - t).toBeLessThan(50);
      expect(got.slice(1)).toEqual(ls.slice(1).map(() => true));
    }
    // a line alone (no file around it): read as a doc block's line, and as fast
    const t = performance.now();
    expect(isCommentLine(`*${spaces}`, F)).toBe(true);
    expect(isCommentLine(`${spaces}*${spaces}*${spaces}x`, F)).toBe(true);
    expect(performance.now() - t).toBeLessThan(50);
    // the annotation is still read after the spaces
    expectLines(
      F,
      ["-", "<?php"],
      ["C", "/**"],
      ["-", `${spaces}*${spaces}@Route("/ledger")`],
      ["-", `/**${spaces}@Route("/ledger/{id}")`],
      ["C", " */"],
    );
  });

  it("reads the comment markers of a long line in each other style in linear time", () => {
    for (const [file, l] of [
      ["src/ledger.ts", `${spaces}*${spaces}`],
      ["config/ledger.yaml", `${spaces}#${spaces}`],
      ["db/ledger.sql", `${spaces}/*${spaces}*/${spaces}/`],
      ["config/ledger.xml", `${spaces}<!--${spaces}-->${spaces}`],
      ["docs/ledger.txt", `${spaces}#${spaces}`],
      ["config/ledger.ini", `${spaces};${spaces}`],
    ] as const) {
      const t = performance.now();
      isCommentLine(l, file);
      expect(performance.now() - t, file).toBeLessThan(50);
    }
  });

  it("reads a PHP heredoc and nowdoc to their closing label, and backticks across lines", () => {
    const F = "src/Controller/LedgerController.php";
    expectLines(
      F,
      ["-", "<?php"],
      ["-", "$x = <<<MD"],
      ["-", "See [docs](/api/*) and don't"],
      ["-", "MD;"],
      ["-", "$app->get('/api/live', $h);"],
    );
    expectLines(
      F,
      ["-", "<?php"],
      ["-", "$help = <<<'TXT'"],
      ["-", "    globs: /* and # and //"],
      ["-", "    TXTS is no end"],
      ["-", "    TXT, $app->get('/api/live', $h));"],
      ["-", "$app->get('/api/ready', $h);"],
      ["C", "// a comment"],
    );
    expectLines(
      F,
      ["-", "<?php"],
      ["-", '$sql = <<< "SQL"'],
      ["-", "  SELECT a /*+ FIRST_ROWS"],
      ["-", "  SQL;"],
      ["-", "$app->get('/api/live', $h);"],
    );
    expectLines(
      F,
      ["-", "<?php"],
      ["-", "$o = `ls /var/www/*`;"],
      ["-", "$app->get('/api/live', $h);"],
      ["-", "$p = `find /srv \\` -name '*'"],
      ["-", "  | grep /*`;"],
      ["-", "$app->get('/api/ready', $h);"],
    );
    // a `"` string spans lines in PHP
    expectLines(
      F,
      ["-", "<?php"],
      ["-", '$s = "first'],
      ["-", "  /* not a comment"],
      ["-", '  end";'],
      ["-", "$app->get('/api/live', $h);"],
    );
  });

  it("reads Rust raw strings, byte raw strings and strings across lines", () => {
    expectLines(
      "src/ledger.rs",
      ["-", 'let j = r#"{"path": "/api/*"}"#;'],
      ["-", '#[get("/api/live")]'],
      ["-", 'let b = br##"a "# /* b"##; let c = r"/*";'],
      ["-", '#[get("/api/ready")]'],
      ["-", 'let m = r#"'],
      ["-", '  {"glob": "/*"}'],
      ["-", '"#;'],
      ["-", "let r#type = 1; // a raw identifier"],
      ["-", '#[get("/api/balances")]'],
      ["C", "/* a comment */"],
    );
    expectLines(
      "src/ledger.rs",
      ["-", 'let s = "first'],
      ["-", "  /* not a comment"],
      ["-", '  end";'],
      ["-", '#[get("/api/live")]'],
      ["-", 'let t = "a \\'],
      ["-", '  /* b";'],
      ["-", '#[get("/api/ready")]'],
      ["C", "// a comment"],
    );
  });

  it("reads a `/` after `}` before `/>`, after `++` or `--`, and after `}` in JSX as a division", () => {
    const jsx =
      '<Routes><Route path="/" element={<Home/>}/><Route path="/users/*" element={<Users/>}/></Routes>';
    for (const file of ["src/portal/App.jsx", "src/portal/App.tsx", "src/portal/app.js"])
      expectLines(
        file,
        ["-", jsx],
        ["-", 'app.get("/api/live", live);'],
        ["-", 'app.get("/api/ready", ready);'],
        ["C", "// a comment"],
      );
    expectLines(
      "src/portal/App.tsx",
      ["-", "const w = {a: 1}.a"],
      ["-", "const h = {b: 2}/2; const p = '/api/*';"],
      ["-", 'app.get("/api/live", live);'],
      ["C", "// a comment"],
    );
    for (const file of ["src/portal/count.js", "src/portal/count.ts"])
      expectLines(
        file,
        ["-", 'let x = i++ / 2; const p = "/api/*";'],
        ["-", 'app.get("/api/live", live);'],
        ["-", 'let y = j-- / 2; const q = "/api/*";'],
        ["-", 'app.get("/api/ready", ready);'],
        // still a regex after `}` in a script, and after `+` alone
        ["-", "if (ok) { done() } /\\/*$/.test(s);"],
        ["-", 'const z = a + /\\/*/.source; app.get("/api/balances", balances);'],
        ["C", "// a comment"],
      );
  });

  it("reads a Dart raw string with no escapes", () => {
    expectLines(
      "lib/ledger.dart",
      ["-", "final a = r'C:\\ledger\\'; final b = '/*';"],
      ["-", "router.get('/api/live', live);"],
      ["-", 'final c = r"\\"; final d = "/*";'],
      ["-", "router.get('/api/ready', ready);"],
      ["-", "final e = r'''"],
      ["-", "  \\'''; final f = '/*';"],
      ["-", "router.get('/api/balances', balances);"],
      ["C", "// a comment"],
    );
  });

  it("reads a leading `*` as a doc block's only inside a block, in a file read whole", () => {
    expectLines(
      "src/portal/sum.ts",
      ["-", "const total = a"],
      ["-", '  * b; app.get("/api/live", live);'],
      ["-", "class Ledger {"],
      ["-", "  * gen () {"],
      ["-", "    yield 1;"],
      ["-", "  }"],
      ["-", "}"],
      ["C", "/**"],
      ["C", " * A ledger."],
      ["C", " */"],
    );
    expectLines(
      "ledger.go",
      ["-", "total := a"],
      ["-", "  * b"],
      ["-", 'http.HandleFunc("/api/live", live)'],
    );
    // a line alone, with no file around it, is still read as a doc block's line
    expect(isCommentLine(" * A ledger.", "src/portal/sum.ts")).toBe(true);
  });
});
