import { cp, mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { Api, QuestionDraft, raiseQuestions, readQuestion } from "@maycombhq/core";
import { startServer, type RunningServer } from "@maycombhq/server";
import { main } from "../src/main.js";
import { uiQuestionRoutes } from "../src/ui-api-questions.js";

/**
 * The assistant proposes, a person confirms (ADR 0144, Q5): atticus questions proposed checks
 * every proposal; list and show show only the ones that check; --accept-proposal (or the app's
 * Accept) makes it the person's answer. Fixtures: fixtures/question-proposals. No network.
 */

const FIX = join(dirname(fileURLToPath(import.meta.url)), "../../../fixtures/question-proposals");
const AT = "2026-10-31T12:00:00.000Z";

async function estate(proposal?: string) {
  const root = await mkdtemp(join(tmpdir(), "atticus-proposals-cli-"));
  await mkdir(join(root, "org-pack"), { recursive: true });
  await cp(join(FIX, "workspace"), join(root, "workspace"), { recursive: true });
  const id = (
    await raiseQuestions(
      root,
      [
        QuestionDraft.parse({
          question: "Is docs/playground.js generated or part of the product?",
          options: [
            { label: "Generated", means: "nobody edits it", changes: "the scan leaves it out" },
            { label: "Product", means: "it ships", changes: "the scan reads it" },
          ],
          evidence: ["docs/playground.js:1"],
        }),
      ],
      {
        step: "scan-survey",
        repo: "forge-notes",
        command: "atticus scan survey forge-notes",
        rerun: "atticus scan survey forge-notes --force",
        at: AT,
      },
    )
  ).raised[0]!.id;
  if (proposal) {
    await mkdir(join(root, "proposals/questions"), { recursive: true });
    await writeFile(
      join(root, "proposals/questions", `${id}.yaml`),
      await readFile(join(FIX, "proposals", `${proposal}.yaml`), "utf8"),
    );
  }
  return { root, id };
}

const run = async (root: string, args: string[]) => {
  const out: string[] = [];
  const err: string[] = [];
  const code = await main(
    ["questions", ...args, "--root", root],
    { out: (l) => out.push(l), err: (l) => err.push(l) },
    { quiet: true },
  );
  return { code, out, err: err.join("\n") };
};

describe("atticus questions proposed, list, show and answer --accept-proposal", () => {
  it("says where proposals go when there are none", async () => {
    const { root } = await estate();
    const r = await run(root, ["proposed"]);
    expect(r.code).toBe(0);
    expect(r.out).toEqual([
      "No proposed answers yet. /atticus-propose writes one per open question to proposals/questions/<question id>.yaml.",
    ]);
  });

  it("checks each proposal, exits 1 while one doesn't, and never shows it", async () => {
    const { root, id } = await estate("bad-quote");
    const r = await run(root, ["proposed"]);
    expect(r.code).toBe(1);
    expect(r.out).toEqual([
      `${id}  doesn't check, so nobody sees it (proposals/questions/${id}.yaml):`,
      '  docs/playground.js:2 doesn\'t say "Generated by the docs build".',
      "1 proposal doesn't check: fix each citation from the file's line, or remove the proposal.",
    ]);
    const list = await run(root, ["list"]);
    expect(list.out.join("\n")).not.toContain("Proposed by");
    const show = await run(root, ["show", id]);
    expect(show.out.join("\n")).toContain("doesn't check, so it isn't shown");
    expect((await run(root, ["answer", id, "--accept-proposal", "--by", "pat"])).code).toBe(2);
    expect((await readQuestion(root, id))?.state).toBe("open");
  });

  it("shows a checked proposal with its citations, and a person's acceptance is their answer", async () => {
    const { root, id } = await estate("good");
    expect((await run(root, ["proposed"])).code).toBe(0);
    const list = await run(root, ["list"]);
    expect(list.out).toContain(
      "  Proposed by claude-code (not answered yet): option 1, Generated. The file says it is generated by the docs build, and build.sh writes it on every release.",
    );
    expect(list.out).toContain(
      '    Cites forge-notes docs/playground.js:1: "Generated by the docs build: do not edit." (checked: it is on that line)',
    );
    expect(list.out).toContain(
      `  Accept it as your answer: atticus questions answer ${id} --accept-proposal`,
    );
    const both = await run(root, ["answer", id, "--accept-proposal", "--option", "1"]);
    expect(both.code).toBe(2);
    const r = await run(root, ["answer", id, "--accept-proposal", "--by", "pat"]);
    expect(r.err).toBe("");
    expect(r.code).toBe(0);
    expect(r.out).toContain(
      "It was the assistant's proposal; you accepted it, so it is recorded as answered by pat.",
    );
    expect((await readQuestion(root, id))?.answer).toMatchObject({ option: 1, by: "pat" });
  });
});

describe("the Questions API: a proposal and Accept (ADR 0144)", () => {
  let srv: RunningServer;
  let id: string;
  beforeAll(async () => {
    const e = await estate("good");
    id = e.id;
    srv = await startServer({
      root: e.root,
      port: 0,
      user: "priya.nair",
      extend: (r, ctx) => uiQuestionRoutes(r, ctx),
    });
  });
  afterAll(() => srv?.close());
  const call = async (method: string, path: string, body?: unknown) => {
    const r = await fetch(srv.url + path, {
      method,
      headers: { "X-Atticus-Token": srv.token, "Content-Type": "application/json" },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    return { status: r.status, body: (await r.json()) as unknown };
  };

  it("lists the checked proposal beside the question, and Accept records the person's answer", async () => {
    const list = Api.QuestionList.parse((await call("GET", "/api/questions")).body);
    expect(list.about?.[id]?.proposal).toMatchObject({
      answer: { option: 1 },
      by: "claude-code",
      file: `proposals/questions/${id}.yaml`,
    });
    const r = await call("POST", `/api/questions/${id}/answer`, { acceptProposal: true });
    expect(r.status).toBe(200);
    expect(Api.AnsweredQuestion.parse(r.body).question.answer).toMatchObject({
      option: 1,
      by: "priya.nair",
    });
    const after = Api.QuestionList.parse((await call("GET", "/api/questions")).body);
    expect(after.about?.[id]?.proposal).toBeUndefined();
  });
});
