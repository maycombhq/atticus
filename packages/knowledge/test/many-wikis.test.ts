describe("syncing 12 sources", () => {
  it("skips restricted pages and a page mirrored in another wiki, path and reason only", async () => {
    const root = await estate();
    const { sync: s } = await sync(root);
    const skipped = s.skipped.map((x) => `${x.source} ${x.path}: ${x.reason}`);
    expect(skipped).toContainEqual(
      expect.stringMatching(
        /^security-standards wikis\/security-standards\/incident\/pen-test-findings-2026\.md: under view restrictions/,
      ),
    );
    expect(skipped).toContainEqual(
      expect.stringMatching(/^payments-team .*Fraud-thresholds\.html: under view restrictions/),
    );
    expect(skipped).toContain(
      "web-team wikis/web-team/copied/logging-standard.md: the same page as ea-standards/Standards/Logging-Standard.md, which reads it",
    );
    // Nothing of a restricted page reaches a snapshot.
    for (const id of ["security-standards", "payments-team"]) {
      const snap = await readSnapshot(root, id);
      for (const p of snap!.pages) expect(p.text).not.toMatch(/did not check|fraud desk/);
    }
    const sec = await readSnapshot(root, "security-standards");
    expect(sec!.manifest.skipped).toContainEqual({
      page: "wikis/security-standards/incident/pen-test-findings-2026.md",
      reason: expect.stringMatching(/under view restrictions/),
    });
  });

  it("reads a restricted page when the source says the metarepo's audience may", async () => {
    const root = await estate({
      sources: (t) =>
        t.replace(
          "    authority: standard\n    reviewMonths: 18\n    tags: { kinds: [security-standard] }",
          "    authority: standard\n    reviewMonths: 18\n    readRestricted: true\n    tags: { kinds: [security-standard] }",
        ),
    });
    const { sync: s } = await sync(root);
    expect(s.pages.map((p) => p.pagePath)).toContain("incident/pen-test-findings-2026.md");
  });

  it("copies only the pages that changed into a later snapshot, pointing at the rest", async () => {
    const root = await estate();
    await sync(root, "2026-10-20T08:00:00Z");
    const page = join(root, "wikis/orders-team/runbooks/replay-a-failed-refund.md");
    await writeFile(
      page,
      (await readFile(page, "utf8")).replace("by its refund id", "by refund id"),
    );
    await sync(root, "2026-10-21T08:00:00Z");
    expect(await snapshotDates(root, "orders-team")).toEqual(["2026-10-21", "2026-10-20"]);
    const dir = join(root, "knowledge/snapshots/orders-team/2026-10-21");
    const files: string[] = [];
    for (const e of await readdir(dir, { recursive: true, withFileTypes: true }))
      if (e.isFile()) files.push(e.name);
    expect(files.sort()).toEqual(["replay-a-failed-refund.md", "snapshot.yaml"]);
    const snap = (await readSnapshot(root, "orders-team"))!;
    expect(snap.pages).toHaveLength(4);
    const kept = snap.manifest.pages.find((p) => p.page === "events/order-events-v2.md")!;
    expect(kept.in).toBe("2026-10-20");
    const v2 = snap.pages.find((p) => p.pagePath === "events/order-events-v2.md")!;
    expect(v2.path).toBe("knowledge/snapshots/orders-team/2026-10-20/events/order-events-v2.md");
    expect(v2.text).toContain("as JSON, after the order is saved");
    const changed = snap.pages.find((p) => p.pagePath === "runbooks/replay-a-failed-refund.md")!;
    expect(changed.path).toBe(
      "knowledge/snapshots/orders-team/2026-10-21/runbooks/replay-a-failed-refund.md",
    );
    // A source nothing changed in gets a snapshot that copies nothing.
    const web = (await readSnapshot(root, "web-framework"))!;
    expect(web.manifest.date).toBe("2026-10-21");
    expect(web.manifest.pages.every((p) => p.in === "2026-10-20")).toBe(true);
  });
});

describe("a page's standing", () => {
  it("is the source's authority, a page override, the page's status, and a review age", async () => {
    const root = await estate();
    await sync(root);
    const settings = await readSourceSettings(root);
    const at = async (src: string, page: string) => {
      const snap = (await readSnapshot(root, src))!;
      return pageStandingOf(
        snap.pages.find((p) => p.pagePath === page)!,
        settings,
        NOW,
      );
    };
    expect(await at("ea-standards", "Standards/Idempotency-Keys.md")).toMatchObject({
      authority: "standard",
      status: "current",
      outOfDate: { since: "2023-01-10", months: 18 },
    });
    expect(await at("ea-standards", "Drafts/Idempotency-Keys-v2-DRAFT.md")).toMatchObject({
      authority: "reference",
    });
    expect(await at("orders-team", "events/order-events-v1.md")).toMatchObject({
      authority: "team",
      status: "deprecated",
    });
    expect(await at("orders-team", "events/order-events-v2.md")).toMatchObject({
      status: "current",
    });
    expect(settings.get("gcp-platform")?.appliesTo).toEqual({
      platforms: ["gcp"],
      newComponents: true,
    });
  });
});

describe("pages that disagree, across sources", () => {
  const idem: KnowledgeConflict = {
    about: ["idempotency-keys"],
    pages: [
      { source: "ea-standards", page: "Standards/Idempotency-Keys.md" },
      { source: "payments-team", page: "SitePages/Idempotency.md" },
    ],
    says: [
      "The service keeps each idempotency key for 24 hours.",
      "forge-payments keeps each idempotency key for 72 hours, because the card network retries a refund for up to three days.",
    ],
    summary: "how long an idempotency key is kept",
    foundBy: "ai",
    owner: {
      source: "payments-team",
      page: "SitePages/Idempotency.md",
      signal: "last-edited",
      detail:
        "SitePages/Idempotency.md was last edited 2026-08-20, after Standards/Idempotency-Keys.md (2023-01-10)",
    },
  };
  const tls: KnowledgeConflict = {
    about: ["internal-tls"],
    pages: [
      { source: "security-standards", page: "tls/internal-calls-tls.md" },
      { source: "stock-team", page: "warehouse/legacy-warehouse-link.md" },
    ],
    says: [
      "A service refuses a connection that offers only TLS 1.2 or older.",
      "forge-stock calls the warehouse over TLS 1.2 with mutual authentication until the warehouse is replaced.",
    ],
    summary: "the TLS version of an internal call",
    foundBy: "ai",
  };

  it("suggests the more authoritative page, says a stale standard may be out of date, and asks", async () => {
    const root = await estate();
    await sync(root);
    const [v] = await readConflicts(root, { conflicts: [idem], questions: [], now: NOW });
    expect(v!.suggested).toMatchObject({
      source: "ea-standards",
      page: "Standards/Idempotency-Keys.md",
      signal: "authority",
    });
    expect(v!.suggested!.detail).toMatch(/standard.*team/);
    expect(v!.suggested!.detail).toMatch(/may be out of date: last updated 2023-01-10/);
    // A person still decides: nothing is applied.
    expect(v!.applies).toEqual([]);
    expect(v!.decided).toBeUndefined();
    const q = await conflictDraft(root, idem, { items: [], now: NOW });
    expect(q.question).toMatch(
      /Suggested: ea-standards\/Standards\/Idempotency-Keys\.md, by authority .*a suggestion only/,
    );
    expect(q.options.map((o) => o.label)).toEqual([
      "ea-standards/Standards/Idempotency-Keys.md applies",
      "payments-team/SitePages/Idempotency.md applies",
      "Both, in different cases",
    ]);
  });

  it("suggests an approved exception over the standard it names, within its scope", async () => {
    const root = await estate();
    await sync(root);
    const [v] = await readConflicts(root, { conflicts: [tls], questions: [], now: NOW });
    expect(v!.suggested).toMatchObject({
      source: "stock-team",
      page: "warehouse/legacy-warehouse-link.md",
      signal: "exception",
    });
    expect(v!.suggested!.detail).toMatch(/WVR-2291/);
    expect(v!.suggested!.detail).toMatch(
      /an approved exception to security-standards\/tls\/internal-calls-tls\.md/,
    );
    expect(v!.suggested!.detail).toMatch(/within its scope \(components forge-stock\)/);
    expect(v!.suggested!.scope).toEqual({ components: ["forge-stock"] });
    expect(v!.suggested!.otherwise).toMatchObject({
      source: "security-standards",
      page: "tls/internal-calls-tls.md",
      signal: "authority",
    });
    expect(v!.applies).toEqual([]);
  });
});

describe("the cost of a scan, before it runs", () => {
  it("counts each source's pages to read, their tokens and the model calls, within its cap", async () => {
    const root = await estate({
      sources: (t) =>
        t.replace("    authority: reference\n", "    authority: reference\n    maxPages: 1\n"),
    });
    await sync(root);
    const op = await pack(root);
    const e = await estimateScan(root, { orgPack: op, batchTokens: 2000 });
    const ea = e.sources.find((s) => s.source === "ea-standards")!;
    expect(ea.pages).toBe(12);
    expect(ea.toRead).toBe(12);
    expect(ea.tokens).toBeGreaterThan(0);
    const gl = e.sources.find((s) => s.source === "glossary-reference")!;
    expect(gl).toMatchObject({ pages: 1, toRead: 1, cap: 1 });
    expect(e.total.pages).toBe(e.sources.reduce((n, s) => n + s.pages, 0));
    expect(e.total.calls).toBeGreaterThanOrEqual(Math.ceil(e.total.tokens / 2000));
    expect(e.notSynced).toEqual([]);
  });
});

describe("standards become checks a person accepts", () => {
  it("proposes each rule of a confirmed standard from a standard source; accepting writes C3 rules", async () => {
    const root = await estate();
    await sync(root);
    // Two standards read by the scan: the logging standard (confirmed by a person) and the
    // error format (not yet), and a team's conventions (confirmed, but not a standard source).
    const item = (id: string, source: string, page: string, rules: string[]) => ({
      kind: "Pattern",
      schemaVersion: 2,
      id,
      status: "current",
      confidence: "inferred",
      evidence: [
        {
          source: "document",
          path: `knowledge/snapshots/${source}/2026-10-20/${page}`,
          line: 1,
          side: "document",
        },
      ],
      code: id,
      name: id,
      patternKind: "standard",
      patternStatus: "to-review",
      rules,
      tags: [],
      quote: { source, page, section: "S", text: rules[0], snapshot: "2026-10-20", line: 1 },
    });
    for (const i of [
      item("structured-logging", "ea-standards", "Standards/Logging-Standard.md", [
        "A service writes every log line as one JSON object with the fields timestamp, level, service, traceId and message.",
        "A log line never carries a card number, a password or a token.",
      ]),
      item("error-response-format", "ea-standards", "Standards/Error-Response-Format.md", [
        "Every REST endpoint answers an error with an application/problem+json body.",
      ]),
      item("payments-api-conventions", "payments-team", "SitePages/Payments-API-conventions.md", [
        "A refund request carries the amount in minor units and the currency, never a decimal amount.",
      ]),
    ]) {
      const r = parseRecord(i);
      if (!r.ok) throw new Error(JSON.stringify(r.issues));
      const f = join(root, "knowledge/items", recordPath(r.record));
      await mkdir(dirname(f), { recursive: true });
      await writeFile(f, serializeRecord(r.record));
      if (i.id !== "error-response-format") {
        const v = reviewItem(r.record as KnowledgeRecord, {
          verdict: "verified",
          by: "ana",
          at: "2026-10-19T10:00:00Z",
        });
        if ("error" in v) throw new Error(v.error);
        await writeReview(root, v.review);
      }
    }
    const d = await draftStandardChecks(root, { now: new Date(NOW) });
    expect(d.proposals.map((p) => p.rule.id)).toEqual([
      "std-structured-logging-1",
      "std-structured-logging-2",
    ]);
    expect(d.proposals[0]).toMatchObject({
      from: "structured-logging",
      page: "ea-standards/Standards/Logging-Standard.md",
      verifiedBy: "ana",
      rule: {
        layer: "org",
        severity: "blocking",
        waivable: true,
        check: { type: "ai" },
        source: "ea-standards/Standards/Logging-Standard.md (knowledge item structured-logging)",
      },
    });
    expect(d.left).toEqual([
      { item: "error-response-format", why: "no person has confirmed it yet" },
      { item: "payments-api-conventions", why: "payments-team is a team source, not a standard" },
    ]);
    // Nothing is enforced until a person accepts: the org pack has no checklist yet.
    expect((await pack(root)).checklists ?? []).toEqual([]);
    const a = await acceptStandardChecks(root, { only: ["std-structured-logging-2"] });
    expect(a).toMatchObject({ added: ["std-structured-logging-2"], left: 1 });
    const file = parse(await readFile(join(root, "org-pack/checklists/standards.yaml"), "utf8"));
    expect(ChecklistPack.safeParse(file).success).toBe(true);
    expect(file.rules.map((r: { id: string }) => r.id)).toEqual(["std-structured-logging-2"]);
    expect(
      Sources.safeParse(parse(await readFile(join(root, "org-pack/sources.yaml"), "utf8"))).success,
    ).toBe(true);
  });
});
