/**
 * Many wikis (ADR 0130): an organisation with a dozen wikis, read from exports when there is no
 * API, each with how much its word counts and where it applies. The invented Forge shop's 12
 * sources (fixtures/many-wikis): an Enterprise Architecture Confluence space export, a
 * SharePoint team site export, and Markdown folders.
 */

const FIX = join(HERE, "../../../fixtures/many-wikis");
const NOW = "2026-10-20T08:00:00Z";

/** A metarepo with the 12 sources' planted pages under wikis/, and sources.yaml as given. */
async function estate(o: { sources?: (text: string) => string } = {}): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "atticus-many-wikis-"));
  await mkdir(join(root, "org-pack"), { recursive: true });
  const text = await readFile(join(FIX, "org-pack/sources.yaml"), "utf8");
  await writeFile(join(root, "org-pack/sources.yaml"), o.sources ? o.sources(text) : text);
  await cp(join(FIX, "sources"), join(root, "wikis"), { recursive: true });
  return root;
}

async function pack(root: string): Promise<OrgPack> {
  const op = await loadOrgPack(join(root, "org-pack"));
  if (op.problems.length) throw new Error(JSON.stringify(op.problems));
  return op;
}

async function sync(root: string, now = NOW) {
  const op = await pack(root);
  const s = await syncSources({ root, orgPack: op, now });
  await writeSnapshots({ root, orgPack: op, sync: s, takenAt: now });
  return { op, sync: s };
}

const source = (op: OrgPack, id: string) => op.sources.wikis.find((w) => w.id === id)!;

describe("a Confluence space export as a source", () => {
  it("reads every page with its place in the space, last edit, author and labels", async () => {
    const root = await estate();
    const op = await pack(root);
    const pages = await confluenceExportAdapter.pages(source(op, "ea-standards"), {
      root,
      orgPackDir: join(root, "org-pack"),
    });
    const paths = pages.map((p) => p.pagePath).sort();
    expect(paths).toEqual([
      "Drafts.md",
      "Drafts/Idempotency-Keys-v2-DRAFT.md",
      "Meeting-notes.md",
      "Meeting-notes/2026-09-12-Architecture-Review-Board.md",
      "Principles.md",
      "Principles/Event-Driven-Architecture-Principles.md",
      "Standards.md",
      "Standards/API-Design-Standard.md",
      "Standards/Database-Schema-Changes.md",
      "Standards/Error-Response-Format.md",
      "Standards/Idempotency-Keys.md",
      "Standards/Logging-Standard.md",
    ]);
    const idem = pages.find((p) => p.pagePath === "Standards/Idempotency-Keys.md")!;
    expect(idem.updatedAt).toBe("2023-01-10");
    expect(idem.path).toBe("wikis/ea-standards/EA/Idempotency-Keys_65603.html");
    const fm = parse(idem.content.split("---")[1]!);
    expect(fm).toMatchObject({
      title: "Idempotency Keys",
      author: "Ana Ruiz",
      updated: "2023-01-10",
      labels: ["standard", "payments"],
      space: "Enterprise Architecture",
    });
    const body = idem.content.split("---").slice(2).join("---");
    expect(body).toContain("# Idempotency Keys\n");
    expect(body).toContain("## Keeping the key\n");
    expect(body).toContain("- The service keeps each idempotency key for 24 hours.\n");
    // The export's chrome (breadcrumbs, the metadata line, labels, footer) is not page text.
    expect(body).not.toMatch(/Created by|Document generated by|breadcrumbs|labels\//);
  });

  it("turns HTML into Markdown: headings, paragraphs, lists, entities; scripts and styles out", () => {
    expect(
      htmlToMarkdown(
        `<h2>A &amp; B</h2><p>One <b>two</b><br/>three.</p><ol><li>First</li><li>Second</li></ol>` +
          `<script>alert(1)</script><style>p{}</style><blockquote><p>Deprecated: old.</p></blockquote>`,
      ),
    ).toBe("## A & B\n\nOne two\nthree.\n\n1. First\n2. Second\n\n> Deprecated: old.\n");
  });
});

