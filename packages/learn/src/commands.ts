/** The command entry a text names: the longest command name it starts with. */
export function commandNamed(text: string): CommandHelp | undefined {
  const words = text
    .trim()
    .replace(/^atticus\s+/, "")
    .split(/\s+/)
    .filter((w) => w && !w.startsWith("-"));
  for (let n = Math.min(words.length, 3); n > 0; n--) {
    const name = words.slice(0, n).join(" ");
    const hit = COMMANDS.find((c) => c.name === name);
    if (hit) return hit;
  }
  return undefined;
}
