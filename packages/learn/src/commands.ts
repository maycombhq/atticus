/**
 * Every Atticus command in plain words, for `atticus explain <command>`, the lessons and the
 * M4 tours. One entry per command: what it does, who usually runs it, what it changes, and
 * whether it needs a person's approval. Kept as data next to the lessons; when a command is
 * added to the CLI, add it here too (the CLI tests check that every lesson command is here).
 */

export interface CommandHelp {
  /** The command words after `atticus`, e.g. "change handoff". */
  name: string;
  usage: string;
  /** What it does, in one or two plain sentences. */
  what: string;
  /** Roles that usually run it. */
  who: string[];
  /** What it changes: "nothing" for read-only commands. */
  changes: string;
  /** True when it writes to a shared system and so asks for a person's approval. */
  approval?: boolean;
  related?: string[];
}

