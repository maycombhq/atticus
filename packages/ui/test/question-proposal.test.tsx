import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { COPY } from "../src/copy.js";
import { aboutWords, QuestionDetail, type QuestionView } from "../src/screens/Questions.js";

/** The Questions page shows the assistant's checked proposal, with Accept (ADR 0144, Q5). */

const P = COPY.questions.proposal;
const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/'/g, "&#x27;");

const question: QuestionView = {
  schemaVersion: 2,
  id: "q-a4a06bcb15a5",
  askedBy: {
    step: "scan-survey",
    command: "atticus scan survey forge-notes",
    at: "2026-10-31T12:00:00.000Z",
  },
  repo: "forge-notes",
  question: "Is docs/playground.js generated or part of the product?",
  options: [
    { label: "Generated", means: "nobody edits it", changes: "the scan leaves it out" },
    { label: "Product", means: "it ships", changes: "the scan reads it" },
  ],
  evidence: ["docs/playground.js:1"],
  scope: { level: "repo", id: "forge-notes" },
  state: "open",
  rerun: "atticus scan survey forge-notes --force",
};

const proposal = {
  answer: { option: 1 },
  why: "The file says it is generated by the docs build.",
  cites: [{ file: "docs/playground.js", line: 1, quote: "Generated by the docs build" }],
  by: "claude-code",
  at: "2026-10-31T12:00:00.000Z",
  file: "proposals/questions/q-a4a06bcb15a5.yaml",
};

describe("a proposed answer on the Questions page (ADR 0144)", () => {
  it("shows the proposal as not yet an answer, with its checked lines and an Accept button", () => {
    const out = renderToStaticMarkup(
      <QuestionDetail question={question} proposal={proposal} onAnswered={() => {}} />,
    );
    expect(out).toContain(esc(P.notYet("claude-code")));
    expect(out).toContain(esc(P.option(1, "Generated")));
    expect(out).toContain("forge-notes docs/playground.js:1");
    expect(out).toContain(`<button type="button" class="btn primary">${P.accept}</button>`);
    expect(out).toContain(P.command("q-a4a06bcb15a5"));
    // The person can still answer it themselves.
    expect(out).toContain('type="submit"');
  });

  it("shows no proposal without one, and the list says one is proposed", () => {
    const out = renderToStaticMarkup(<QuestionDetail question={question} onAnswered={() => {}} />);
    expect(out).not.toContain(P.title);
    expect(aboutWords({ restsOn: [], joins: 0, owner: { team: "team-web" }, proposal })).toContain(
      P.listed,
    );
  });
});
