/**
 * Pipeline snippets that run the drift check in a code repo's pipeline: GitHub Actions,
 * Azure Pipelines, GitLab CI and Jenkins. Plain templates (nothing is fetched to make them);
 * the pipeline checks out the metarepo beside the code, runs `atticus ci drift`, publishes the
 * JUnit XML and keeps the JSON report. The metarepo location and the CLI version are pipeline
 * variables, so the same snippet works for every repo of an organisation.
 */

export const SNIPPET_KINDS = ["github", "azure", "gitlab", "jenkins"] as const;
export type SnippetKind = (typeof SNIPPET_KINDS)[number];

export interface Snippet {
  kind: SnippetKind;
  /** Where the file usually lives in the code repo. */
  path: string;
  content: string;
}

const CLI = "npx --yes @maycombhq/cli@${ATTICUS_VERSION:-latest}";
const ARGS = "--json atticus-drift.json --junit atticus-drift.xml";

const GITHUB = `# Generated by Atticus (atticus ci snippet github): the catalog drift check.
# Set the repository variable ATTICUS_METAREPO (owner/name of the metarepo) and, for a private
# metarepo, the secret ATTICUS_METAREPO_TOKEN (read-only). ATTICUS_VERSION pins the CLI.
name: atticus-drift
on:
  pull_request:
  push:
    branches: [main]
jobs:
  drift:
    runs-on: ubuntu-latest
    env:
      ATTICUS_VERSION: \${{ vars.ATTICUS_VERSION || 'latest' }}
    steps:
      - uses: actions/checkout@v4
        with:
          path: repo
      - name: Check out the metarepo
        uses: actions/checkout@v4
        with:
          repository: \${{ vars.ATTICUS_METAREPO }}
          token: \${{ secrets.ATTICUS_METAREPO_TOKEN || github.token }}
          path: atticus-metarepo
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Atticus drift check
        run: ${CLI} ci drift repo --catalog atticus-metarepo --repo \${{ github.event.repository.name }} ${ARGS} --summary "$GITHUB_STEP_SUMMARY"
      - name: Keep the drift report
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: atticus-drift
          path: |
            atticus-drift.json
            atticus-drift.xml
`;

const AZURE = `# Generated by Atticus (atticus ci snippet azure): the catalog drift check.
# Declare the metarepo as a repository resource named atticus_metarepo; ATTICUS_VERSION pins the CLI.
resources:
  repositories:
    - repository: atticus_metarepo
      type: git
      name: $(ATTICUS_METAREPO)

trigger:
  - main
pr:
  - "*"

pool:
  vmImage: ubuntu-latest

steps:
  - checkout: self
    path: s/repo
  - checkout: atticus_metarepo
    path: s/atticus-metarepo
  - task: NodeTool@0
    inputs:
      versionSpec: "22.x"
  - script: ${CLI} ci drift repo --catalog atticus-metarepo --repo $(Build.Repository.Name) ${ARGS} --summary atticus-drift.md
    displayName: Atticus drift check
    workingDirectory: $(Pipeline.Workspace)/s
  - task: PublishTestResults@2
    condition: always()
    inputs:
      testResultsFormat: JUnit
      testResultsFiles: $(Pipeline.Workspace)/s/atticus-drift.xml
      testRunTitle: Atticus drift
  - task: PublishBuildArtifacts@1
    condition: always()
    inputs:
      PathtoPublish: $(Pipeline.Workspace)/s/atticus-drift.json
      ArtifactName: atticus-drift
`;

const GITLAB = `# Generated by Atticus (atticus ci snippet gitlab): the catalog drift check.
# Set the CI/CD variable ATTICUS_METAREPO_URL (an https clone URL the job token can read);
# ATTICUS_VERSION pins the CLI.
atticus-drift:
  image: node:22
  stage: test
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
    - if: $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH
  script:
    - git clone --depth 1 "$ATTICUS_METAREPO_URL" ../atticus-metarepo
    - ${CLI} ci drift . --catalog ../atticus-metarepo --repo "$CI_PROJECT_NAME" ${ARGS} --summary atticus-drift.md
  artifacts:
    when: always
    paths:
      - atticus-drift.json
      - atticus-drift.md
    reports:
      junit: atticus-drift.xml
`;

const JENKINS = `// Generated by Atticus (atticus ci snippet jenkins): the catalog drift check.
// Set ATTICUS_METAREPO_URL and, for a private metarepo, the credentials id
// ATTICUS_METAREPO_CREDENTIALS; ATTICUS_VERSION pins the CLI.
pipeline {
  agent any
  stages {
    stage('Atticus drift check') {
      steps {
        dir('repo') {
          checkout scm
        }
        dir('atticus-metarepo') {
          git url: env.ATTICUS_METAREPO_URL, credentialsId: env.ATTICUS_METAREPO_CREDENTIALS
        }
        sh '${CLI} ci drift repo --catalog atticus-metarepo --repo "$(basename "$GIT_URL" .git)" ${ARGS} --summary atticus-drift.md'
      }
    }
  }
  post {
    always {
      junit allowEmptyResults: false, testResults: 'atticus-drift.xml'
      archiveArtifacts artifacts: 'atticus-drift.json,atticus-drift.md', allowEmptyArchive: true
    }
  }
}
`;

const SNIPPETS: Record<SnippetKind, Snippet> = {
  github: { kind: "github", path: ".github/workflows/atticus-drift.yml", content: GITHUB },
  azure: { kind: "azure", path: "azure-pipelines.atticus-drift.yml", content: AZURE },
  gitlab: { kind: "gitlab", path: ".gitlab-ci.atticus-drift.yml", content: GITLAB },
  jenkins: { kind: "jenkins", path: "Jenkinsfile.atticus-drift", content: JENKINS },
};

/** The snippet for one CI system; undefined for an unknown kind. */
export function pipelineSnippet(kind: string): Snippet | undefined {
  const k = kind.toLowerCase().replace(/[-_ ]?(actions|pipelines|ci)$/, "") as SnippetKind;
  return (SNIPPETS as Record<string, Snippet>)[k];
}
