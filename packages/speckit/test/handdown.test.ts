import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import { readSpecKitFeatures } from "@maycombhq/extractors";
import { fsRepo } from "@maycombhq/sdk";
import { writeFileAtomic } from "@maycombhq/changes";
import { handDown, SPEC_KIT_VERSION, SpecKitError } from "../src/index.js";
import { CHANGE, git, read, sh, SPECKIT, speckitRoot, worktree } from "./helpers.js";

const EXPECTED = join(SPECKIT, "expected/handdown/forge-ledger");
const T = 120_000;

describe("hand-down (Spec Kit engine)", () => {
  it(
    "writes specs/<task>/ in the repo's change worktree, as the hand-written golden files say",
    async () => {
      const { root } = await speckitRoot();
      const r = await handDown(root, CHANGE, "1.2", { git });
      expect(r).toMatchObject({
        change: CHANGE,
        task: "1.2",
        repo: "forge-ledger",
        engine: "speckit",
        worktree: "workspace/.worktrees/add-transfer-limit/forge-ledger",
        feature: "specs/1.2",
        kept: [],
      });
      const wt = worktree(root, "forge-ledger");
      for (const f of [
        "spec.md",
        "plan.md",
        "tasks.md",
        "data-model.md",
        "checklists/requirements.md",
      ])
        expect(await read(join(wt, "specs/1.2", f)), f).toBe(
          await read(join(EXPECTED, "specs/1.2", f)),
        );
      expect(parse(await read(join(wt, "specs/1.2/contracts/ledger-api.yaml")))).toEqual(
        parse(await read(join(EXPECTED, "specs/1.2/contracts/ledger-api.yaml"))),
      );
      expect(await read(join(wt, ".specify/feature.json"))).toBe(
        await read(join(EXPECTED, "feature.json")),
      );
      expect(r.written).toEqual(
        expect.arrayContaining([
          "specs/1.2/spec.md",
          "specs/1.2/plan.md",
          "specs/1.2/tasks.md",
          "specs/1.2/data-model.md",
          "specs/1.2/contracts/ledger-api.yaml",
          "specs/1.2/checklists/requirements.md",
          ".specify/feature.json",
          ".specify/memory/constitution.md",
        ]),
      );
      // No topics in this repo's part of the design: no AsyncAPI contract.
      expect(existsSync(join(wt, "specs/1.2/contracts/ledger-api-events.yaml"))).toBe(false);
    },
    T,
  );

  it(
    "generates the constitution from the critic's constitution layer, the org rules and the owning team's rules",
    async () => {
      const { root } = await speckitRoot();
      await handDown(root, CHANGE, "1.2", { git });
      const text = await read(
        join(worktree(root, "forge-ledger"), ".specify/memory/constitution.md"),
      );
      const lines = text.split("\n");
      expect(lines[0]).toMatch(
        /^<!-- Generated by Atticus from org-pack checklists and the Atticus constitution\./,
      );
      expect(lines[1]).toBe("# forge-ledger Constitution");
      expect(text).toContain("\n## Core Principles\n");
      expect(text).toContain("\n## Organisation Rules\n");
      expect(text).toContain("\n## Team Rules (team-ledger)\n");
      expect(text).toContain("\n## Governance\n");
      // The 14 active built-in rules (17, one retired with the four questions, and the timeout
      // and rollback checks moved to the starter org rules by the product owner's decisions of
      // 2026-10-24, ADR 0124 Part 4) and the Forge pack's two constitution-layer rules are the
      // core principles.
      const principles = lines.filter((l) => /^### [IVXLC]+\. /.test(l));
      expect(principles).toHaveLength(16);
      expect(principles).toContain("### I. Every interface names an approved integration pattern");
      expect(principles.some((l) => / Calls to vendors go through the gateway$/.test(l))).toBe(
        true,
      );
      expect(text).toContain(
        "Rule `constitution.interface-approved-pattern` (architecture lens, blocking, never waived).",
      );
      expect(text).toContain("### Tests cover every spec scenario");
      expect(text).toContain("### Every behaviour change has a test task before it");
      expect(text).toMatch(/\*\*Version\*\*: 1\.0\.0\+forge\.0\.1\.0 \|/);
    },
    T,
  );

  it(
    "installs Spec Kit's templates, scripts and /speckit.* commands through the skill source, and commits locally",
    async () => {
      const { root, remotes } = await speckitRoot();
      const r = await handDown(root, CHANGE, "1.2", { git });
      const wt = worktree(root, "forge-ledger");
      for (const p of [
        ".specify/templates/plan-template.md",
        ".specify/scripts/bash/check-prerequisites.sh",
        ".claude/commands/speckit.plan.md",
        ".github/prompts/speckit.implement.prompt.md",
        ".claude/skills/forge-migrations/SKILL.md",
        "CLAUDE.md",
      ])
        expect(existsSync(join(wt, p)), p).toBe(true);
      expect(r.assistantFiles.results.length).toBeGreaterThan(20);
      expect(sh(wt, "rev-parse", "--abbrev-ref", "HEAD")).toBe("change/add-transfer-limit");
      expect(sh(wt, "log", "-1", "--format=%s")).toBe(
        "Hand down task 1.2 of add-transfer-limit: Check the limit in the transfer transaction, with tests",
      );
      expect(r.commit).toBe(sh(wt, "rev-parse", "HEAD"));
      expect(sh(wt, "status", "--porcelain")).toBe("");
      // Nothing is pushed: the remote has no change branch.
      expect(sh(remotes["forge-ledger"]!, "branch", "--list", "change/*")).toBe("");
      expect(SPEC_KIT_VERSION).toBe("1.2.1");
    },
    T,
  );

  it(
    "hands down what the speckit extractor reads back as the design's planned records",
    async () => {
      const { root } = await speckitRoot();
      await handDown(root, CHANGE, "1.2", { git });
      const warnings: string[] = [];
      const [f] = await readSpecKitFeatures(
        fsRepo("forge-ledger", worktree(root, "forge-ledger"), "0".repeat(40)),
        {
          component: "ledger-api",
          system: "ledger",
          dialects: [],
          scannedAt: "2026-10-21T09:00:00Z",
          warn: (m) => warnings.push(m),
        },
      );
      expect(warnings).toEqual([]);
      const brief = f!.records
        .filter((r) => r.kind !== "ProcessArtifact")
        .map((r) => {
          const x = r as unknown as Record<string, unknown>;
          return `${r.kind} ${r.status} ${String(x.to ?? x.pathOrTopic ?? x.name)}${x.method ? ` ${String(x.method)}` : ""}${x.via ? ` via ${String(x.via)}` : ""}${x.type ? ` ${String(x.type)}` : ""}`;
        })
        .sort();
      expect(brief).toEqual([
        "Column planned-new account_id bigint",
        "Column planned-new changed_at timestamp",
        "Column planned-new changed_by_email varchar(200)",
        "Column planned-new daily_limit numeric(18,2)",
        "Column planned-new id bigint",
        "Column planned-new new_limit numeric(18,2)",
        "Column planned-new old_limit numeric(18,2)",
        "Endpoint planned-modify /transfers POST",
        "Endpoint planned-new /accounts/{id}/limit GET",
        "Interface planned-new northwind-pay POST via gateway",
        "Interface planned-new risk-engine POST via gateway",
        "Table planned-modify account",
        "Table planned-new limit_change",
      ]);
    },
    T,
  );

  it(
    "keeps files a developer changed on a second hand-down, unless forced",
    async () => {
      const { root } = await speckitRoot();
      await handDown(root, CHANGE, "1.2", { git });
      const again = await handDown(root, CHANGE, "1.2", { git });
      expect(again.written).toEqual([]);
      expect(again.kept).toEqual([]);
      expect(again.commit).toBeUndefined();
      const plan = join(worktree(root, "forge-ledger"), "specs/1.2/plan.md");
      await writeFile(plan, (await read(plan)) + "\nThe developer's own notes.\n");
      const third = await handDown(root, CHANGE, "1.2", { git, commit: false });
      expect(third.kept).toEqual(["specs/1.2/plan.md"]);
      expect(await read(plan)).toContain("The developer's own notes.");
      const forced = await handDown(root, CHANGE, "1.2", { git, force: true, commit: false });
      expect(forced.written).toContain("specs/1.2/plan.md");
      expect(await read(plan)).not.toContain("The developer's own notes.");
    },
    T,
  );
});

describe("hand-down and OpenSpec stores (ADR 0126)", () => {
  const STORES = join(SPECKIT, "../openspec-stores");

  it(
    "adds the metarepo under references: in the repo's openspec/config.yaml only when the org pack turns it on",
    async () => {
      const { root } = await speckitRoot({ repos: ["forge-ledger"] });
      const wt = worktree(root, "forge-ledger");
      const config = join(wt, "openspec/config.yaml");
      await mkdir(join(wt, "openspec"), { recursive: true });
      await writeFile(config, await read(join(STORES, "references/no-references.yaml")));
      await mkdir(join(root, ".openspec-store"), { recursive: true });
      await writeFile(join(root, ".openspec-store/store.yaml"), "version: 1\nid: forge\n");

      // Off by default: the file is the developer's, as it was.
      const off = await handDown(root, CHANGE, "1.2", { git });
      expect(off.written).not.toContain("openspec/config.yaml");
      expect(await read(config)).toBe(await read(join(STORES, "references/no-references.yaml")));

      await writeFile(
        join(root, "org-pack/openspec.yaml"),
        "schemaVersion: 1\nreferenceInRepos: true\n",
      );
      const on = await handDown(root, CHANGE, "1.2", { git });
      expect(on.written).toContain("openspec/config.yaml");
      expect(on.problems).toEqual([]);
      // The metarepo has no origin here, so the reference is the store id alone.
      expect(await read(config)).toBe(
        await read(join(STORES, "references/no-references-expected.yaml")),
      );
      expect(sh(wt, "status", "--porcelain")).toBe("");
      const again = await handDown(root, CHANGE, "1.2", { git });
      expect(again.unchanged).toContain("openspec/config.yaml");
    },
    T,
  );

  it(
    "says why it added no reference when the metarepo isn't a store yet",
    async () => {
      const { root } = await speckitRoot({ repos: ["forge-ledger"] });
      await writeFile(
        join(root, "org-pack/openspec.yaml"),
        "schemaVersion: 1\nreferenceInRepos: true\n",
      );
      const r = await handDown(root, CHANGE, "1.2", { git });
      expect(r.problems).toContain(
        "OpenSpec reference not added to openspec/config.yaml: this metarepo isn't an OpenSpec store yet (no .openspec-store/store.yaml): run atticus upgrade --openspec-store, commit the file, then hand down again",
      );
    },
    T,
  );
});

