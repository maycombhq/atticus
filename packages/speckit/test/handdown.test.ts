describe("hand-down refusals", () => {
  it(
    "refuses an unknown task, a repo with no worktree, and a change whose design isn't approved",
    async () => {
      const { root } = await speckitRoot({ repos: ["forge-ledger"] });
      await expect(handDown(root, CHANGE, "9.9", { git })).rejects.toThrow(
        "There is no task 9.9 in add-transfer-limit's tasks.md. Tasks: 1.1, 1.2, 1.3, 2.1, 2.2.",
      );
      await expect(handDown(root, CHANGE, "2.1", { git })).rejects.toThrow(
        /forge-portal-bff has no worktree for add-transfer-limit yet. Open it first: atticus workspace open add-transfer-limit --repos forge-portal-bff/,
      );
      const file = join(root, "openspec/changes", CHANGE, "change.yaml");
      await writeFileAtomic(
        file,
        (await readFile(file, "utf8"))
          .replace("state: plan", "state: design")
          .replace(
            "  - from: design\n    to: plan\n    at: 2026-10-19T14:00:00Z\n    by: avery\n    pr: 2\n    reason: Approve design merged\n",
            "",
          ),
      );
      const err = await handDown(root, CHANGE, "1.2", { git }).catch((e: unknown) => e);
      expect(err).toBeInstanceOf(SpecKitError);
      expect((err as Error).message).toMatch(
        /is design: a task is handed down only after the design is approved/,
      );
    },
    T,
  );
});
