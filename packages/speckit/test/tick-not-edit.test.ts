import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { editSha } from "@maycombhq/changes";
import { editedByPerson } from "@maycombhq/naysayer";
import { markTaskDone, setTaskDone, type ChangeTask } from "../src/index.js";

/**
 * Review round 50: ticking a task (hand-up's markTaskDone, the Task board's setTaskDone) changes
 * tasks.md, which the stories stage wrote and keeps the hash of. A tick is progress, not a
 * person's edit of the draft: the edit checks hash tasks.md with its boxes aside.
 */
const CHANGE = "add-transfer-limit";
const TASKS = [
  "<!-- Generated by atticus plan stories: tasks from the stories. -->",
  "# Tasks",
  "",
  "## forge-ledger",
  "",
  "- [ ] 1.1 Refuse over-limit transfers (story s1-transfer)",
  "- [ ] 1.2 Say the limit in the error (story s1-transfer)",
  "",
].join("\n");

let root: string;
afterEach(async () => {
  if (root) await rm(root, { recursive: true, force: true });
});

describe("a tick in tasks.md", () => {
  it("is not an edit of the stories stage's draft, by either way of ticking", async () => {
    root = await mkdtemp(join(tmpdir(), "atticus-tick-"));
    const dir = join(root, "openspec", "changes", CHANGE);
    await mkdir(join(dir, "stage"), { recursive: true });
    await writeFile(join(dir, "tasks.md"), TASKS);
    await writeFile(
      join(dir, "stage/stories.yaml"),
      `written:\n  tasks.md: ${editSha("tasks.md", TASKS)}\n`,
    );
    const t: ChangeTask = {
      id: "1.1",
      repo: "forge-ledger",
      title: "",
      stories: [],
      line: 6,
      done: false,
    };
    expect(await markTaskDone(root, CHANGE, t)).toBe(true);
    expect(await setTaskDone(root, CHANGE, "1.2", true)).toBe(true);
    expect(await readFile(join(dir, "tasks.md"), "utf8")).toContain("- [x] 1.2");
    expect(await editedByPerson(dir)).toEqual([]);
    expect(await setTaskDone(root, CHANGE, "1.2", false)).toBe(true);
    expect(await editedByPerson(dir)).toEqual([]);
  });
});
